import { pathToFileURL } from 'node:url';

// Explicit host setup only: rendering never changes security policy or sysctls.
export function renderSandboxAppArmorProfile(homeDir) {
  if (typeof homeDir !== 'string' || !/^\/(?:[A-Za-z0-9_. -]+\/)*[A-Za-z0-9_. -]+$/.test(homeDir)
      || homeDir.split('/').some(part => part === '.' || part === '..')) {
    throw new Error('AppArmor setup requires an absolute home directory without policy metacharacters');
  }
  const stacks = '.happier/dev-targets/*/stack-state/*/cli/tools';
  const binaries = [
    `${stacks}/providers/codex/current/{bin/codex,codex-resources/bwrap}`,
    `.local/share/codex-standalone/*-x86_64-unknown-linux-musl/{bin/codex,codex-resources/bwrap}`,
    `${stacks}/browser-chromium/*/chrome-linux64/chrome`,
    `${stacks}/providers/muse/current/bin/muse-bin-*`,
    `.local/bin/muse-bin-*`,
  ];
  return `# Generated by apps/stack/scripts/utils/dev_targets/apparmor.mjs
abi <abi/4.0>,
include <tunables/global>

profile happier-sandbox-binaries "${homeDir}/{${binaries.join(',')}}" flags=(unconfined) {
  userns,
}
`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  process.stdout.write(renderSandboxAppArmorProfile(process.argv[2]));
}
