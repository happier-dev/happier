import { spawn } from 'node:child_process';
import { appendFile, lstat, readdir, readFile, rename, rm, writeFile } from 'node:fs/promises';
import { basename, dirname, isAbsolute, join, posix, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

import { resolveMutagenRepositoryKey } from './mutagen_project.mjs';
import {
  MUTAGEN_SYNC_LIST_JSON_TEMPLATE,
  resolveDevTargetMutagenRuntime,
} from './mutagen_runtime.mjs';
import { posixQuote } from './remote_commands.mjs';
import { runDevTargetControlProcess } from './sync_project.mjs';

const COMMAND_STATE_PREFIX = 'commands-';

async function pathExists(path) {
  try {
    await lstat(path);
    return true;
  } catch (error) {
    if (error.code === 'ENOENT') return false;
    throw error;
  }
}

// Only a sibling replica created for this checkout name next to the worker's
// executor mirror is a candidate; Stack runtime targets keep their own repository.
function isSiblingReplicaTarget(target, name) {
  return (
    target?.platform === 'posix' &&
    typeof target.ssh === 'string' &&
    typeof target.repoDir === 'string' &&
    typeof target.executorRepoDir === 'string' &&
    posix.isAbsolute(target.repoDir) &&
    posix.basename(target.repoDir) === name &&
    posix.dirname(target.repoDir) === posix.dirname(target.executorRepoDir) &&
    target.repoDir !== target.executorRepoDir
  );
}

// The worker-side producer writes .happier/command-replica.json naming the
// replica root. A directory without that exact owner record is never deleted.
function buildRemoteCommandReplicaRemovalCommand(repoDirs) {
  return [
    'set -u',
    ...repoDirs.map((repoDir) => {
      const dir = posixQuote(repoDir);
      const owner = posixQuote(`"repoDir":${JSON.stringify(repoDir)}`);
      const absent = `[ ! -e ${dir} ] && [ ! -L ${dir} ]`;
      return (
        `if ${absent}; then :; elif grep -qF -- ${owner} ${posixQuote(`${repoDir}/.happier/command-replica.json`)} 2>/dev/null; ` +
        `then rm -rf -- ${dir} || exit 1; else printf '%s\\n' ${posixQuote(`unowned ${repoDir}`)} >&2; fi\n` +
        `if ${absent}; then printf '%s\\n' ${posixQuote(`removed ${repoDir}`)}; fi`
      );
    }),
  ].join('\n');
}

const RETIREMENT_STATE = 'retirement.v1.json';

async function readJson(file) {
  return JSON.parse(await readFile(file, 'utf8').catch(error => {
    if (error.code === 'ENOENT') return 'null';
    throw error;
  }));
}

async function removedRepositorySources(stackDir, executor, runtime) {
  const sources = new Set();
  for (const entry of await readdir(stackDir, { withFileTypes: true })) {
    if (!entry.isDirectory() || !entry.name.startsWith(COMMAND_STATE_PREFIX)) continue;
    const name = entry.name.slice(COMMAND_STATE_PREFIX.length);
    if (name) sources.add(join(dirname(executor), name));
  }
  const repositoriesDir = join(runtime.mutagenDir, 'repositories');
  const projects = await readdir(repositoriesDir, { withFileTypes: true }).catch(error => {
    if (error.code === 'ENOENT') return [];
    throw error;
  });
  for (const entry of projects) {
    if (!entry.isDirectory()) continue;
    const project = await readFile(join(repositoriesDir, entry.name, 'mutagen.yml'), 'utf8').catch(error => {
      if (error.code === 'ENOENT') return '';
      throw error;
    });
    // Read the canonical generator's JSON alpha strings, not arbitrary YAML.
    // A project can repeat its source once per worker; standby projects do not
    // have this generated header and cannot become command-replica candidates.
    if (!project.includes('# Generated by hstack. User configuration lives in dev-targets.json.')) continue;
    let alphas;
    try { alphas = new Set([...project.matchAll(/^    alpha: (.+)$/gm)].map(match => JSON.parse(match[1]))); }
    catch { continue; }
    if (alphas.size !== 1) continue;
    const [sourceDir] = alphas;
    if (typeof sourceDir !== 'string' || !isAbsolute(sourceDir) || /[\0\r\n]/.test(sourceDir)
      || resolveMutagenRepositoryKey(sourceDir) !== entry.name) continue;
    sources.add(resolve(sourceDir));
  }
  const removed = [];
  for (const sourceDir of sources) {
    if (sourceDir !== executor && !(await pathExists(sourceDir))) removed.push({ sourceDir });
  }
  return removed;
}

// `git worktree remove` cannot reach the controller state, the one-way
// Mutagen sessions or the source+dependency replica a sibling dispatch left on
// every worker (about 5 GB each; mac2-linux filled twice, 2026-10-27/29).
// Workers cannot observe the checkout's absence, so the dispatching controller
// retires them. Each pass verifies every worker share, including previously
// completed ones: replicas can reappear while other workers remain pending.
export async function retireRemovedCommandRepositories(
  { stackDir, executorRepoRoot, env = process.env, repositories },
  { runProcess = runDevTargetControlProcess } = {},
) {
  const executor = resolve(executorRepoRoot);
  const runtime = resolveDevTargetMutagenRuntime({ stackBaseDir: stackDir, env });
  // The optional selection is for a manifest-backed, one-off operator cleanup.
  // Automatic dispatch always discovers absent sources through the same body.
  const selected = repositories ?? await removedRepositorySources(stackDir, executor, runtime);
  const removed = [];
  for (const selection of selected) {
    if (typeof selection.sourceDir !== 'string' || !isAbsolute(selection.sourceDir)
      || /[\0\r\n]/.test(selection.sourceDir)) throw new Error('[dev-targets] retirement requires an absolute source');
    const sourceDir = resolve(selection.sourceDir);
    if (sourceDir === executor) throw new Error('[dev-targets] executor repository cannot be retired');
    const name = basename(sourceDir);
    // commands-* belongs only to sibling dispatch. Nested historical scratch
    // sources have project evidence, but do not inherit a sibling's targets.
    const candidateStateDir = dirname(sourceDir) === dirname(executor) ? join(stackDir, `${COMMAND_STATE_PREFIX}${name}`) : null;
    const stateDir = candidateStateDir && await pathExists(candidateStateDir) ? candidateStateDir : null;
    const config = stateDir ? await readJson(join(stateDir, 'dev-targets.json')) : null;
    const doneTargets = new Set();
    removed.push({ name, sourceDir, stateDir, doneTargets, failed: false, sessionIds: selection.sessionIds,
      targets: selection.sessionIds ? [] : (selection.targets ?? config?.targets ?? [])
        .filter(target => isSiblingReplicaTarget(target, name)) });
  }
  if (removed.length === 0) return { retired: [], pending: {}, terminated: [] };

  const listed = await runProcess({ label: '', command: 'mutagen',
    args: ['sync', 'list', '--template', MUTAGEN_SYNC_LIST_JSON_TEMPLATE], env: runtime.env });
  if (listed?.code !== 0) throw new Error('[dev-targets] Mutagen session inventory failed for retired command repositories');
  const sessions = JSON.parse(listed.out || '[]');
  if (!Array.isArray(sessions)) throw new Error('[dev-targets] invalid Mutagen session inventory');
  const ownedSessions = repository => sessions.filter(session => session.alpha?.protocol === 'local'
    && resolve(session.alpha.path ?? '') === repository.sourceDir && session.mode === 'one-way-replica'
    && session.labels?.['io.mutagen.project'] && session.identifier
    && (!repository.sessionIds || repository.sessionIds.includes(session.identifier)));
  // Record exact writers and destinations before either termination or removal.
  await appendFile(join(stackDir, 'command-replica-retirement.manifest.jsonl'), `${JSON.stringify({
    at: new Date().toISOString(), repositories: removed.map(({ sourceDir, targets, sessionIds }) => ({ sourceDir, targets, sessionIds })),
    sessions: removed.flatMap(repository => ownedSessions(repository).map(session => ({
      identifier: session.identifier, sourceDir: repository.sourceDir, beta: { host: session.beta?.host, path: session.beta?.path },
    }))),
  })}\n`);
  const terminated = [];
  const pending = {};
  for (const repository of removed) {
    // Same ownership predicate as the project owner's orphan reconciliation.
    const sourceRuntime = resolveDevTargetMutagenRuntime({ stackBaseDir: stackDir, sourceDir: repository.sourceDir, env });
    for (const session of ownedSessions(repository)) {
      const result = await runProcess({ label: 'sync', command: 'mutagen',
        args: ['sync', 'terminate', session.identifier], env: sourceRuntime.env });
      if (result?.code !== 0) {
        repository.failed = true;
        pending[`sync:${repository.name}`] = (pending[`sync:${repository.name}`] ?? 0) + 1;
      } else terminated.push(session.identifier);
    }
  }

  // One SSH per worker covers every removed sibling it may hold. Stream its
  // removal body: accumulated replicas can exceed the OS argv-string limit.
  const byWorker = new Map();
  for (const repository of removed) {
    if (repository.failed) continue;
    for (const target of repository.targets) {
      const key = `${target.sshConfigFile ?? ''}\0${target.ssh}`;
      if (!byWorker.has(key)) byWorker.set(key, { target, entries: [] });
      byWorker.get(key).entries.push({ repository, target });
    }
  }
  await Promise.all([...byWorker.values()].map(async ({ target, entries }) => {
    const result = await runProcess({ label: `remote:${target.name}`, command: 'ssh', args: [
      ...(target.sshConfigFile ? ['-F', target.sshConfigFile] : []), '-o', 'BatchMode=yes', target.ssh,
      'sh -s',
    ], input: buildRemoteCommandReplicaRemovalCommand(entries.map(entry => entry.target.repoDir)), env });
    const verified = new Set((result?.out ?? '').split('\n'));
    for (const entry of entries) {
      if (result?.code === 0 && verified.has(`removed ${entry.target.repoDir}`)) entry.repository.doneTargets.add(entry.target.name);
      else pending[entry.target.name] = (pending[entry.target.name] ?? 0) + 1;
    }
  }));

  const retired = [];
  for (const repository of removed) {
    if (repository.sessionIds) continue;
    const complete = !repository.failed && repository.targets.every(target => repository.doneTargets.has(target.name));
    if (!complete) {
      if (repository.stateDir) {
        const file = join(repository.stateDir, RETIREMENT_STATE);
        await writeFile(`${file}.${process.pid}.tmp`, `${JSON.stringify({ version: 1, doneTargets: [...repository.doneTargets].sort() })}\n`);
        await rename(`${file}.${process.pid}.tmp`, file);
      }
      continue;
    }
    await rm(join(runtime.mutagenDir, 'repositories', resolveMutagenRepositoryKey(repository.sourceDir)), { recursive: true, force: true });
    if (repository.stateDir) await rm(repository.stateDir, { recursive: true, force: true });
    retired.push(repository.name);
  }
  return { retired, pending, terminated };
}

// Retirement reaches every worker a removed sibling may hold, including ones
// that are down (some target configs wait 180 s to connect). It therefore runs
// detached from the dispatch it was observed in, one pass per Stack at a time.
export function startRemovedCommandRepositoryRetirement({ stackDir, executorRepoRoot, env = process.env }) {
  const child = spawn(process.execPath, [fileURLToPath(import.meta.url), stackDir, executorRepoRoot],
    { detached: true, stdio: 'ignore', env });
  child.on('error', () => {});
  child.unref();
}

function processAlive(pid) {
  try { process.kill(pid, 0); return true; }
  catch (error) { return error.code === 'EPERM'; }
}

async function main([stackDir, executorRepoRoot]) {
  const lock = join(stackDir, 'command-replica-retirement.lock');
  const holder = Number((await readFile(lock, 'utf8').catch(() => '')).trim());
  if (Number.isSafeInteger(holder) && holder > 0 && processAlive(holder)) return;
  await rm(lock, { force: true });
  try { await writeFile(lock, `${process.pid}\n`, { flag: 'wx' }); }
  catch (error) { if (error.code === 'EEXIST') return; throw error; }
  let record = null;
  try {
    const { retired, pending } = await retireRemovedCommandRepositories({ stackDir, executorRepoRoot });
    if (retired.length > 0) record = { retired, pending };
  } catch (error) {
    record = { error: error instanceof Error ? error.message : String(error) };
  } finally {
    await rm(lock, { force: true });
  }
  if (record) await appendFile(join(stackDir, 'command-replica-retirement.log'),
    `${JSON.stringify({ at: new Date().toISOString(), ...record })}\n`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) await main(process.argv.slice(2));
