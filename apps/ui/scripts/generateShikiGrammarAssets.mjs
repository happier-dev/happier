import { createHash } from 'node:crypto';
import { mkdir, readFile, readdir, rename, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { SOURCE_UI_ASSET_OUTPUT_PATHS } from './sourceUiAssetPaths.mjs';

const uiDirectory = fileURLToPath(new URL('..', import.meta.url));
const inventoryRelativePath = SOURCE_UI_ASSET_OUTPUT_PATHS.shiki;

async function writeChanged(path, content) {
    const current = await readFile(path, 'utf8').catch(error => {
        if (error.code !== 'ENOENT') throw error;
        return null;
    });
    if (current === content) return;
    await mkdir(dirname(path), { recursive: true });
    const temporary = `${path}.${process.pid}.tmp`;
    await writeFile(temporary, content);
    await rename(temporary, path);
}

export async function resolveShikiGrammarAssetInputPaths({ uiPackageDir = uiDirectory } = {}) {
    const require = createRequire(join(uiPackageDir, 'package.json'));
    const shikiPackagePath = require.resolve('shiki/package.json');
    const grammarDirectory = dirname(createRequire(shikiPackagePath).resolve('@shikijs/langs/typescript'));
    const shikiDirectory = dirname(require.resolve('shiki/langs'));
    return [
        fileURLToPath(import.meta.url),
        fileURLToPath(new URL('./sourceUiAssetPaths.mjs', import.meta.url)),
        shikiPackagePath,
        ...((await readdir(shikiDirectory)).filter(name => name.startsWith('langs') && name.endsWith('.mjs'))
            .map(name => join(shikiDirectory, name))),
        ...((await readdir(grammarDirectory)).filter(name => name.endsWith('.mjs'))
            .map(name => join(grammarDirectory, name))),
    ];
}

/** Preserve each installed loader's complete registration closure, deduplicating
 * shared embedded grammars before projecting them as packaged Expo assets. */
export async function generateShikiGrammarAssets({
    uiPackageDir = uiDirectory,
    outputDirectory = resolve(uiPackageDir, '.expo/hstack/shiki'),
    outputPath = resolve(uiPackageDir, inventoryRelativePath),
    publicationPath = outputPath,
} = {}) {
    const require = createRequire(join(uiPackageDir, 'package.json'));
    const { bundledLanguages, bundledLanguagesInfo } = await import(pathToFileURL(require.resolve('shiki/langs')).href);
    const assets = new Map();
    const languages = [];
    for (const [id, load] of Object.entries(bundledLanguages)) {
        const { default: registrations } = await load();
        const references = [];
        for (const registration of registrations) {
            const content = JSON.stringify(registration);
            const digest = createHash('sha256').update(content).digest('hex');
            if (!assets.has(digest)) assets.set(digest, { content, index: assets.size });
            references.push(`asset${assets.get(digest).index}`);
        }
        languages.push(`    ${JSON.stringify(id)}: [${references.join(', ')}],`);
    }
    const assetPaths = [];
    const declarations = [];
    for (const [digest, { content, index }] of assets) {
        const path = join(outputDirectory, `${digest}.json.bundle`);
        await writeChanged(path, content);
        assetPaths.push(path);
        let specifier = relative(dirname(publicationPath), path).replaceAll('\\', '/');
        if (!specifier.startsWith('.')) specifier = `./${specifier}`;
        declarations.push(`const asset${index} = require(${JSON.stringify(specifier)});`);
    }
    await writeChanged(outputPath, [
        '// Generated by scripts/generateShikiGrammarAssets.mjs from installed Shiki loaders.',
        ...declarations,
        'export const SHIKI_LANGUAGE_ASSETS = {',
        ...languages,
        '};',
        `export const SHIKI_LANGUAGE_INFO = ${JSON.stringify(bundledLanguagesInfo.map(({ import: _load, ...metadata }) => metadata))};`,
        '',
    ].join('\n'));
    return { outputPath, assetPaths, inputPaths: await resolveShikiGrammarAssetInputPaths({ uiPackageDir }) };
}
