import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import url from 'node:url';
import esbuild from 'esbuild';

const ENTRY_RELATIVE_PATH = path.join(
    'sources',
    'components',
    'markdown',
    'mermaidWebViewEntry.ts',
);
const OUTPUT_RELATIVE_PATH = path.join(
    'sources',
    'components',
    'markdown',
    'mermaidWebViewBundle.generated.ts',
);
const MAX_BUNDLE_BYTES = 3_500_000;

function writeIfChanged(filePath, contents) {
    const existing = fs.existsSync(filePath) ? fs.readFileSync(filePath, 'utf8') : null;
    if (existing === contents) return false;
    fs.mkdirSync(path.dirname(filePath), { recursive: true });
    fs.writeFileSync(filePath, contents, 'utf8');
    return true;
}

function chunkString(value, chunkSize) {
    const chunks = [];
    for (let index = 0; index < value.length; index += chunkSize) {
        chunks.push(value.slice(index, index + chunkSize));
    }
    return chunks;
}

export function assertMermaidWebViewBundleFresh({
    actualContents,
    expectedContents,
    generatedFilePath,
}) {
    if (actualContents === null) {
        throw new Error(`Mermaid WebView generated bundle is missing: ${generatedFilePath}`);
    }
    if (actualContents !== expectedContents) {
        throw new Error(
            `Mermaid WebView generated bundle is stale: ${generatedFilePath}. `
            + 'Regenerate it with yarn --cwd apps/ui postinstall:real.',
        );
    }
}

export async function createMermaidWebViewBundleSource({ expoAppDir }) {
    const entryPath = path.resolve(expoAppDir, ENTRY_RELATIVE_PATH);
    if (!fs.existsSync(entryPath)) {
        throw new Error(`Mermaid WebView entry not found at ${entryPath}`);
    }

    const result = await esbuild.build({
        absWorkingDir: expoAppDir,
        entryPoints: [entryPath],
        bundle: true,
        write: false,
        format: 'iife',
        platform: 'browser',
        target: ['es2020'],
        minify: true,
        legalComments: 'none',
        sourcemap: false,
        treeShaking: true,
    });
    const js = result.outputFiles?.[0]?.text ?? '';
    const bundleBytes = Buffer.byteLength(js, 'utf8');
    if (!js.trim() || !js.includes('HAPPIER_MERMAID')) {
        throw new Error('esbuild produced an invalid Mermaid WebView bundle');
    }
    if (bundleBytes > MAX_BUNDLE_BYTES) {
        throw new Error(`Mermaid WebView bundle is ${bundleBytes} bytes; limit is ${MAX_BUNDLE_BYTES}`);
    }

    const chunks = chunkString(js, 50_000);
    const contents = `/**
 * Generated by \`apps/ui/tools/mermaid/buildMermaidWebViewBundle.mjs\`.
 * The native Mermaid WebView has no CDN or runtime-network fallback.
 */
const MERMAID_WEBVIEW_BUNDLE_CHUNKS = [
${chunks.map((chunk) => `    ${JSON.stringify(chunk)},`).join('\n')}
];

export const MERMAID_WEBVIEW_BUNDLE_JS = MERMAID_WEBVIEW_BUNDLE_CHUNKS.join('');
export const MERMAID_WEBVIEW_BUNDLE_BYTES = ${bundleBytes};
`;
    return { contents, bundleBytes };
}

export async function buildMermaidWebViewBundle({ expoAppDir }) {
    const generated = await createMermaidWebViewBundleSource({ expoAppDir });
    const outFile = path.resolve(expoAppDir, OUTPUT_RELATIVE_PATH);
    return {
        wrote: writeIfChanged(outFile, generated.contents),
        outFile,
        bundleBytes: generated.bundleBytes,
    };
}

export async function verifyMermaidWebViewBundle({ expoAppDir }) {
    const generated = await createMermaidWebViewBundleSource({ expoAppDir });
    const outFile = path.resolve(expoAppDir, OUTPUT_RELATIVE_PATH);
    const actualContents = fs.existsSync(outFile) ? fs.readFileSync(outFile, 'utf8') : null;
    assertMermaidWebViewBundleFresh({
        actualContents,
        expectedContents: generated.contents,
        generatedFilePath: outFile,
    });
    return { outFile, bundleBytes: generated.bundleBytes };
}

if (process.argv[1] && import.meta.url === url.pathToFileURL(process.argv[1]).href) {
    const toolsDir = path.dirname(fs.realpathSync(url.fileURLToPath(import.meta.url)));
    const expoAppDir = path.resolve(toolsDir, '..', '..');
    const checkOnly = process.argv.slice(2).includes('--check');
    const task = checkOnly
        ? verifyMermaidWebViewBundle({ expoAppDir })
        : buildMermaidWebViewBundle({ expoAppDir });
    task
        .then((result) => {
            const status = checkOnly ? 'verified' : (result.wrote ? 'written' : 'up to date');
            console.log(
                `[mermaid] webview bundle ${status}: `
                + `${path.relative(expoAppDir, result.outFile)} (${Math.round(result.bundleBytes / 1024)}kb)`,
            );
        })
        .catch((error) => {
            console.error(error instanceof Error ? error.message : String(error));
            process.exit(1);
        });
}
