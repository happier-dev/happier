import { build } from 'esbuild';
import { readFile, writeFile, mkdir, rename } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

export async function buildStreamWebViewBundle({ expoAppDir, check = false }) {
    const output = resolve(expoAppDir, 'sources/components/stream/renderers/webview/bundle.generated.ts');
    const result = await build({ absWorkingDir: expoAppDir,
        entryPoints: ['sources/components/stream/renderers/webview/entry.tsx'],
        alias: { 'react-native': 'react-native-web' },
        conditions: ['browser', 'happier-source'],
        define: { 'process.env.NODE_ENV': '"production"' },
        bundle: true, write: false, format: 'iife', platform: 'browser', target: ['es2020'],
        minify: true, legalComments: 'none' });
    const js = result.outputFiles[0].text;
    const contents = `// Generated by apps/ui/tools/stream/buildStreamWebViewBundle.mjs.\nexport const STREAM_WEBVIEW_BUNDLE = ${JSON.stringify(js)};\n`;
    const previous = await readFile(output, 'utf8').catch(error => {
        if (error.code === 'ENOENT') return null;
        throw error;
    });
    if (check && previous !== contents) throw new Error('Stream WebView bundle is stale; run node apps/ui/tools/stream/buildStreamWebViewBundle.mjs');
    if (!check && previous !== contents) {
        await mkdir(dirname(output), { recursive: true });
        const temporary = `${output}.${process.pid}.tmp`;
        await writeFile(temporary, contents);
        await rename(temporary, output);
    }
    return { bytes: Buffer.byteLength(js) };
}
if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
    const expoAppDir = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
    console.log(await buildStreamWebViewBundle({ expoAppDir, check: process.argv.includes('--check') }));
}
