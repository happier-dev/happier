import { voiceDiagnosticsConsentTranslations } from './voiceDiagnosticsConsentTranslations';

/**
 * The complete `settingsVoice.diagnostics` subtree for every non-English locale.
 *
 * Speech diagnostics record real microphone audio onto a machine the user picked, so every leaf
 * here — what is recorded, where it is kept, how long, how it is exported and how it is deleted —
 * is a privacy statement. An English fallback in this screen tells a Japanese or Catalan user
 * nothing about what is being kept on their machine, which is why the whole subtree is owned here
 * rather than left to eleven locale files.
 *
 * The recording consent itself keeps its own owner, `voiceDiagnosticsConsentTranslations`, and is
 * composed in below: one key, one owner, and the consent-completeness test keeps guarding it.
 */
type VoiceDiagnosticsLocale = keyof typeof voiceDiagnosticsConsentTranslations;

type VoiceDiagnosticsCopy = Readonly<{
  title: string;
  footer: string;
  enabled: string;
  enabledSubtitle: string;
  sttInput: string;
  ttsOutput: string;
  location: string;
  unavailable: string;
  retention: string;
  retentionDetail: (args: { hours: number; files: number; megabytes: number }) => string;
  deleteAll: string;
  deleteAllSubtitle: string;
  deleteConfirmTitle: string;
  deleteConfirmBody: string;
  deleteAction: string;
  deleteFailed: string;
  cleanupRequired: string;
  cleanupRequiredSubtitle: string;
  captureFailed: string;
  captureFailedSubtitle: string;
  retryCleanup: string;
  retryCleanupSubtitle: string;
  cleanupRetryFailed: string;
  exportTitle: string;
  noArtifacts: string;
  exportSttArtifact: string;
  exportTtsArtifact: string;
  exportArtifactAccessibility: string;
  exportConfirmTitle: string;
  exportConfirmBody: string;
  exportAction: string;
  exportFailed: string;
  backupPolicy: string;
  backupPolicyBestEffort: string;
  activeIndicator: string;
  checkingIndicator: string;
  statusUnknownIndicator: string;
  shutdownPendingIndicator: string;
  shutdownFailedIndicator: string;
  retryShutdown: string;
  sessionOptOut: string;
  sessionOptOutConfirmTitle: string;
  sessionOptOutConfirmBody: string;
  sessionOptOutFailed: string;
  sessionOptOutRetry: string;
}>;

function defineVoiceDiagnostics(locale: VoiceDiagnosticsLocale, copy: VoiceDiagnosticsCopy) {
  return { diagnostics: { ...voiceDiagnosticsConsentTranslations[locale].diagnostics, ...copy } };
}

