/**
 * English sentences name an input in running text ("Choose the repository"): a label that starts
 * as a capitalised ordinary word reads lower-case there; a name with inner capitals ("GitHub
 * account", "URL") keeps its spelling.
 */
function inSentence(label: string): string {
    return /^[A-Z][a-z]/.test(label) ? label[0]!.toLowerCase() + label.slice(1) : label;
}

