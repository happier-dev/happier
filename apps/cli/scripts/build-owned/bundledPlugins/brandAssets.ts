/** Packaged SVG inputs for the existing bundled-plugin projection publisher. */
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';

import { readDescriptorGeneratedSvgIcon, renderDescriptorGeneratedSvgIconLines, toAgentConstPrefix } from './agentUi.ts';
import { readJsonObjectProperty, readOptionalJsonStringProperty } from './literals.ts';
import type { BundledPluginPackage } from './projectionFacts.ts';

function renderTemplateResolver(xml: string): string {
  const parts: string[] = [];
  let offset = 0;
  for (const match of xml.matchAll(/\{\{([A-Za-z_$][\w$]*(?:\.[A-Za-z_$][\w$]*)*)\}\}/gu)) {
    parts.push(JSON.stringify(xml.slice(offset, match.index)), `theme.colors.${match[1]!}`);
    offset = match.index + match[0].length;
  }
  parts.push(JSON.stringify(xml.slice(offset)));
  return `(${parts.length > 1 ? 'theme' : '_theme'}) => ${parts.join(' + ')}`;
}

export function renderBundledBrandAssetsTs(params: Readonly<{
  rootDir: string;
  pluginPackages: readonly BundledPluginPackage[];
}>): string {
  const agentEntries: string[] = [];
  const serviceEntries: string[] = [];
  const pathResolvers: string[] = [];
  for (const plugin of params.pluginPackages) {
    const packageRoot = resolve(params.rootDir, 'packages/plugins', plugin.pluginPackageId);
    const descriptor = plugin.agentUiDescriptor;
    if (descriptor) {
      const svg = readJsonObjectProperty(descriptor.assets ?? {}, 'svgIcon');
      const assetPath = svg && readOptionalJsonStringProperty(svg, 'path');
      if (assetPath) {
        const xml = readFileSync(resolve(packageRoot, assetPath), 'utf8').trim();
        agentEntries.push(`    ${JSON.stringify(descriptor.agentId)}: ${renderTemplateResolver(xml)},`);
      } else {
        const source = readDescriptorGeneratedSvgIcon(descriptor, toAgentConstPrefix(descriptor.agentId));
        if (source) {
          pathResolvers.push(...renderDescriptorGeneratedSvgIconLines(source), '');
          agentEntries.push(`    ${JSON.stringify(descriptor.agentId)}: ${source.constName},`);
        }
      }
    }
    for (const service of plugin.manifest.contributes.connectedAccountDescriptors ?? []) {
      const iconResourceId = service.ui?.iconResourceId;
      if (!iconResourceId) continue;
      const resource = plugin.manifest.contributes.resources.find(resource => resource.id === iconResourceId);
      if (!resource || resource.kind !== 'asset' || !('path' in resource) || resource.contentType !== 'image/svg+xml') {
        throw new Error(`Service mark ${plugin.pluginId}/${service.id} must reference a packaged SVG Resource: ${iconResourceId}`);
      }
      const xml = readFileSync(resolve(packageRoot, resource.path), 'utf8').trim();
      serviceEntries.push(`    ${JSON.stringify(`${plugin.pluginId}/${service.id}`)}: ${renderTemplateResolver(xml)},`);
    }
  }
  return [
    '/** Generated by apps/cli/scripts/build-owned/generateBundledPluginEntries.ts from plugin-owned SVG assets. */',
    "import type { AgentIconSvgXmlResolver } from './registryUi';",
    "import type { CanonicalAgentId } from './registryCore';",
    '',
    'function createGeneratedSvgIconXml(viewBox: string, body: string): string {',
    '    return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}">${body}</svg>`.replace(/\\s{2,}/g, \' \').trim();',
    '}',
    '',
    ...pathResolvers,
    'export const AGENT_LOGO_SVG_XML: Readonly<Partial<Record<CanonicalAgentId, AgentIconSvgXmlResolver>>> = Object.freeze({',
    ...agentEntries,
    '});',
    '',
    'export const CONNECTED_SERVICE_LOGO_SVG_XML: Readonly<Record<string, AgentIconSvgXmlResolver>> = Object.freeze({',
    ...serviceEntries,
    '});',
    '',
  ].join('\n');
}
