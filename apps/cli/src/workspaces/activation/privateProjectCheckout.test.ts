import { describe, expect, it } from 'vitest';
import { preparePrivateProjectCheckout, admitPrivateProjectCheckoutDestination } from '@/workspaces/activation/privateProjectCheckout';
import { deriveAgentIsolationMemberIdentity } from '@/daemon/agentIsolation/provisioning';
import { selectHostRequesterExecutionIdentity } from '@/daemon/agentIsolation/agentIsolationLaunchPolicy';
import { readAgentIsolationMemberWorkspaceRoot } from '@/daemon/agentIsolation/agentIsolationNativeIdentity';
import { materializeWorkspaceRefForMachineRoot } from '@/workspaces/workspaceRefsV1';
import { computeWorkspaceSyncPolicyDigest } from '@happier-dev/protocol';

async function nativeFixture(accountId = 'member-a', homeServerIdentityId = 'home') {
  const selected = selectHostRequesterExecutionIdentity({ hostHomeServerIdentityId: homeServerIdentityId,
    hostAccountAgent: { accountId, custodianAccountId: 'owner', machineId: 'machine', installationId: 'installation' } });
  if (selected.kind !== 'isolated') throw new Error('Fixture must reach canonical isolated identity');
  // Native observation is an OS boundary fixture. The production projection
  // below is generated by the canonical native owner, not re-derived here.
  const requesterIdentity = selected;
  const identity = { ...deriveAgentIsolationMemberIdentity({ requester: selected.requester, homeServerIdentityId }), agentUid: 2401, agentGid: 2401 };
  const memberRoot = await readAgentIsolationMemberWorkspaceRoot(identity, { observe: async step => ({
    stepId: step.id, status: 'satisfied', facts: { uid: identity.agentUid, gid: 2400 },
  }) }, { daemonObservation: { daemonIdentity: 'nonRoot', daemonUid: 2400,
    daemonUsername: 'alice', daemonPrimaryGroup: 'engineers' } });
  return { requesterIdentity, memberRoot };
}
const boundaryFixture = await nativeFixture();
const fixture = () => boundaryFixture;

describe('private Project checkout preparation', () => {
  it('consumes the native qualified Home without adding a field to the requester selector', () => {
    const input = fixture();
    const requester = input.memberRoot.identity.requester;
    const selected = selectHostRequesterExecutionIdentity({ hostHomeServerIdentityId: input.memberRoot.identity.homeServerIdentityId,
      hostAccountAgent: { accountId: requester.accountId, custodianAccountId: 'owner', machineId: requester.machineId,
        installationId: requester.installationId } });
    expect(selected).not.toHaveProperty('homeServerIdentityId');
    const prepared = preparePrivateProjectCheckout({ requesterIdentity: selected, memberRoot: input.memberRoot,
      workspaceRefs: [], createId: () => 'retained-selector-checkout' });
    expect(prepared.rootPath).toBe(`${input.memberRoot.workspaceRoot}/retained-selector-checkout`);
    expect(prepared.workspaceRefId).toBe('retained-selector-checkout');
  });

  it('reserves the SAME canonical WorkspaceRef id before review without accepting or moving any row', () => {
    const input = fixture();
    let allocations = 0;
    const workspaceRefs = Object.freeze([]);
    const prepared = preparePrivateProjectCheckout({ ...input, workspaceRefs,
      createId: () => { allocations += 1; return 'checkout-id'; } });
    expect(prepared).toEqual({ workspaceRefId: 'checkout-id', rootPath: `${input.memberRoot.workspaceRoot}/checkout-id`,
      destinationParentPath: input.memberRoot.workspaceRoot, destinationDirectoryName: 'checkout-id' });
    expect(workspaceRefs).toEqual([]);
    expect(allocations).toBe(1);
    const accepted = materializeWorkspaceRefForMachineRoot(workspaceRefs, { serverId: 'home', machineId: 'machine',
      rootPath: prepared.rootPath, nowMs: 1, createId: () => prepared.workspaceRefId });
    expect(accepted.workspaceRef.id).toBe(prepared.workspaceRefId);
    expect(accepted.workspaceRef.rootPath).toBe(prepared.rootPath);
  });

  it('reuses an exact existing own checkout without allocating another Account identity', () => {
    const input = fixture();
    const rootPath = `${input.memberRoot.workspaceRoot}/existing-checkout`;
    const existing = materializeWorkspaceRefForMachineRoot([], { serverId: 'home', machineId: 'machine', rootPath,
      nowMs: 1, createId: () => 'existing-checkout' }).workspaceRef;
    const prepared = preparePrivateProjectCheckout({ ...input, workspaceRefs: [existing], workspaceRefId: existing.id,
      createId: () => { throw new Error('Existing checkout identity must survive'); } });
    expect(prepared.workspaceRefId).toBe(existing.id);
    expect(prepared.rootPath).toBe(existing.rootPath);
  });

  it('requires the reviewed exact destination and never relocates or converts a worktree request', () => {
    const input = fixture();
    const prepared = preparePrivateProjectCheckout({ ...input, workspaceRefs: [], createId: () => 'checkout-id' });
    expect(() => admitPrivateProjectCheckoutDestination({ prepared, materialization: {
      kind: 'clone', destinationParentPath: prepared.destinationParentPath, destinationDirectoryName: prepared.destinationDirectoryName,
    } })).not.toThrow();
    for (const materialization of [
      { kind: 'clone' as const, destinationParentPath: '/shared', destinationDirectoryName: prepared.destinationDirectoryName },
      { kind: 'clone' as const, destinationParentPath: prepared.destinationParentPath, destinationDirectoryName: 'other-checkout' },
      { kind: 'worktree' as const, targetPath: prepared.rootPath,
        checkout: { kind: 'git_worktree' as const, displayName: 'feature', baseRef: 'main', branchMode: 'new' as const } },
    ]) expect(() => admitPrivateProjectCheckoutDestination({ prepared, materialization }))
      .toThrowError(expect.objectContaining({ code: 'workspace_private_checkout_review_required' }));
  });

  it('admits Sync only at the same prepared private checkout, without accepting a foreign or nested root', () => {
    const input = fixture();
    const prepared = preparePrivateProjectCheckout({ ...input, workspaceRefs: [], createId: () => 'sync-checkout' });
    const policy = { v: 1 as const, selection: 'all_files' as const, extraIgnorePatterns: [], extraIncludePatterns: [] };
    const workspaceAction = { kind: 'copy_once' as const,
      contentPolicy: { ...policy, policyDigest: computeWorkspaceSyncPolicyDigest(policy) } };
    expect(() => admitPrivateProjectCheckoutDestination({ prepared,
      materialization: { kind: 'sync', targetPath: prepared.rootPath, workspaceAction } })).not.toThrow();
    for (const targetPath of ['/shared/sync-checkout', `${input.memberRoot.workspaceRoot}/another`, `${prepared.rootPath}/nested`]) {
      expect(() => admitPrivateProjectCheckoutDestination({ prepared,
        materialization: { kind: 'sync', targetPath, workspaceAction } }))
        .toThrowError(expect.objectContaining({ code: 'workspace_private_checkout_review_required' }));
    }
  });

  it.each(['account', 'server', 'machine', 'installation'] as const)('does not borrow another admitted native %s root', field => {
    const input = fixture();
    const identity = input.memberRoot.identity;
    const foreign = { ...identity, requester: { ...identity.requester,
      [field === 'account' ? 'accountId' : field === 'server' ? 'serverId' : field === 'machine' ? 'machineId' : 'installationId']: 'another' } };
    expect(() => preparePrivateProjectCheckout({ ...input, memberRoot: { ...input.memberRoot, identity: foreign },
      workspaceRefs: [], createId: () => 'checkout-id' }))
      .toThrowError(expect.objectContaining({ code: 'workspace_private_checkout_required' }));
  });

  it.each(['../other', 'nested/checkout', 'nested\\checkout', '.', '..', '', ' leading', 'trailing '])('rejects unsafe existing checkout identity %j', workspaceRefId => {
    expect(() => preparePrivateProjectCheckout({ ...fixture(), workspaceRefs: [], workspaceRefId, createId: () => 'unused' }))
      .toThrowError(expect.objectContaining({ code: 'workspace_private_checkout_required' }));
  });

  it('does not replace an accepted foreign/shared root or a conflicting existing identity', () => {
    const input = fixture();
    const existing = materializeWorkspaceRefForMachineRoot([], { serverId: 'home', machineId: 'machine', rootPath: '/shared/authored',
      nowMs: 1, createId: () => 'existing-checkout' }).workspaceRef;
    expect(() => preparePrivateProjectCheckout({ ...input, workspaceRefs: [existing], workspaceRefId: existing.id,
      createId: () => 'unused' })).toThrowError(expect.objectContaining({ code: 'workspace_private_checkout_required' }));
    expect(existing.rootPath).toBe('/shared/authored');
  });

  it('refuses a second canonical identity already associated with the reviewed private physical root', () => {
    const input = fixture();
    const rootPath = `${input.memberRoot.workspaceRoot}/reserved-checkout`;
    const existing = materializeWorkspaceRefForMachineRoot([], { serverId: 'home', machineId: 'machine', rootPath,
      nowMs: 1, createId: () => 'different-accepted-id' }).workspaceRef;
    expect(() => preparePrivateProjectCheckout({ ...input, workspaceRefs: [existing], createId: () => 'reserved-checkout' }))
      .toThrowError(expect.objectContaining({ code: 'workspace_private_checkout_required' }));
    expect(existing.id).toBe('different-accepted-id');
  });

  it('retains a typed, non-content phase/reason on a private checkout refusal', () => {
    const input = fixture();
    const identity = input.memberRoot.identity;
    expect(() => preparePrivateProjectCheckout({ ...input, memberRoot: { ...input.memberRoot,
      identity: { ...identity, requester: { ...identity.requester, serverId: 'foreign-home' } } }, workspaceRefs: [], createId: () => 'checkout' }))
      .toThrowError(expect.objectContaining({ code: 'workspace_private_checkout_required',
        details: { reason: 'workspace_private_checkout_required', phase: 'native_execution_admission' } }));
  });
});
