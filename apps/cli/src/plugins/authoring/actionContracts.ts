import { lstat, mkdir, readdir, readFile, realpath, rmdir, unlink, writeFile } from 'node:fs/promises';
import { dirname, relative, resolve, sep } from 'node:path';

import { resolvePortablePluginRelativePath } from '../manifest/portableRelativePath';
import { isCanonicalAbsolutePathInsideRoot } from '@/utils/path/expandHomeDirPath';

type ActionContractManifest = Readonly<{
  id: string;
  entrypoints?: Readonly<{ daemon?: string }>;
  contributes: Readonly<{
    actions: readonly Readonly<{ id: string }>[];
  }>;
}>;

type ActionContractIdentity = Readonly<{
  pluginId: string;
  localId: string;
}>;

type ActionContractProjection = Readonly<Record<string, ActionContractIdentity>>;

const GENERATED_ACTION_CONTRACT_MARKER = '// Generated by the Happier plugin authoring toolchain; do not edit.';

async function realpathNearestExistingAncestor(targetPath: string): Promise<string> {
  let candidatePath = targetPath;
  while (true) {
    try {
      return await realpath(candidatePath);
    } catch (error) {
      if ((error as NodeJS.ErrnoException | null)?.code !== 'ENOENT') throw error;
      const parentPath = dirname(candidatePath);
      if (parentPath === candidatePath) throw error;
      candidatePath = parentPath;
    }
  }
}

async function assertContainedActionOutputPath(params: Readonly<{
  projectRoot: string;
  targetPath: string;
  label: string;
}>): Promise<void> {
  const physicalRoot = await realpath(resolve(params.projectRoot));
  const physicalAncestor = await realpathNearestExistingAncestor(resolve(params.targetPath));
  if (!isCanonicalAbsolutePathInsideRoot(physicalRoot, physicalAncestor)) {
    throw new Error(`${params.label} resolves outside the physical plugin root`);
  }
  try {
    const stats = await lstat(params.targetPath);
    if (stats.isSymbolicLink()) {
      let physicalTarget: string;
      try {
        physicalTarget = await realpath(params.targetPath);
      } catch (error) {
        if ((error as NodeJS.ErrnoException | null)?.code === 'ENOENT') {
          throw new Error(`${params.label} is a dangling symbolic link`);
        }
        throw error;
      }
      if (!isCanonicalAbsolutePathInsideRoot(physicalRoot, physicalTarget)) {
        throw new Error(`${params.label} resolves outside the physical plugin root`);
      }
    }
  } catch (error) {
    if ((error as NodeJS.ErrnoException | null)?.code !== 'ENOENT') throw error;
  }
}

function relativeModuleSpecifier(fromDirectory: string, targetPath: string): string {
  const value = relative(fromDirectory, targetPath).split(sep).join('/');
  return value.startsWith('.') ? value : `./${value}`;
}

function projectActionContractRuntime(
  actionContracts: ActionContractProjection,
): string {
  const lines = [
    GENERATED_ACTION_CONTRACT_MARKER,
    'export const actionContracts = Object.freeze({',
  ];
  for (const [localId, action] of Object.entries(actionContracts)) {
    lines.push(
      `  ${JSON.stringify(localId)}: Object.freeze({ pluginId: ${JSON.stringify(action.pluginId)}, localId: ${JSON.stringify(action.localId)} }),`,
    );
  }
  lines.push('});', '');
  return lines.join('\n');
}

function projectActionContractTypes(daemonModuleSpecifier: string): string {
  return [
    GENERATED_ACTION_CONTRACT_MARKER,
    `export type ActionContracts = typeof import(${JSON.stringify(daemonModuleSpecifier)}).actionContracts;`,
    "export type { ActionContract } from '@happier-dev/plugin-sdk/actions';",
    'export declare const actionContracts: ActionContracts;',
    '',
  ].join('\n');
}

function isRecord(value: unknown): value is Readonly<Record<string, unknown>> {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

function assertActionContractProjection(
  value: unknown,
  manifest: ActionContractManifest,
): ActionContractProjection {
  if (!isRecord(value)) {
    throw new Error('Plugin actionContracts export must be a frozen object keyed by local Action id');
  }
  if (!Object.isFrozen(value)) {
    throw new Error('Plugin actionContracts export must be frozen by definePlugin');
  }

  const projected = Object.fromEntries(Object.entries(value).map(([localId, rawIdentity]) => {
    if (!isRecord(rawIdentity)
      || typeof rawIdentity.pluginId !== 'string'
      || typeof rawIdentity.localId !== 'string'
      || rawIdentity.pluginId.length === 0
      || rawIdentity.localId.length === 0
      || rawIdentity.localId !== localId
      || rawIdentity.pluginId !== manifest.id
      || !Object.isFrozen(rawIdentity)) {
      throw new Error(
        `Plugin actionContracts.${JSON.stringify(localId)} must be the frozen identity for '${manifest.id}:${localId}'`,
      );
    }
    return [localId, Object.freeze({
      pluginId: rawIdentity.pluginId,
      localId: rawIdentity.localId,
    })] as const;
  }));

  const declaredIds = manifest.contributes.actions.map((action) => action.id);
  const projectedIds = Object.keys(projected);
  if (declaredIds.length !== projectedIds.length
    || declaredIds.some((id) => !Object.prototype.hasOwnProperty.call(projected, id))) {
    throw new Error(
      `Plugin actionContracts export must match manifest contributes.actions for '${manifest.id}'`,
    );
  }
  return Object.freeze(projected);
}

async function removeGeneratedActionContractBarrel(generatedPaths: readonly string[]): Promise<void> {
  await Promise.all(generatedPaths.map(async (generatedPath) => {
    try {
      const existing = await readFile(generatedPath, 'utf8');
      if (existing.startsWith(GENERATED_ACTION_CONTRACT_MARKER)) {
        await unlink(generatedPath);
      }
    } catch (error) {
      if ((error as NodeJS.ErrnoException | null)?.code !== 'ENOENT') throw error;
    }
  }));
  await Promise.all([...new Set(generatedPaths.map((generatedPath) => dirname(generatedPath)))].map(async (directory) => {
    try {
      await rmdir(directory);
    } catch (error) {
      const code = (error as NodeJS.ErrnoException | null)?.code;
      if (code !== 'ENOENT' && code !== 'ENOTEMPTY') throw error;
    }
  }));
}

function resolveGeneratedActionContractBarrelPaths(params: Readonly<{
  projectRoot: string;
  daemonEntrypoint: string;
}>): Readonly<{
  actionsDirectory: string;
  daemonPath: string;
  generatedPaths: readonly string[];
}> {
  const daemonResolution = resolvePortablePluginRelativePath({
    rootPath: params.projectRoot,
    value: params.daemonEntrypoint,
    label: 'entrypoints.daemon',
  });
  if (!daemonResolution.ok) throw new Error(daemonResolution.message);

  const actionsDirectory = resolve(dirname(daemonResolution.path), 'actions');
  return Object.freeze({
    actionsDirectory,
    daemonPath: daemonResolution.path,
    generatedPaths: Object.freeze([
      resolve(actionsDirectory, 'index.js'),
      resolve(actionsDirectory, 'index.d.ts'),
    ]),
  });
}

function shouldSkipGeneratedActionContractSearchDirectory(name: string): boolean {
  return name === '.git' || name === '.happier-plugin' || name === 'node_modules';
}

async function findGeneratedActionContractBarrels(projectRoot: string): Promise<readonly string[]> {
  const resolvedProjectRoot = resolve(projectRoot);
  await assertContainedActionOutputPath({
    projectRoot: resolvedProjectRoot,
    targetPath: resolvedProjectRoot,
    label: 'Generated Action output root',
  });
  const pendingDirectories = [resolvedProjectRoot];
  const generatedPaths: string[] = [];
  while (pendingDirectories.length > 0) {
    const directory = pendingDirectories.pop()!;
    await assertContainedActionOutputPath({
      projectRoot: resolvedProjectRoot,
      targetPath: directory,
      label: 'Generated Action output directory',
    });
    let entries;
    try {
      entries = await readdir(directory, { withFileTypes: true });
    } catch (error) {
      if ((error as NodeJS.ErrnoException | null)?.code === 'ENOENT') continue;
      throw error;
    }
    for (const entry of entries) {
      const entryPath = resolve(directory, entry.name);
      if (entry.isDirectory()) {
        if (shouldSkipGeneratedActionContractSearchDirectory(entry.name)) continue;
        pendingDirectories.push(entryPath);
        continue;
      }
      if (!entry.isFile() || entry.name !== 'index.js' && entry.name !== 'index.d.ts') continue;
      if (directory.split(sep).at(-1) !== 'actions') continue;
      await assertContainedActionOutputPath({
        projectRoot: resolvedProjectRoot,
        targetPath: entryPath,
        label: 'Generated Action output file',
      });
      try {
        const existing = await readFile(entryPath, 'utf8');
        if (existing.startsWith(GENERATED_ACTION_CONTRACT_MARKER)) generatedPaths.push(entryPath);
      } catch (error) {
        if ((error as NodeJS.ErrnoException | null)?.code !== 'ENOENT') throw error;
      }
    }
  }
  return generatedPaths;
}

/** Removes only marker-owned generated Action barrels left by a prior executable build. */
export async function cleanupPluginAuthorActionContracts(projectRoot: string): Promise<void> {
  const generatedPaths = await findGeneratedActionContractBarrels(resolve(projectRoot));
  await removeGeneratedActionContractBarrel(generatedPaths);
}

/**
 * Materializes the public `./actions` surface from the canonical author
 * `definePlugin(...).actionContracts` projection. Runtime output contains only
 * qualified identities; the declaration output follows the author entry's
 * inferred `actionContracts` type and imports no implementation or schema
 * module. The manifest is used only to validate that the author-published
 * projection has not diverged from the canonical contribution declaration.
 */
export async function generatePluginActionContracts(params: Readonly<{
  projectRoot: string;
  manifest?: ActionContractManifest;
  actionContracts?: unknown;
}>): Promise<void> {
  const projectRoot = resolve(params.projectRoot);
  let manifest = params.manifest;
  let actionContracts = params.actionContracts;
  if (!manifest) {
    const { evaluatePluginAuthorSource } = await import('./sourceModule');
    const evaluated = await evaluatePluginAuthorSource({ locator: projectRoot });
    manifest = evaluated.manifest;
    actionContracts = evaluated.actionContracts;
  }

  // A legacy author that does not publish actionContracts keeps its existing
  // build intact, but any marker-owned barrels from an earlier executable
  // build must be removed when the manifest no longer has a daemon entry.
  if (actionContracts === undefined && manifest.entrypoints?.daemon === undefined) {
    await cleanupPluginAuthorActionContracts(projectRoot);
    return;
  }

  const daemonEntrypoint = manifest.entrypoints?.daemon;
  if (!daemonEntrypoint) {
    throw new Error('Plugin action contract generation requires entrypoints.daemon');
  }
  const { actionsDirectory, daemonPath, generatedPaths } = resolveGeneratedActionContractBarrelPaths({
    projectRoot,
    daemonEntrypoint,
  });
  await assertContainedActionOutputPath({
    projectRoot,
    targetPath: actionsDirectory,
    label: 'Generated Action output directory',
  });
  await Promise.all(generatedPaths.map((generatedPath) => assertContainedActionOutputPath({
    projectRoot,
    targetPath: generatedPath,
    label: 'Generated Action output file',
  })));
  if (actionContracts === undefined) {
    await cleanupPluginAuthorActionContracts(projectRoot);
    return;
  }

  const projectedActionContracts = assertActionContractProjection(actionContracts, manifest);
  if (Object.keys(projectedActionContracts).length === 0) {
    await cleanupPluginAuthorActionContracts(projectRoot);
    return;
  }
  // The executable authoring pipeline owns marker-headed Action barrels, not
  // a fixed dist pathname. Once the replacement projection is valid, retire
  // every prior marker-owned location so an entrypoint move cannot retain a
  // second generated public surface.
  await cleanupPluginAuthorActionContracts(projectRoot);
  await mkdir(actionsDirectory, { recursive: true });
  await Promise.all([
    writeFile(
      resolve(actionsDirectory, 'index.js'),
      projectActionContractRuntime(projectedActionContracts),
      'utf8',
    ),
    writeFile(
      resolve(actionsDirectory, 'index.d.ts'),
      projectActionContractTypes(relativeModuleSpecifier(actionsDirectory, daemonPath)),
      'utf8',
    ),
  ]);
}
