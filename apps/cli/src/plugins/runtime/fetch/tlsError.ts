// Native Node/OpenSSL and Bun TLS codes shared by HTTP observations and ws.
const TLS_DRIVER_ERROR_CODES = new Set([
    'CERT_CHAIN_TOO_LONG',
    'CERT_HAS_EXPIRED',
    'CERT_REJECTED',
    'CERT_REVOKED',
    'CERT_SIGNATURE_FAILURE',
    'CERT_UNTRUSTED',
    'CERT_NOT_YET_VALID',
    'CRL_HAS_EXPIRED',
    'CRL_NOT_YET_VALID',
    'CRL_SIGNATURE_FAILURE',
    'DEPTH_ZERO_SELF_SIGNED_CERT',
    'ERROR_IN_CERT_NOT_AFTER_FIELD',
    'ERROR_IN_CERT_NOT_BEFORE_FIELD',
    'ERROR_IN_CRL_LAST_UPDATE_FIELD',
    'ERROR_IN_CRL_NEXT_UPDATE_FIELD',
    'ERR_TLS_CERT_ALTNAME_INVALID',
    'HOSTNAME_MISMATCH',
    'INVALID_CA',
    'INVALID_PURPOSE',
    'PATH_LENGTH_EXCEEDED',
    'SELF_SIGNED_CERT_IN_CHAIN',
    'UNABLE_TO_DECODE_ISSUER_PUBLIC_KEY',
    'UNABLE_TO_DECRYPT_CERT_SIGNATURE',
    'UNABLE_TO_DECRYPT_CRL_SIGNATURE',
    'UNABLE_TO_GET_CRL',
    'UNABLE_TO_GET_ISSUER_CERT',
    'UNABLE_TO_GET_ISSUER_CERT_LOCALLY',
    'UNABLE_TO_VERIFY_LEAF_SIGNATURE',
]);

export function isNativeTlsErrorCode(code: string, encrypted: boolean): boolean {
    return (code === 'EPROTO' && encrypted) || code.startsWith('ERR_TLS_') || TLS_DRIVER_ERROR_CODES.has(code);
}
