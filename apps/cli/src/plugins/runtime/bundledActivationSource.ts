function parseContainedPackageNameSegments(packageName: string): readonly string[] {
    const segments = packageName.split('/');
    if (segments.some((segment) => (
        segment.length === 0
        || segment === '.'
        || segment === '..'
        || segment.includes('\\')
    ))) {
        throw new Error(`Bundled plugin package name is not contained: '${packageName}'`);
    }
    return segments;
}

function parseContainedManifestModulePath(modulePath: string): readonly string[] {
    if (!modulePath.startsWith('./') || modulePath.includes('\\')) {
        throw new Error(`Bundled plugin daemon entry is not a contained relative path: '${modulePath}'`);
    }
    const segments = modulePath.slice(2).split('/');
    if (segments.some((segment) => (
        segment.length === 0 || segment === '.' || segment === '..'
    ))) {
        throw new Error(`Bundled plugin daemon entry is not a contained relative path: '${modulePath}'`);
    }
    return segments;
}

/**
 * Resolves first-party packaged activation bytes directly inside the exact
 * runtime closure that contains the executing CLI. Semantic generated
 * metadata selects the package and manifest entry; no generated byte ledger
 * or plugin-store generation participates in this mapping.
 */
export function resolvePackagedBundledActivationPaths(params: Readonly<{
    runtimeRoot: string;
    activationTargets: readonly BundledExecutablePluginTarget[];
    metadata: readonly BundledPackagedPluginMetadata[];
    locators: readonly BundledPackagedPluginLocator[];
}>): Readonly<{
    entryPathsByPackageName: ReadonlyMap<string, string>;
    rootPathsByPackageName: ReadonlyMap<string, string>;
}> {
    const runtimeRoot = resolve(params.runtimeRoot);
    const metadataByPluginId = new Map<string, BundledPackagedPluginMetadata>();
    const locatorByPluginId = new Map<string, BundledPackagedPluginLocator>();
    for (const metadata of params.metadata) {
        if (metadataByPluginId.has(metadata.pluginId)) {
            throw new Error(`Bundled plugin metadata is ambiguous for '${metadata.pluginId}'`);
        }
        metadataByPluginId.set(metadata.pluginId, metadata);
    }
    for (const locator of params.locators) {
        if (locatorByPluginId.has(locator.pluginId)) {
            throw new Error(`Bundled plugin locator is ambiguous for '${locator.pluginId}'`);
        }
        locatorByPluginId.set(locator.pluginId, locator);
    }

    const entryPathsByPackageName = new Map<string, string>();
    const rootPathsByPackageName = new Map<string, string>();
    for (const target of params.activationTargets) {
        if (
            target.sourceSpec.kind !== 'bundled'
            || !target.daemonEntryPath
        ) continue;
        const metadata = metadataByPluginId.get(target.pluginId);
        const locator = locatorByPluginId.get(target.pluginId);
        const manifest = locator
            ? readCanonicalPluginManifest(readBundledPluginManifest(locator, runtimeRoot))
            : null;
        const daemonEntrypoint = manifest?.entrypoints?.daemon;
        if (
            !metadata
            || metadata.packageName !== target.daemonEntryPath
            || !manifest
            || manifest.id !== target.pluginId
            || !daemonEntrypoint
        ) {
            throw new Error(`Bundled plugin packaged activation metadata is invalid for '${target.pluginId}'`);
        }
        const packageRoot = resolve(
            runtimeRoot,
            'node_modules',
            ...parseContainedPackageNameSegments(metadata.packageName),
        );
        const entryPath = resolve(
            packageRoot,
            ...parseContainedManifestModulePath(daemonEntrypoint),
        );
        if (
            !isCanonicalAbsolutePathInsideRoot(runtimeRoot, packageRoot)
            || !isCanonicalAbsolutePathInsideRoot(packageRoot, entryPath)
        ) {
            throw new Error(`Bundled plugin packaged activation escapes the CLI runtime root for '${target.pluginId}'`);
        }
        entryPathsByPackageName.set(metadata.packageName, entryPath);
        rootPathsByPackageName.set(metadata.packageName, packageRoot);
    }
    return Object.freeze({
        entryPathsByPackageName,
        rootPathsByPackageName,
    });
}

function normalizePathSeparators(pathLike: string): string {
    return pathLike.replaceAll('\\', '/');
}

function compareCanonicalStrings(left: string, right: string): number {
    if (left < right) return -1;
    if (left > right) return 1;
    return 0;
}

function parseFirstPartyPluginIdFromPackageName(packageName: string): string | null {
    const prefix = '@happier-dev/plugins-';
    if (!packageName.startsWith(prefix)) {
        return null;
    }
    const pluginId = packageName.slice(prefix.length).trim();
    if (!pluginId) {
        return null;
    }
    return pluginId;
}

async function importModule(specifier: string): Promise<PluginDaemonModuleNamespace> {
    return await import(specifier) as PluginDaemonModuleNamespace;
}

export function resolveBundledActivationSourceRepoRoot(
    moduleUrl: string | URL,
): string {
    const lexicalModulePath = fileURLToPath(moduleUrl);
    let modulePath = lexicalModulePath;
    try {
        modulePath = realpathSync(lexicalModulePath);
    } catch {
        // Packaged virtual filesystems do not necessarily expose a realpath.
    }
    return resolve(projectPathFromModuleUrl(pathToFileURL(modulePath).href), '..', '..');
}

function defaultRepoRoot(): string {
    return resolveBundledActivationSourceRepoRoot(import.meta.url);
}

function resolveComparableFileIdentity(path: string): string {
    const absolutePath = resolve(path);
    try {
        return realpathSync(absolutePath);
    } catch {
        return absolutePath;
    }
}

export function resolveSourceDevelopmentBundledPackageNames(params: Readonly<{
    artifacts: readonly Readonly<{
        packageName: string;
        packageEntryRelativePath: string;
    }>[];
    canImportFirstPartyPluginSource?: () => boolean;
    existsSync?: (path: string) => boolean;
    repoRoot?: string;
    resolveBundledPackageEntry?: (packageName: string) => string;
}>): ReadonlySet<string> {
    const canImportFirstPartyPluginSource =
        params.canImportFirstPartyPluginSource ?? defaultCanImportFirstPartyPluginSource;
    if (!canImportFirstPartyPluginSource()) return new Set();
    const repoRoot = params.repoRoot ?? defaultRepoRoot();
    const existsSync = params.existsSync ?? nodeExistsSync;
    const resolveBundledPackageEntry =
        params.resolveBundledPackageEntry
        ?? createRequire(import.meta.url).resolve;
    const sourceDevelopmentPackageNames = new Set<string>();
    for (const artifact of params.artifacts) {
        const pluginId = parseFirstPartyPluginIdFromPackageName(artifact.packageName);
        const workspaceName = normalizeBundledWorkspaceNameFromPackageName(
            artifact.packageName,
        );
        if (!pluginId || !workspaceName) continue;
        const sourceEntryPath = resolve(
            repoRoot,
            'packages',
            'plugins',
            pluginId,
            'src',
            'index.ts',
        );
        if (!existsSync(sourceEntryPath)) continue;
        let resolvedPackageEntry: string;
        try {
            resolvedPackageEntry = resolve(resolveBundledPackageEntry(artifact.packageName));
        } catch {
            continue;
        }
        const sourceDevelopmentCopyEntry = resolve(
            repoRoot,
            'apps',
            'cli',
            'node_modules',
            '@happier-dev',
            workspaceName,
            ...artifact.packageEntryRelativePath.split('/'),
        );
        // The managed source checkout copies workspace output into this exact
        // dependency root. It is a development dependency closure, not the
        // generated immutable artifact whose inventory happens to describe a
        // subset of its files.
        if (
            resolveComparableFileIdentity(resolvedPackageEntry)
            === resolveComparableFileIdentity(sourceDevelopmentCopyEntry)
        ) {
            sourceDevelopmentPackageNames.add(artifact.packageName);
        }
    }
    return sourceDevelopmentPackageNames;
}

export function createBundledActivationSourceResolver(params: Readonly<{
    bundledPackageNames: readonly string[];
    bundledDeclarations?: readonly LoadedPlugin[];
    packagedRuntimeRoot?: string;
    signal?: AbortSignal;
    immutableArtifactPackageNames?: readonly string[];
    /**
     * The published daemon runtime bundle for each bundled package: the module that
     * activates the plugin and the directory its staged session-runner leaves live in.
     * It is not the package root export, which stays the compiler's own emit.
     */
    immutableArtifactEntryPathsByPackageName?: ReadonlyMap<string, string>;
    immutableArtifactRootPathsByPackageName?: ReadonlyMap<string, string>;
    unavailableImmutableArtifactPackageNames?: ReadonlySet<string>;
    canImportFirstPartyPluginSource?: () => boolean;
    existsSync?: (path: string) => boolean;
    importModule?: ImportModule;
    prepareSourceDevSharedDeps?: PrepareSourceDevSharedDeps;
    repoRoot?: string;
    packagedRuntime?: BundledPackagedRuntimeCustody;
    resolveDevelopmentSourceAuthority?: (input: Readonly<{
        pluginId: string;
        rootPath: string;
    }>) => Extract<PluginRuntimeSourceAuthority, { kind: 'development' }> | null;
}>) {
    const bundledPackageNames = new Set(params.bundledPackageNames);
    const immutableArtifactPackageNames = new Set(params.immutableArtifactPackageNames ?? []);
    const immutableArtifactEntryPathsByPackageName = params.immutableArtifactEntryPathsByPackageName ?? new Map();
    const immutableArtifactRootPathsByPackageName = params.immutableArtifactRootPathsByPackageName ?? new Map();
    const unavailableImmutableArtifactPackageNames = params.unavailableImmutableArtifactPackageNames ?? new Set();
    const canImportFirstPartyPluginSource =
        params.canImportFirstPartyPluginSource ?? defaultCanImportFirstPartyPluginSource;
    const existsSync = params.existsSync ?? nodeExistsSync;
    const loadImport = params.importModule ?? importModule;
    const prepareSourceDevSharedDeps =
        params.prepareSourceDevSharedDeps ?? prepareSourceDevSharedDepsForBundledPluginRuntimeLoad;
    const repoRoot = params.repoRoot ?? defaultRepoRoot();
    const sourceDevSharedDepsPreflightByPackageName = new Map<string, SourceDevSharedDepsPreflightCacheEntry>();
    let sourceDevSharedDepsBatchTarget: Readonly<{
        packageName: string;
        workspaceNames: readonly string[];
    }> | null | undefined;
    let sourceDevSharedDepsBatchPreflight: Promise<SourceDevSharedDepsBatchPreflightOutcome> | null = null;
    let sourceDevSharedDepsBatchFallbackReady = false;

    function resolveSourceDevWorkspaceNames(packageName: string): readonly string[] {
        const workspaceName = normalizeBundledWorkspaceNameFromPackageName(packageName);
        return workspaceName ? Object.freeze([workspaceName]) : Object.freeze([]);
    }

    function resolveSourceDevSharedDepsBatchTarget(): typeof sourceDevSharedDepsBatchTarget {
        if (sourceDevSharedDepsBatchTarget !== undefined) {
            return sourceDevSharedDepsBatchTarget;
        }

        const packageNamesByWorkspaceName = new Map<string, string>();
        for (const packageName of bundledPackageNames) {
            if (
                immutableArtifactEntryPathsByPackageName.has(packageName)
                || immutableArtifactPackageNames.has(packageName)
            ) {
                continue;
            }
            const pluginId = parseFirstPartyPluginIdFromPackageName(packageName);
            const workspaceName = normalizeBundledWorkspaceNameFromPackageName(packageName);
            if (!pluginId || !workspaceName) continue;
            const srcCandidate = resolve(repoRoot, 'packages', 'plugins', pluginId, 'src', 'index.ts');
            if (!existsSync(srcCandidate)) continue;

            const existingPackageName = packageNamesByWorkspaceName.get(workspaceName);
            if (!existingPackageName || compareCanonicalStrings(packageName, existingPackageName) < 0) {
                packageNamesByWorkspaceName.set(workspaceName, packageName);
            }
        }

        const workspaceNames = [...packageNamesByWorkspaceName.keys()].sort(compareCanonicalStrings);
        const batchPackageName = workspaceNames[0]
            ? packageNamesByWorkspaceName.get(workspaceNames[0])
            : undefined;
        sourceDevSharedDepsBatchTarget = workspaceNames.length > 1 && batchPackageName
            ? Object.freeze({
                packageName: batchPackageName,
                workspaceNames: Object.freeze(workspaceNames),
            })
            : null;
        return sourceDevSharedDepsBatchTarget;
    }

    async function runSourceDevSharedDepsPreflightForPackage(
        packageName: string,
        options?: Readonly<{ admittedCopyOnly?: boolean }>,
    ): Promise<SourceDevSharedDepsPreflightResult> {
        const existing = sourceDevSharedDepsPreflightByPackageName.get(packageName);
        if (existing?.result) {
            return existing.result;
        }
        if (existing?.promise) {
            return await existing.promise;
        }
        const workspaceNames = resolveSourceDevWorkspaceNames(packageName);
        const preflightPromise = Promise.resolve().then(() => prepareSourceDevSharedDeps({
            packageName,
            ...(params.signal ? { signal: params.signal } : {}),
            ...(workspaceNames.length > 0
                ? { workspaceNames }
                : {}),
            ...(options?.admittedCopyOnly
                ? { admittedCopyOnly: true }
                : {}),
        }));
        const entry: SourceDevSharedDepsPreflightCacheEntry = {
            promise: preflightPromise,
            result: null,
        };
        sourceDevSharedDepsPreflightByPackageName.set(packageName, entry);
        try {
            const result = await preflightPromise;
            if (sourceDevSharedDepsPreflightByPackageName.get(packageName) === entry) {
                entry.promise = null;
                if (result.type === 'error') {
                    sourceDevSharedDepsPreflightByPackageName.delete(packageName);
                } else {
                    entry.result = result;
                }
            }
            return result;
        } catch (error) {
            if (sourceDevSharedDepsPreflightByPackageName.get(packageName) === entry) {
                sourceDevSharedDepsPreflightByPackageName.delete(packageName);
            }
            throw error;
        }
    }

    async function runSourceDevSharedDepsPreflight(
        packageName: string,
        options?: Readonly<{ admittedCopyOnly?: boolean }>,
    ): Promise<SourceDevSharedDepsPreflightResult> {
        if (options?.admittedCopyOnly) {
            return await runSourceDevSharedDepsPreflightForPackage(packageName, options);
        }
        const batchTarget = resolveSourceDevSharedDepsBatchTarget();
        if (!batchTarget) {
            return await runSourceDevSharedDepsPreflightForPackage(packageName);
        }
        if (sourceDevSharedDepsBatchFallbackReady) {
            return await runSourceDevSharedDepsPreflightForPackage(packageName);
        }

        sourceDevSharedDepsBatchPreflight ??= Promise.resolve()
            .then(() => prepareSourceDevSharedDeps({
                ...batchTarget,
                ...(params.signal ? { signal: params.signal } : {}),
            }))
            .then((result): SourceDevSharedDepsBatchPreflightOutcome => (
                result.type === 'ready'
                    ? { type: 'ready', result }
                    : { type: 'targeted-fallback' }
            ))
            .catch((): SourceDevSharedDepsBatchPreflightOutcome => ({
                type: 'targeted-fallback',
            }));

        const batchOutcome = await sourceDevSharedDepsBatchPreflight;
        params.signal?.throwIfAborted();
        if (batchOutcome.type === 'ready') {
            return batchOutcome.result;
        }
        sourceDevSharedDepsBatchFallbackReady = true;
        return await runSourceDevSharedDepsPreflightForPackage(packageName);
    }

    return function resolveBundledActivationSource(target: BundledActivationTarget,
        options: BundledActivationSourceSelectionOptions = {}): BundledActivationSource | null {
        // Account portable code has declaration custody even when this bundled
        // package has no daemon entry. It is still selected by the existing
        // host declaration/root owner, never by an arbitrary local pathname.
        if (options.realm === 'account' || target.account || (!target.daemonEntryPath && target.sourceSpec?.kind === 'bundled')) {
            const packageName = target.sourceSpec?.kind === 'bundled' ? target.sourceSpec.locator : null;
            if (!packageName || !bundledPackageNames.has(packageName)) return null;
            const declaration = (params.bundledDeclarations ?? loadCurrentBundledPluginLocatorResult().loadedPlugins)
                .find(plugin => plugin.pluginId === target.pluginId && plugin.sourceSpec.kind === 'bundled'
                    && plugin.sourceSpec.locator === packageName);
            if (!declaration || !target.manifest || !target.pluginRootPath) return null;
            if (target.manifest.id !== declaration.manifest.id || target.manifest.version !== declaration.manifest.version) return null;
            if (!isAbsolute(declaration.pluginRootPath) || !isAbsolute(target.pluginRootPath)) return null;
            let packageRoot: string;
            try {
                packageRoot = realpathSync(declaration.pluginRootPath);
                if (realpathSync(target.pluginRootPath) !== packageRoot) return null;
                if (params.packagedRuntimeRoot) {
                    const expectedRoot = realpathSync(resolve(params.packagedRuntimeRoot, 'node_modules',
                        ...parseContainedPackageNameSegments(packageName)));
                    if (expectedRoot !== packageRoot || !params.packagedRuntime) return null;
                }
            } catch {
                // Missing/unreadable bytes refuse this source through the existing
                // per-plugin selection, rather than aborting the entire census.
                return null;
            }
            const sourceAuthority = bindPluginRuntimeSourceAuthority({ custody: {
                kind: 'bundled_first_party', packagedRuntime: params.packagedRuntimeRoot && params.packagedRuntime
                    ? params.packagedRuntime
                    : { kind: 'source_declaration', packageName },
            }, resolvedRoot: packageRoot });
            return {
                kind: 'bundled', moduleId: packageName, sourceAuthority,
                prepare: async () => {
                    params.signal?.throwIfAborted();
                    const metadataPath = join(packageRoot, 'package.json');
                    const metadata = await lstat(metadataPath);
                    if (metadata.isSymbolicLink() || !metadata.isFile()) throw new Error('Bundled Account package metadata must be a regular file');
                    const packageMetadata: unknown = JSON.parse(await readFile(metadataPath, 'utf8'));
                    if (!packageMetadata || typeof packageMetadata !== 'object' || Reflect.get(packageMetadata, 'name') !== packageName) {
                        throw new Error('Bundled Account package identity mismatch');
                    }
                    if (params.packagedRuntimeRoot) {
                        const manifestPath = join(packageRoot, '.happier-plugin', 'plugin.json');
                        const metadata = await lstat(manifestPath);
                        if (metadata.isSymbolicLink() || !metadata.isFile()) throw new Error('Bundled Account manifest must be a regular file');
                        const manifest = readCanonicalPluginManifest(JSON.parse(await readFile(manifestPath, 'utf8')));
                        if (!manifest || manifest.id !== declaration.manifest.id || manifest.version !== declaration.manifest.version) {
                            throw new Error('Bundled Account declaration mismatch');
                        }
                    }
                },
                load: async () => { throw new Error('Bundled Account execution requires its declared Account artifact'); },
                resolveRelativeModule: async () => { throw new Error('Bundled Account execution requires its declared Account artifact'); },
            };
        }
        if (!target.daemonEntryPath || !bundledPackageNames.has(target.daemonEntryPath)) {
            return null;
        }
        const daemonEntryPath = target.daemonEntryPath;
        const resolveSourceDevEntry = (): Readonly<{
            entryPath: string;
            rootPath: string;
            loadMode: 'source-ts';
        }> | null => {
            if (!canImportFirstPartyPluginSource()) return null;
            if (immutableArtifactPackageNames.has(daemonEntryPath)) {
                return null;
            }
            const pluginId = parseFirstPartyPluginIdFromPackageName(daemonEntryPath);
            if (!pluginId) return null;
            const packageRoot = resolve(repoRoot, 'packages', 'plugins', pluginId);
            const entryPath = resolve(packageRoot, 'src', 'index.ts');
            return existsSync(entryPath)
                ? { entryPath, rootPath: packageRoot, loadMode: 'source-ts' }
                : null;
        };
        let prepared = false;
        const prepare = async (): Promise<void> => {
            params.signal?.throwIfAborted();
            if (prepared) return;
            const pluginId = parseFirstPartyPluginIdFromPackageName(daemonEntryPath);
            const sourceDevEntry = resolveSourceDevEntry();
            const canImportSource = canImportFirstPartyPluginSource();
            if (
                pluginId
                && !immutableArtifactEntryPathsByPackageName.has(daemonEntryPath)
                && canImportSource
                && (
                    sourceDevEntry
                    || !immutableArtifactPackageNames.has(daemonEntryPath)
                )
            ) {
                const preflight = await runSourceDevSharedDepsPreflight(
                    daemonEntryPath,
                    sourceDevEntry ? undefined : { admittedCopyOnly: true },
                );
                params.signal?.throwIfAborted();
                if (preflight.type === 'error') {
                    throw new Error(preflight.errorMessage);
                }
            }
            const packagedEntryPath =
                immutableArtifactEntryPathsByPackageName.get(daemonEntryPath);
            const packagedRootPath =
                immutableArtifactRootPathsByPackageName.get(daemonEntryPath);
            if (packagedEntryPath && packagedRootPath) {
                const [entryMetadata, packageMetadataFile, manifestMetadata] =
                    await Promise.all([
                        lstat(packagedEntryPath),
                        lstat(join(packagedRootPath, 'package.json')),
                        lstat(join(
                            packagedRootPath,
                            '.happier-plugin',
                            'plugin.json',
                        )),
                    ]);
                if (
                    entryMetadata.isSymbolicLink()
                    || !entryMetadata.isFile()
                    || packageMetadataFile.isSymbolicLink()
                    || !packageMetadataFile.isFile()
                    || manifestMetadata.isSymbolicLink()
                    || !manifestMetadata.isFile()
                ) {
                    throw new Error(`Bundled plugin '${target.pluginId}' packaged files must be regular files`);
                }
                const canonicalRoot = realpathSync(packagedRootPath);
                const canonicalEntry = realpathSync(packagedEntryPath);
                if (
                    !isCanonicalAbsolutePathInsideRoot(canonicalRoot, canonicalEntry)
                ) {
                    throw new Error(`Bundled plugin '${target.pluginId}' packaged entry escapes its runtime root`);
                }
                const packageMetadata = JSON.parse(
                    await readFile(join(canonicalRoot, 'package.json'), 'utf8'),
                ) as unknown;
                if (
                    !packageMetadata
                    || typeof packageMetadata !== 'object'
                    || Array.isArray(packageMetadata)
                    || !('name' in packageMetadata)
                    || packageMetadata.name !== daemonEntryPath
                ) {
                    throw new Error(`Bundled plugin '${target.pluginId}' packaged metadata name mismatch`);
                }
                const manifest = readCanonicalPluginManifest(JSON.parse(
                    await readFile(
                        join(canonicalRoot, '.happier-plugin', 'plugin.json'),
                        'utf8',
                    ),
                ) as unknown);
                const daemonEntrypoint = manifest?.entrypoints?.daemon;
                const expectedEntry = daemonEntrypoint
                    ? realpathSync(resolve(
                        canonicalRoot,
                        ...parseContainedManifestModulePath(
                            daemonEntrypoint,
                        ),
                    ))
                    : null;
                if (
                    !manifest
                    || manifest.id !== target.pluginId
                    || expectedEntry !== canonicalEntry
                ) {
                    throw new Error(`Bundled plugin '${target.pluginId}' packaged manifest locator mismatch`);
                }
            }
            prepared = true;
        };

        const resolveSelectedEntry = (): Readonly<{
            entryPath: string;
            rootPath: string;
            loadMode: 'immutable-js' | 'source-ts';
        }> | null => {
            const immutableArtifactEntryPath = immutableArtifactEntryPathsByPackageName.get(daemonEntryPath);
            if (immutableArtifactEntryPath) {
                return {
                    entryPath: immutableArtifactEntryPath,
                    rootPath: immutableArtifactRootPathsByPackageName.get(daemonEntryPath)
                        ?? dirname(immutableArtifactEntryPath),
                    loadMode: 'immutable-js',
                };
            }
            const sourceDevEntry = resolveSourceDevEntry();
            if (sourceDevEntry) return sourceDevEntry;
            if (
                immutableArtifactPackageNames.has(daemonEntryPath)
                || unavailableImmutableArtifactPackageNames.has(daemonEntryPath)
            ) {
                return null;
            }
            const pluginId = parseFirstPartyPluginIdFromPackageName(daemonEntryPath);
            if (!pluginId) return null;
            const packageRoot = resolve(repoRoot, 'packages', 'plugins', pluginId);
            const distEntryPath = resolve(packageRoot, 'dist', 'index.js');
            if (existsSync(distEntryPath)) {
                return { entryPath: distEntryPath, rootPath: packageRoot, loadMode: 'immutable-js' };
            }
            return null;
        };
        const selectedForAuthority = resolveSelectedEntry();
        // Custody follows where the bytes come from, not how they load: an
        // admitted immutable artifact belongs to the packaged runtime; the
        // checkout package root (its source, or its built `dist` when this host
        // cannot import source) is a first-party development root.
        const selectedPackagedArtifact = selectedForAuthority !== null
            && selectedForAuthority.entryPath === immutableArtifactEntryPathsByPackageName.get(daemonEntryPath);
        const sourceAuthority = selectedForAuthority
            ? selectedPackagedArtifact
                ? params.packagedRuntime
                    ? bindPluginRuntimeSourceAuthority({
                        custody: {
                            kind: 'bundled_first_party',
                            packagedRuntime: params.packagedRuntime,
                        },
                        resolvedRoot: selectedForAuthority.rootPath,
                    })
                    : null
                : params.resolveDevelopmentSourceAuthority?.({
                    pluginId: target.pluginId,
                    rootPath: selectedForAuthority.rootPath,
                }) ?? null
            : null;

        const resolveRelativeModuleFromSelected = async (
            module: string,
            selected: Readonly<{
                entryPath: string;
                rootPath: string;
                loadMode: 'immutable-js' | 'source-ts';
            }>,
        ): Promise<PluginRelativeModuleResolution<Record<string, unknown>>> => {
            const candidateBase = resolve(dirname(selected.entryPath), module);
            const extensionCandidates = resolvePluginModuleCandidatePaths({
                candidateBase,
                loadMode: selected.loadMode,
            });
            let existingCandidate: string | null = null;
            let lexicalModuleMetadata: Awaited<ReturnType<typeof lstat>> | null = null;
            for (const candidate of extensionCandidates) {
                if (!existsSync(candidate)) continue;
                const candidateMetadata = await lstat(candidate);
                if (
                    !candidateMetadata.isSymbolicLink()
                    && !candidateMetadata.isFile()
                ) {
                    continue;
                }
                existingCandidate = candidate;
                lexicalModuleMetadata = candidateMetadata;
                break;
            }
            if (!existingCandidate || !lexicalModuleMetadata) {
                throw new Error(`Runner module '${module}' was not found in bundled plugin '${daemonEntryPath}'`);
            }
            if (
                lexicalModuleMetadata.isSymbolicLink()
                || !lexicalModuleMetadata.isFile()
            ) {
                throw new Error(`Runner module '${module}' must be a real bundled plugin file`);
            }
            const entryPath = realpathSync(selected.entryPath);
            const modulePath = realpathSync(existingCandidate);
            const rootPath = realpathSync(selected.rootPath);
            const relativeModulePath = relative(rootPath, modulePath);
            if (
                modulePath === rootPath
                || !isCanonicalAbsolutePathInsideRoot(rootPath, modulePath)
            ) {
                throw new Error(`Runner module '${module}' escapes bundled plugin '${daemonEntryPath}'`);
            }
            if (modulePath === entryPath) {
                throw new Error(`Runner module '${module}' must be a leaf distinct from the plugin activation entry`);
            }
            const normalizedModulePath =
                relativeModulePath.split(sep).join('/');
            const moduleNamespace = (
                await loadImport(pathToFileURL(modulePath).href, { loadMode: selected.loadMode })
            ) as Record<string, unknown>;
            return Object.freeze({
                module: moduleNamespace,
                normalizedModulePath,
                loadMode: selected.loadMode,
            });
        };
        const resolveRelativeModule = async (
            module: string,
        ): Promise<PluginRelativeModuleResolution<Record<string, unknown>>> => {
            await prepare();
            const selected = resolveSelectedEntry();
            if (!selected) {
                throw new Error(`Bundled plugin '${daemonEntryPath}' has no file-backed runner module root`);
            }
            return await resolveRelativeModuleFromSelected(
                module,
                selected,
            );
        };

        return {
            kind: 'bundled' as const,
            moduleId: daemonEntryPath,
            get processEntry() {
                return resolveSelectedEntry() ?? undefined;
            },
            ...(sourceAuthority ? { sourceAuthority } : {}),
            prepare,
            resolveRelativeModule,
            load: async () => {
                await prepare();
                const selectedEntry = resolveSelectedEntry();
                if (selectedEntry) {
                    return await loadImport(
                        pathToFileURL(selectedEntry.entryPath).href,
                        { loadMode: selectedEntry.loadMode },
                    );
                }
                if (
                    immutableArtifactPackageNames.has(daemonEntryPath)
                    || unavailableImmutableArtifactPackageNames.has(daemonEntryPath)
                ) {
                    throw new Error(`Bundled immutable artifact is unavailable for '${daemonEntryPath}'`);
                }

                return await loadImport(daemonEntryPath, { loadMode: 'immutable-js' });
            },
        };
    };
}
