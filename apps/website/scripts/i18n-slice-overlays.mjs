/**
 * Per-route translation slices.
 *
 * THE DEFECT THIS EXISTS FOR. Every localised client entry imported its whole
 * locale:
 *
 *     import overlay from '../i18n/messages/overlays/ru.json';
 *
 * That file is 310 KB of source and 75 KB gzipped — every id on the site, all
 * 958 of them. So `/ru/agents/auggie` downloaded the Russian for /ru/security,
 * /ru/enterprise and twelve other agents in order to render one page, and it
 * downloaded it as JavaScript on top of an HTML document that already contained
 * every one of those sentences. Measured on the build before this script: `ru`
 * was the heaviest route on the site at 173.8 KB gzip, 75 KB of it this file.
 *
 * HOW A SLICE IS DERIVED. By rendering the route and recording which of the 15
 * data modules it READ, then keeping every id in those namespaces.
 *
 * The first version of this script matched on output instead: keep an id when
 * its translated value appears in the route's HTML. That found almost nothing
 * and all 210 routes failed the gate below, for a reason worth writing down —
 * RevealText and HeroHeadline split prose into one span per word
 * (src/i18n/segmentWords.ts), so a translated sentence is never present in the
 * document as a contiguous string. Reading is the signal that survives
 * rendering; the rendered bytes are not.
 *
 * Namespace granularity, not id granularity, because `useSiteData()` hands out
 * an object and consumers destructure it — `const { pageProse } = useSiteData()`
 * is a property access a Proxy can observe, whereas which of pageProse's 233
 * ids a page ends up reading is buried in component internals. Namespaces are
 * also where the weight is: `agents` alone is 31% of the Russian overlay and is
 * read by 14 of 21 pages.
 *
 * WHY IT IS SAFE. Over-inclusion costs bytes, never correctness. Under-inclusion
 * is caught by the gate: the route is re-rendered with the slice alone
 * registered and the bytes must equal the full-overlay render, or that route
 * keeps its whole locale and says so. The optimisation applies only where it is
 * provably invisible.
 *
 * (LocaleSuggestion is the one component that renders client-only. It reads
 * LOCALE_META from src/i18n rather than siteData, so it is not exposed to this
 * — a fact worth re-checking if it ever starts reading siteData.)
 *
 * Run after `yarn build:server` and before `yarn build:client`, which is the
 * order `yarn build` uses — the slices are inputs to the client bundle.
 */
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, '..');
const SSR_ENTRY = join(ROOT, 'dist/.ssr/entry-server.js');
const OVERLAY_DIR = join(ROOT, 'src/i18n/messages/overlays');
const OUT_DIR = join(ROOT, 'src/i18n/generated/slices');

const kb = (n) => `${(n / 1024).toFixed(1)} KB`;

function overlayLocales() {
    if (!existsSync(OVERLAY_DIR)) return [];
    return readdirSync(OVERLAY_DIR)
        .filter((f) => f.endsWith('.json') && f !== 'routeMeta.json')
        .map((f) => f.slice(0, -'.json'.length))
        .sort();
}

/**
 * `src/entries/agents--auggie.tsx` → `agents--auggie`.
 */
function entrySlug(clientEntry) {
    const m = /src\/entries\/(.+)\.tsx$/.exec(clientEntry);
    if (!m) throw new Error(`Unrecognised clientEntry: ${clientEntry}`);
    return m[1];
}

/**
 * The ENGLISH slug for a localised route, which is the name the slice takes.
 *
 * Deliberately not string-surgery on the localised entry name. Two things break
 * that: the URL prefix is not the locale code (`/zh` is `zh-Hans`, so stripping
 * `${locale}--` strips nothing), and the home route's entry is `home.tsx` while
 * its localised entries are bare `zh.tsx` / `ru.tsx` with no `--` at all. Both
 * produced files scripts/i18n-generate-entries.mjs then could not import.
 *
 * Looking the English route up by path has neither problem, and it uses the
 * same mapping the generator does rather than a second copy of the rule.
 */
function englishSlugFor(route, englishSlugByPath) {
    const withoutLocale = route.path.replace(/^\/[^/]+/, '') || '/';
    const slug = englishSlugByPath.get(withoutLocale);
    if (!slug) {
        throw new Error(
            `No English route matches ${route.path} (looked for ${withoutLocale}). ` +
                'Every localised route must correspond to one, or the slice has no name.',
        );
    }
    return slug;
}

/**
 * The entries are COMMITTED and are not regenerated by `yarn build`, so the
 * namespace list baked into each one can fall behind the manifest this script
 * just wrote. That is the one way this optimisation can ship a hole: a page
 * starts reading a namespace, the slicer notices and records it, and the entry
 * still imports the old set — so the page renders correctly at build time and
 * falls back to English in the browser.
 *
 * The gate above cannot see that; it tests slices, not entries. This does.
 */
function verifyEntriesMatchManifest(locale, manifest, prefixFor) {
    const problems = [];
    for (const [slug, namespaces] of Object.entries(manifest)) {
        const entryFile = join(ROOT, 'src/entries', `${prefixFor(slug)}.tsx`);
        if (!existsSync(entryFile)) {
            problems.push(`  missing entry ${entryFile.replace(ROOT + '/', '')}`);
            continue;
        }
        const src = readFileSync(entryFile, 'utf8');
        const imported = [...src.matchAll(/generated\/slices\/[^/]+\/([^']+)\.json/g)].map((m) => m[1]).sort();
        const expected = [...namespaces].sort();
        if (imported.join(',') !== expected.join(',')) {
            problems.push(
                `  ${prefixFor(slug)}.tsx imports [${imported.join(', ')}] but ${locale} reads ` +
                    `[${expected.join(', ')}]`,
            );
        }
    }
    return problems;
}

async function main() {
    if (!existsSync(SSR_ENTRY)) {
        throw new Error(
            `No SSR bundle at dist/.ssr/entry-server.js. Run \`yarn build:server\` first — ` +
                'the slicer renders every route to find which ids that route actually uses.',
        );
    }

    const { render, routeManifest, registerOverlay, __recordNamespaceReads } = await import(
        pathToFileURL(SSR_ENTRY).href,
    );

    const locales = overlayLocales();
    if (locales.length === 0) {
        console.log('i18n-slice-overlays: no overlays to slice.');
        return;
    }

    rmSync(OUT_DIR, { recursive: true, force: true });
    mkdirSync(OUT_DIR, { recursive: true });

    const routes = routeManifest();
    const englishSlugByPath = new Map(
        routes.filter((r) => r.locale === 'en').map((r) => [r.path, entrySlug(r.clientEntry)]),
    );
    let keptFull = 0;
    const staleEntries = [];
    let totalBefore = 0;
    let totalAfter = 0;

    for (const locale of locales) {
        const full = JSON.parse(readFileSync(join(OVERLAY_DIR, `${locale}.json`), 'utf8'));
        const entries = Object.entries(full);
        const fullBytes = Buffer.byteLength(JSON.stringify(full));

        mkdirSync(join(OUT_DIR, locale), { recursive: true });

        const localeRoutes = routes.filter((r) => r.locale === locale);

        /*
         * ONE FILE PER NAMESPACE, NOT PER ROUTE.
         *
         * Two earlier shapes were wrong in opposite directions. A self-contained
         * slice per route was right per visitor and terrible on disk — 210 files
         * with no sharing took dist/ from 24 MB to 42 MB, because `agents` (31%
         * of a locale) was copied into all 14 agent routes. Splitting out the
         * all-routes intersection helped (34 MB) but not enough: `agents` is
         * common to 14 routes and to no others, so it still landed in 14 deltas.
         *
         * Emitting the namespace itself as the unit lets Rollup do the sharing
         * it already does for code — 14 entries importing the same agents.json
         * get one chunk between them. Disk goes back to roughly the original
         * total while each route still downloads only what it reads.
         */
        const byNamespace = new Map();
        for (const [id, value] of entries) {
            const ns = id.split('.', 1)[0];
            let bucket = byNamespace.get(ns);
            if (!bucket) byNamespace.set(ns, (bucket = {}));
            bucket[id] = value;
        }

        const written = new Set();
        const manifest = {};

        for (const route of localeRoutes) {
            registerOverlay(locale, full);
            const expected = render(route.path);

            const touched = new Set();
            __recordNamespaceReads(touched);
            render(route.path);
            __recordNamespaceReads(null);

            const used = [...touched].filter((ns) => byNamespace.has(ns)).sort();
            const merged = {};
            for (const ns of used) Object.assign(merged, byNamespace.get(ns));

            // The gate. What the entry will register is the union of the files
            // it imports; the page that produces must be the page the full
            // overlay produced, byte for byte.
            registerOverlay(locale, merged);
            const actual = render(route.path);
            const name = englishSlugFor(route, englishSlugByPath);

            let namespaces = used;
            if (actual !== expected) {
                // Fall back to the whole locale for this route, as one file it
                // alone imports. Never ship a hole.
                keptFull += 1;
                namespaces = [`_full--${name}`];
                byNamespace.set(`_full--${name}`, full);
                console.log(
                    `  ! ${route.path} kept the full overlay: the namespaces it reads did not ` +
                        'reproduce its HTML.',
                );
            }
            registerOverlay(locale, full);

            manifest[name] = namespaces;
            for (const ns of namespaces) {
                if (written.has(ns)) continue;
                written.add(ns);
                const json = JSON.stringify(byNamespace.get(ns));
                writeFileSync(join(OUT_DIR, locale, `${ns}.json`), json);
                totalAfter += Buffer.byteLength(json);
            }
            totalBefore += fullBytes;
        }

        writeFileSync(join(OUT_DIR, locale, '_routes.json'), JSON.stringify(manifest, null, 1));

        const prefix = localeRoutes.length > 0 ? localeRoutes[0].path.split('/')[1] : locale;
        staleEntries.push(
            ...verifyEntriesMatchManifest(locale, manifest, (slug) =>
                slug === englishSlugByPath.get('/') ? prefix : `${prefix}--${slug}`,
            ),
        );
    }

    if (staleEntries.length > 0) {
        console.error(
            'i18n-slice-overlays: these entries no longer match what their route reads.\n' +
                'Run `node scripts/i18n-generate-entries.mjs --write`.\n' +
                staleEntries.join('\n'),
        );
        process.exitCode = 1;
    }

    const saved = totalBefore - totalAfter;
    console.log(
        `i18n-slice-overlays: ${routes.filter((r) => locales.includes(r.locale)).length} localised ` +
            `route(s); ${kb(totalBefore)} of overlay imports became ${kb(totalAfter)} ` +
            `(${((100 * saved) / totalBefore).toFixed(1)}% less), ${keptFull} kept whole by the gate.`,
    );
}

main().catch((error) => {
    console.error(`i18n-slice-overlays failed: ${error.message}`);
    process.exit(1);
});
