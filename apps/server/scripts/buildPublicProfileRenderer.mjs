import { randomUUID } from 'node:crypto';
import { build } from 'esbuild';
import { copyFile, mkdir, readFile, rename, rm, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { PUBLIC_RENDERER_ASSET_PATHS } from './publicRendererAssetPaths.mjs';
import { readPublicProfileAssetFiles } from './publicProfileAssetFiles.mjs';

const defaultProjectDir = resolve(dirname(fileURLToPath(import.meta.url)), '..');

/** Bind the actual portable page to the server's declared RNW renderer, without an app runtime. */
export async function buildPublicProfileRenderer({ projectDir = defaultProjectDir, check = false, printPatch = false, traceInputs = false } = {}) {
    const requireServer = createRequire(resolve(projectDir, 'package.json'));
    const target = resolve(projectDir, PUBLIC_RENDERER_ASSET_PATHS.profile);
    const sourceDir = dirname(target);
    const repoRoot = resolve(projectDir, '../..');
    // One RNW instance: the page's StyleSheet rules and the sheet the renderer serializes must be the same module.
    const reactNativeWeb = requireServer.resolve('react-native-web/dist/index.js');
    const result = await build({
        absWorkingDir: repoRoot,
        metafile: traceInputs, entryPoints: [resolve(sourceDir, 'publicProfileRenderer.ts')],
        bundle: true, write: false, minify: true, platform: 'node', format: 'esm', target: ['node20'], jsx: 'automatic',
        tsconfig: resolve(projectDir, 'tsconfig.json'), conditions: ['happier-source'],
        external: ['react', 'react-dom/server', 'react/jsx-runtime'],
        // Bundled CommonJS dependencies can require Node built-ins on first import.
        banner: { js: "import { createRequire as __publicProfileCreateRequire } from 'node:module'; const require = __publicProfileCreateRequire(import.meta.url);" },
        alias: {
            // Resolve from the workspace root while retaining esbuild's TS and package metadata.
            '@happier-dev/protocol': '@happier-dev/protocol',
            'react-native': reactNativeWeb,
            'react-native-web': reactNativeWeb,
            'react-native-svg': requireServer.resolve('react-native-svg/lib/module/elements.web.js'),
        },
        define: { 'process.env.NODE_ENV': '"production"', '__DEV__': 'false' },
        legalComments: 'eof',
    });
    const source = '// Generated by scripts/buildPublicProfileRenderer.mjs; do not edit.\n' + result.outputFiles[0].text;
    if (printPatch) {
        // stdout is a generator transport for remote execution, not runtime code.
        process.stdout.write(`*** Begin Patch\n*** Add File: ${target}\n${source.replace(/\n$/u, '').split('\n').map(line => '+' + line).join('\n')}\n*** End Patch\n`);
        return;
    }
    const current = await readFile(target, 'utf8').catch(error => {
        if (error.code === 'ENOENT') return null;
        throw error;
    });
    if (check && current !== source) throw new Error('Public-profile renderer is stale; run build:public-profile');
    if (!check && current !== source) {
        const staged = `${target}.${randomUUID()}.tmp`;
        try {
            await writeFile(staged, source);
            await rename(staged, target);
        } finally {
            await rm(staged, { force: true });
        }
    }
    return { inputPaths: Object.keys(result.metafile?.inputs ?? {}).map(path => resolve(repoRoot, path)) };
}

export { readPublicProfileAssetFiles };

/** Retain the exact shipped faces and licenses, without a runtime source-tree dependency. */
export async function stagePublicProfileAssets({ projectDir = defaultProjectDir, outDir }) {
    const target = resolve(outDir, 'assets/public-profile');
    await mkdir(target, { recursive: true });
    const files = await readPublicProfileAssetFiles({ projectDir });
    for (const { filename, sourcePath } of files) await copyFile(sourcePath, resolve(target, filename));
    return files.map(({ filename }) => resolve(target, filename));
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    await buildPublicProfileRenderer({ check: process.argv.includes('--check'), printPatch: process.argv.includes('--print-patch') });
}
