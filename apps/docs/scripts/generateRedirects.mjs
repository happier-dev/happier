#!/usr/bin/env node
/**
 * Writes public/_redirects from ../redirects.mjs, before every build.
 *
 * WHY THIS EXISTS. `output: 'export'` drops `redirects()` without erroring, so
 * the 160 permanent moves this site has made would silently stop working the
 * moment it was exported. The Cloudflare Workers asset layer reads `_redirects`
 * natively and applies it ahead of any asset match, so the rules survive — but
 * only if something writes the file, and only if that something runs from the
 * same list the rest of the repo edits. That is this script.
 *
 * WHY GENERATED RATHER THAN HAND-MAINTAINED. A hand-written _redirects and a
 * redirects.mjs would drift, and the drift is invisible: the build is green
 * either way and the damage lands on old URLs nobody on the team visits.
 *
 * ORDERING IS LOAD-BEARING. Cloudflare applies the FIRST matching rule, so a
 * splat rule listed above the exact paths it covers swallows them. `/docs/:path*`
 * must not precede `/docs`, and neither may precede any exact rule under them.
 * Exact rules are therefore emitted first, splats last, regardless of the order
 * they appear in the source list.
 */

import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { REDIRECTS } from '../redirects.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const packageRoot = path.resolve(here, '..');

/** Next's `:path*` is Cloudflare's `:splat`, and only in the destination. */
function toCloudflare(rule) {
    const source = rule.source.replace(/\/:path\*$/, '/*');
    const destination = rule.destination.replace(/\/:path\*$/, '/:splat');
    const status = rule.permanent ? 301 : 302;
    return { source, destination, status, isSplat: source.endsWith('/*') };
}

export function renderRedirects(rules = REDIRECTS) {
    const mapped = rules.map(toCloudflare);
    const exact = mapped.filter((r) => !r.isSplat);
    const splat = mapped.filter((r) => r.isSplat);
    const ordered = [...exact, ...splat];

    const width = Math.max(...ordered.map((r) => r.source.length));
    const body = ordered
        .map((r) => `${r.source.padEnd(width)}  ${r.destination}  ${r.status}`)
        .join('\n');

    return [
        '# GENERATED by scripts/generateRedirects.mjs from redirects.mjs — do not edit.',
        '#',
        '# Exact rules first, splats last: Cloudflare applies the first match, so a',
        '# splat above an exact path under it would swallow that path.',
        '',
        body,
        '',
    ].join('\n');
}

if (import.meta.url === `file://${process.argv[1]}`) {
    const out = path.join(packageRoot, 'public', '_redirects');
    await mkdir(path.dirname(out), { recursive: true });
    await writeFile(out, renderRedirects(), 'utf8');
    console.log(`generateRedirects: wrote ${REDIRECTS.length} rules to public/_redirects`);
}
