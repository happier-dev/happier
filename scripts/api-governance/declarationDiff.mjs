function normalizeHeading(heading) {
  return heading.slice(4).replaceAll('`', '');
}

function declarationBlocks(contents) {
  const blocks = new Map();
  let heading;
  let lines = [];
  const commit = () => {
    if (heading !== undefined) blocks.set(normalizeHeading(heading), lines.join('\n'));
  };
  for (const line of contents.split('\n')) {
    if (line.startsWith('### `')) {
      commit();
      heading = line;
      lines = [line];
      continue;
    }
    if (heading !== undefined) lines.push(line);
  }
  commit();
  return blocks;
}

/**
 * Names the bounded set of declaration blocks responsible for a report drift.
 * This is intentionally a presentation helper over generated bytes, not a
 * second declaration scanner or compatibility classifier.
 */
export function summarizeDeclarationDiff(previousContents, nextContents, limit = 5) {
  if (previousContents === nextContents) return Object.freeze([]);
  const previous = declarationBlocks(previousContents ?? '');
  const next = declarationBlocks(nextContents);
  const headings = new Set([...previous.keys(), ...next.keys()]);
  return Object.freeze(
    [...headings]
      .filter((heading) => previous.get(heading) !== next.get(heading))
      .sort((left, right) => left.localeCompare(right))
      .slice(0, limit),
  );
}
