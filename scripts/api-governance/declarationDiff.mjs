function normalizeHeading(heading) {
  return heading.slice(4).replaceAll('`', '');
}

function declarationBlocks(contents) {
  const blocks = new Map();
  let heading;
  let lines = [];
  const commit = () => {
    if (heading !== undefined) blocks.set(normalizeHeading(heading), lines.join('\n'));
  };
  for (const line of contents.split('\n')) {
    if (line.startsWith('### `')) {
      commit();
      heading = line;
      lines = [line];
      continue;
    }
    if (heading !== undefined) lines.push(line);
  }
  commit();
  return blocks;
}

/**
 * Names every declaration block responsible for a report drift. The complete
 * identity list is the comparison fact; bounding happens only at display time
 * through `renderDeclarationDiffSample`, never by dropping facts here. This is
 * intentionally a presentation helper over generated bytes, not a second
 * declaration scanner or compatibility classifier.
 */
export function summarizeDeclarationDiff(previousContents, nextContents) {
  if (previousContents === nextContents) return Object.freeze([]);
  const previous = declarationBlocks(previousContents ?? '');
  const next = declarationBlocks(nextContents);
  const headings = new Set([...previous.keys(), ...next.keys()]);
  return Object.freeze(
    [...headings]
      .filter((heading) => previous.get(heading) !== next.get(heading))
      .sort((left, right) => left.localeCompare(right)),
  );
}

/**
 * Bounds a complete changed-block identity list for human display. A truncated
 * sample always carries a label naming the unshown remainder, so bounded log
 * output can never be mistaken for the complete fact set.
 */
export function renderDeclarationDiffSample(changedBlocks, limit = 5) {
  const sample = changedBlocks.slice(0, limit);
  const remaining = changedBlocks.length - sample.length;
  return Object.freeze(remaining > 0
    ? [...sample, `… and ${remaining} more changed declaration blocks (${changedBlocks.length} total)`]
    : [...sample]);
}
