  'COREPACK_NPM_PASSWORD',
  'COREPACK_INTEGRITY_KEYS',
  'COREPACK_ENABLE_PROJECT_SPEC',
  'YARN_PATH',
  'YARN_RC_FILENAME',
  'YARN_NPM_AUTH_TOKEN',
