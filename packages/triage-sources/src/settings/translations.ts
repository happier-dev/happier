/**
 * A dependency-light manifest helper. Every locale receives the complete shared
 * key set, then its translated overrides. Provider-local messages remain local.
 */
export const TRIAGE_SOURCE_SETTINGS_TRANSLATIONS_V1 = Object.freeze(
  Object.fromEntries([
    ...Object.entries(EXISTING_TRIAGE_SOURCE_SETTINGS_TRANSLATIONS_V1).map(([locale, messages]) => [
      locale,
      Object.freeze({ ...TRIAGE_SOURCE_SETTINGS_ENGLISH_V1, ...messages }),
    ]),
    ['de', Object.freeze({ ...TRIAGE_SOURCE_SETTINGS_ENGLISH_V1, ...GERMAN_OVERRIDES })],
  ]),
);

export function withTriageSourceSettingsTranslationsV1<
  T extends Readonly<{ locale: string; messages: Readonly<Record<string, string>> }>,
>(rows: readonly T[]): readonly T[] {
  return rows.map((row) => Object.freeze({
    ...row,
    messages: Object.freeze({
      ...TRIAGE_SOURCE_SETTINGS_ENGLISH_V1,
      ...(TRIAGE_SOURCE_SETTINGS_TRANSLATIONS_V1[row.locale] ?? {}),
      ...row.messages,
    }),
  }));
}
