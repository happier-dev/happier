import type { PluginJsonSchema } from '@happier-dev/plugin-sdk/protocol';

/**
 * Derivation of the largest structurally valid encoded value a composable
 * schema admits.
 *
 * `CONTRACT.md` §2.1 and §9 require every value that crosses the host's Action
 * byte gate to be measured as a true worst case derived from the real schema —
 * never from an observed or average sample — and to be re-derived whenever a
 * contributing bound changes. This module is that derivation, and it is
 * published rather than kept beside one test because two consumers need the
 * same answer: this package pins the source-facing operation maxima, and the
 * Triage target pins its own aggregate Action result the same way. A second
 * copy of this walk is exactly how two "worst cases" start disagreeing.
 *
 * Nothing here is hand-built. A maximal value is generated by walking a
 * schema's published JSON Schema projection, and `deriveMaximumEncodedBytes`
 * parses it back through that schema, so a structurally invalid value can never
 * be measured.
 *
 * What the derivation deliberately does not model:
 *
 * - Target-enforced keyed uniqueness is a semantic invariant over the parsed
 *   value, not a structural one. The derivation maximizes over the
 *   schema-admitted set, a superset of what a target accepts, and distinct keys
 *   can only cost bytes — so ignoring it keeps the result an upper bound.
 * - The worst-case fill of a patterned string is found by search
 *   (`buildMaximalSchemaString`), not by solving the pattern. It is exact for
 *   every V1 grammar, and any string the search cannot fill throws instead of
 *   quietly measuring a narrower value.
 */

/**
 * The widest expansion JSON escaping can reach: a code point with no short
 * escape becomes `\uXXXX`.
 */
export const WORST_CASE_JSON_ESCAPE_BYTES = 6;

/**
 * Written into every object whose schema admits unknown properties, so an
 * object that preserves rather than drops one is caught instead of being
 * measured as if its known properties bounded it.
 */
const OPEN_OBJECT_PROBE_KEY = 'happierUnknownPropertyProbeV1';

const utf8Encoder = new TextEncoder();

/** UTF-8 byte length of a string, which is what every V1 byte bound counts. */
export function utf8ByteLength(value: string): number {
    return utf8Encoder.encode(value).length;
}

/** Serialized UTF-8 JSON bytes of a value, which is what the host gate measures. */
export function encodedJsonBytes(value: unknown): number {
    return utf8ByteLength(JSON.stringify(value));
}

/** Encoded bytes one code point costs inside a JSON string, quotes excluded. */
export function jsonEscapedByteCost(codePoint: string): number {
    return utf8ByteLength(JSON.stringify(codePoint)) - 2;
}

export function codePointsOf(value: string): readonly string[] {
    return [...value];
}

/**
 * Every ASCII code point, most expensive first. Deriving the fill alphabet
 * instead of naming a worst-case character is what keeps a string's real
 * grammar — not an assumption about it — decide what the string can carry: a
 * C0 control escapes sixfold and is admitted by any pattern that does not
 * exclude it.
 *
 * ASCII wins every **byte** bound, because encoded cost per UTF-8 byte is
 * highest for a single-byte code point: a control sextuples its one byte and
 * `"` doubles it, while no wider code point is escaped at all and so never
 * exceeds one encoded byte per UTF-8 byte.
 */
export const ASCII_FILL_ALPHABET: readonly string[] = Array.from(
    { length: 128 },
    (_unused, code) => String.fromCharCode(code),
).sort((left, right) => (
    jsonEscapedByteCost(right) - jsonEscapedByteCost(left)
    || left.charCodeAt(0) - right.charCodeAt(0)
));

/**
 * Wider representatives of each UTF-8 encoding width, because a **code-point**
 * bound is maximized by a different code point than a byte bound is.
 *
 * JSON escapes nothing above `U+007F`, so a wider code point costs exactly its
 * UTF-8 width in encoded bytes: two, three, or four. Against a code-point bound
 * that beats every non-control ASCII character — a four-byte code point is
 * twice `\"` — so a grammar that excludes controls but admits ordinary text is
 * measured at half its real maximum by an ASCII-only search. Against a byte
 * bound the same code point buys nothing, and `maximalRepeatCount` is what
 * keeps it from being counted as though it did.
 *
 * Each width carries both a letter-like and a non-letter representative, so a
 * grammar that admits one shape and not the other is still filled. Lone
 * surrogates are deliberately absent: they escape sixfold but are not
 * well-formed Unicode, and the strict JSON boundary rejects them before any
 * value reaches the gate this derivation measures against.
 */
const WIDE_FILL_ALPHABET: readonly string[] = [
    /** Two UTF-8 bytes: a Latin-1 letter and a C1 control. */
    '\u00ff',
    '\u0080',
    /** Three UTF-8 bytes: a CJK ideograph and a Samaritan letter. */
    '\u4e00',
    '\u0800',
    /** Four UTF-8 bytes: an archaic letter and an emoji. */
    '\u{10000}',
    '\u{1f600}',
];

const FILL_ALPHABET: readonly string[] = [...ASCII_FILL_ALPHABET, ...WIDE_FILL_ALPHABET];

/**
 * Seeds for the patterns no uniform fill satisfies. Both are external
 * protocol-owned identity grammars the V1 protocol embeds; a string that needs
 * a third shape throws rather than being measured short.
 */
const STRUCTURED_SEED_BUILDERS: readonly ((size: number) => string)[] = [
    /** A namespaced Plugin id (`PluginIdSchema`), whose pattern requires a dot. */
    (size) => `${'a'.repeat(Math.max(size - 2, 1))}.a`,
    /** A lowercase hex UUID (`TriageSourceInstanceIdV1Schema`), fixed at 36. */
    () => '2f1c9c4e-8c1f-4a53-9c2a-4c9a7b1d3e05',
];

const compiledPatterns = new Map<string, RegExp>();

function admitsString(fragment: PluginJsonSchema, value: string): boolean {
    const length = codePointsOf(value).length;
    if (fragment.minLength !== undefined && length < fragment.minLength) return false;
    if (fragment.maxLength !== undefined && length > fragment.maxLength) return false;
    const maxUtf8Bytes = fragment['x-happier-max-utf8-bytes'];
    if (maxUtf8Bytes !== undefined && utf8ByteLength(value) > maxUtf8Bytes) return false;
    if (fragment.pattern === undefined) return true;
    let pattern = compiledPatterns.get(fragment.pattern);
    if (pattern === undefined) {
        pattern = new RegExp(fragment.pattern, 'u');
        compiledPatterns.set(fragment.pattern, pattern);
    }
    return pattern.test(value);
}

/** Replaces one character with a costlier admitted one, keeping it only if valid. */
function raiseCharacter(
    characters: string[],
    index: number,
    replacement: string,
    admits: (value: string) => boolean,
): boolean {
    const previous = characters[index];
    if (previous === undefined) return false;
    if (jsonEscapedByteCost(previous) >= jsonEscapedByteCost(replacement)) return false;
    characters[index] = replacement;
    if (admits(characters.join(''))) return true;
    characters[index] = previous;
    return false;
}

function cheapestCharacterCost(characters: readonly string[]): number {
    return characters.reduce(
        (cheapest, character) => Math.min(cheapest, jsonEscapedByteCost(character)),
        WORST_CASE_JSON_ESCAPE_BYTES,
    );
}

/**
 * Raises a valid maximal-size fill toward its costliest admitted form.
 *
 * A candidate is probed at the first, second, and last position — the three
 * places a V1 grammar can treat differently — and only a candidate admitted at
 * one of them is swept across the whole string. That keeps the search cheap
 * while still finding a grammar that admits an expensive code point only in the
 * interior, which is exactly how the composite-identifier separator behaves.
 */
function raiseFillCost(seed: string, admits: (value: string) => boolean): string {
    const characters = [...codePointsOf(seed)];
    for (const candidate of ASCII_FILL_ALPHABET) {
        if (jsonEscapedByteCost(candidate) <= cheapestCharacterCost(characters)) break;
        const probes = [0, 1, characters.length - 1].filter((index, position, all) => (
            index >= 0 && index < characters.length && all.indexOf(index) === position
        ));
        const admitted = probes
            .map((index) => raiseCharacter(characters, index, candidate, admits))
            .some((raised) => raised);
        if (!admitted) continue;
        for (let index = 0; index < characters.length; index += 1) {
            raiseCharacter(characters, index, candidate, admits);
        }
    }
    return characters.join('');
}

/**
 * How many times one code point fits, against whichever of the two bounds binds
 * it first.
 *
 * A byte bound is spent by the code point's own UTF-8 width and a code-point
 * bound is not, so the two counts differ for every code point above `U+007F`.
 * Deriving the count per candidate rather than once per fragment is what lets
 * both bounds be maximized by their own worst code point.
 */
function maximalRepeatCount(fragment: PluginJsonSchema, character: string): number {
    const maxUtf8Bytes = fragment['x-happier-max-utf8-bytes'];
    return Math.min(
        maxUtf8Bytes === undefined
            ? Number.POSITIVE_INFINITY
            : Math.floor(maxUtf8Bytes / utf8ByteLength(character)),
        fragment.maxLength ?? Number.POSITIVE_INFINITY,
    );
}

/** The costliest string one string fragment admits, at its maximum size. */
export function buildMaximalSchemaString(fragment: PluginJsonSchema, path: string): string {
    const singleByteSize = maximalRepeatCount(fragment, 'a');
    if (!Number.isFinite(singleByteSize)) {
        throw new Error(`${path}: an unbounded string has no maximum encoded value`);
    }
    const admits = (value: string): boolean => admitsString(fragment, value);
    // Widest by measurement, not by rank: two candidates that differ in UTF-8
    // width fit a different number of times, so cost per code point alone no
    // longer orders them.
    let seed = widestValue(FILL_ALPHABET
        .map((character) => character.repeat(maximalRepeatCount(fragment, character)))
        .filter(admits));
    seed ??= STRUCTURED_SEED_BUILDERS.map((build) => build(singleByteSize)).find(admits);
    if (seed === undefined) {
        throw new Error(`${path}: no admitted maximal fill for pattern ${fragment.pattern ?? 'none'}`);
    }
    return raiseFillCost(seed, admits);
}

/**
 * The longest JSON encodings a finite double reaches — seventeen significant
 * digits with a three-digit exponent, and the same mantissa just inside the
 * fixed-notation boundary — beside the safe-integer extremes an integer field
 * admits. A field's own `minimum`/`maximum` join them, so a narrowly bounded
 * number is measured at its own widest admitted value.
 */
const NUMBER_FILL_CANDIDATES: readonly number[] = [
    Number.MIN_SAFE_INTEGER,
    Number.MAX_SAFE_INTEGER,
    -Number.MAX_VALUE,
    -1.2345678901234567e-308,
    -0.0000012345678901234567,
];

function widestValue<TValue>(values: readonly TValue[]): TValue | undefined {
    return values.reduce<TValue | undefined>((widest, value) => (
        widest === undefined || encodedJsonBytes(value) > encodedJsonBytes(widest) ? value : widest
    ), undefined);
}

function buildMaximalNumber(fragment: PluginJsonSchema, path: string): number {
    const { minimum, maximum } = fragment;
    const integral = fragment.type === 'integer';
    const admitted = [...NUMBER_FILL_CANDIDATES, minimum, maximum]
        .filter((candidate): candidate is number => candidate !== undefined)
        .filter((candidate) => (minimum === undefined || candidate >= minimum))
        .filter((candidate) => (maximum === undefined || candidate <= maximum))
        .filter((candidate) => !integral || Number.isSafeInteger(candidate));
    const widest = widestValue(admitted);
    if (widest === undefined) throw new Error(`${path}: no admitted number`);
    return widest;
}

function buildMaximalObject(fragment: PluginJsonSchema, path: string): Record<string, unknown> {
    const value: Record<string, unknown> = {};
    // Optional properties are always present: an omitted one only costs bytes.
    for (const [key, child] of Object.entries(fragment.properties ?? {})) {
        value[key] = buildMaximalSchemaValue(child, `${path}.${key}`);
    }
    if (fragment.additionalProperties !== false) value[OPEN_OBJECT_PROBE_KEY] = 0;
    return value;
}

function buildMaximalArray(fragment: PluginJsonSchema, path: string): unknown[] {
    const { items, maxItems } = fragment;
    if (items === undefined) throw new Error(`${path}: an array without an item schema has no maximum`);
    if (maxItems === undefined) throw new Error(`${path}: an unbounded array has no maximum`);
    if (fragment.uniqueItems !== true) {
        const item = buildMaximalSchemaValue(items, `${path}[]`);
        return Array.from({ length: maxItems }, () => item);
    }
    // A unique array can only carry as many items as its item schema has
    // distinct maximal values, which for a union is one per arm.
    const distinct = new Map<string, unknown>();
    for (const [index, arm] of (items.anyOf ?? [items]).entries()) {
        const candidate = buildMaximalSchemaValue(arm, `${path}[|${index}]`);
        distinct.set(JSON.stringify(candidate), candidate);
    }
    const ranked = [...distinct.values()]
        .sort((left, right) => encodedJsonBytes(right) - encodedJsonBytes(left))
        .slice(0, maxItems);
    if (ranked.length < (fragment.minItems ?? 0)) {
        throw new Error(`${path}: fewer distinct items than the schema requires`);
    }
    return ranked;
}

/** The largest value one JSON Schema projection admits, at every depth. */
export function buildMaximalSchemaValue(fragment: PluginJsonSchema, path: string): unknown {
    if ('const' in fragment) return fragment.const;
    if (fragment.anyOf !== undefined) {
        const widest = widestValue(fragment.anyOf.map((arm, index) => (
            buildMaximalSchemaValue(arm, `${path}|${index}`)
        )));
        if (widest === undefined) throw new Error(`${path}: an empty union has no maximum`);
        return widest;
    }
    if (fragment.oneOf !== undefined || fragment.allOf !== undefined || fragment.enum !== undefined) {
        throw new Error(`${path}: unsupported schema composition`);
    }
    switch (fragment.type) {
        case 'string': return buildMaximalSchemaString(fragment, path);
        case 'integer':
        case 'number': return buildMaximalNumber(fragment, path);
        case 'boolean': return false;
        case 'null': return null;
        case 'object': return buildMaximalObject(fragment, path);
        case 'array': return buildMaximalArray(fragment, path);
        default: throw new Error(`${path}: unsupported schema keyword set`);
    }
}

/** A composable schema that can both project JSON Schema and parse a value back. */
export type MeasurableSchemaV1 = {
    readonly jsonSchema: PluginJsonSchema;
    parse(value: unknown): unknown;
};

/**
 * Derives, validates, and measures one schema's maximum. Parsing is what makes
 * the number a bound on real values: a derivation the schema rejects throws
 * here instead of being pinned.
 */
export function deriveMaximumEncodedBytes(schema: MeasurableSchemaV1, label: string): number {
    const encoded = JSON.stringify(schema.parse(buildMaximalSchemaValue(schema.jsonSchema, label)));
    if (encoded.includes(OPEN_OBJECT_PROBE_KEY)) {
        throw new Error(`${label}: an unknown property survived parsing, so this value is unbounded`);
    }
    return utf8ByteLength(encoded);
}

/** The same derivation over a labelled set, so a pin names every measured value at once. */
export function deriveMaximumEncodedBytesByLabel<TKey extends string>(
    schemas: Readonly<Record<TKey, MeasurableSchemaV1>>,
): Readonly<Record<TKey, number>> {
    return Object.fromEntries(Object.entries<MeasurableSchemaV1>(schemas).map(([label, schema]) => (
        [label, deriveMaximumEncodedBytes(schema, label)]
    ))) as Record<TKey, number>;
}

/** Collects every leaf string field name reachable from a schema projection. */
export function collectSchemaStringFields(
    fragment: PluginJsonSchema,
    name: string,
    into: Map<string, PluginJsonSchema>,
): void {
    if (fragment.type === 'string') {
        into.set(name, fragment);
        return;
    }
    for (const [key, child] of Object.entries(fragment.properties ?? {})) {
        collectSchemaStringFields(child, key, into);
    }
    if (fragment.items !== undefined) collectSchemaStringFields(fragment.items, name, into);
    for (const [index, arm] of (fragment.anyOf ?? []).entries()) {
        collectSchemaStringFields(arm, `${name}|${index}`, into);
    }
}
