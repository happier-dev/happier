import { describe, expect, it } from 'vitest';

import { parseDeepSecCommentOutMarkdown } from './commentOut.js';
import { normalizeDeepSecFindings } from './findings.js';

describe('parseDeepSecCommentOutMarkdown', () => {
  it('preserves complete native finding titles', () => {
    const title = 'Missing authorization on the administrative account recovery endpoint permits any signed-in user to replace another account recovery credential';
    const entries = parseDeepSecCommentOutMarkdown(`### src/auth.ts:42\n\n${title}\n\nRequire authorization.\n\n### src/fallback.ts\n\nCheck access.`);
    const findings = normalizeDeepSecFindings(entries);
    expect(findings[0]?.title).toBe(title);
    expect(findings[0]?.summary).toContain('Require authorization.');
  });

  it('does not invent issue confidence from anchor certainty', () => {
    const entries = parseDeepSecCommentOutMarkdown('### src/auth.ts:42\n\nRequire authorization.\n\n### src/fallback.ts\n\nCheck access.');
    expect(normalizeDeepSecFindings(entries).map((finding) => finding.confidence)).toEqual([undefined, undefined]);
  });

  it('preserves native HIGH BUG severity through finding normalization', () => {
    const entries = parseDeepSecCommentOutMarkdown('## 🔎 deepsec found 1 finding\n\n### 🟣 HIGH BUG · `src/auth.ts:L2`\n\n**Role bypass**\n\nRequire authorization.');
    expect(normalizeDeepSecFindings(entries)).toEqual([expect.objectContaining({ severity: 'high', filePath: 'src/auth.ts', startLine: 2 })]);
  });

  it('parses the native 2.3.12 PR report without creating findings from its summary', () => {
    const report = '## 🔎 deepsec found 1 finding\n\n🟠 HIGH ×1\n\n<sub>scope: `files` · run `r1`</sub>\n\n### 🟠 HIGH · `src/auth.ts:L4-L7`\n\n**Missing authorization**\n<sub>slug: `missing-auth` · confidence: high</sub>\n\nRequire role checks.\n\n**Recommendation:** Check roles.\n\n---\n\n<sub>🤖 generated by [deepsec](https://github.com/vercel/deepsec)</sub>';
    expect(parseDeepSecCommentOutMarkdown(report)).toEqual([expect.objectContaining({
      anchor: { kind: 'range', filePath: 'src/auth.ts', startLine: 4, endLine: 7 },
      severity: 'HIGH', ruleId: 'missing-auth', body: expect.stringContaining('Missing authorization'),
    })]);
  });

  it('extracts anchors taxonomy and low-confidence file-level fallbacks', () => {
    const parsed = parseDeepSecCommentOutMarkdown(`
### src/auth.ts:42

**Severity:** high
**Rule:** CWE-601
**Category:** open_redirect

Validate redirect destinations before use.

### src/ambiguous.ts

Could not resolve a precise line, but this file needs attention.
`);

    expect(parsed[0]).toMatchObject({
      anchor: { kind: 'line', filePath: 'src/auth.ts', line: 42 },
      severity: 'high',
      ruleId: 'CWE-601',
      body: 'Validate redirect destinations before use.',
      confidence: 'high',
    });
    expect(parsed[1]).toMatchObject({
      anchor: { kind: 'file', filePath: 'src/ambiguous.ts' },
      tags: ['deepsec.low_confidence_anchor'],
      confidence: 'low',
    });
  });

  it('extracts line ranges from comment headings', () => {
    const parsed = parseDeepSecCommentOutMarkdown(`
### src/auth.ts:42-45

Validate the whole redirect block.
`);

    expect(parsed).toHaveLength(1);
    expect(parsed[0]?.anchor).toEqual({
      kind: 'range',
      filePath: 'src/auth.ts',
      startLine: 42,
      endLine: 45,
    });
  });

  it('skips unsafe paths from tool output instead of creating leaking anchors', () => {
    const parsed = parseDeepSecCommentOutMarkdown(`
### /Users/alice/repo/src/auth.ts:42

Do not leak this absolute path.

### ../outside.ts:1

Do not anchor traversal paths.

### src/safe.ts:7

Keep this one.
`);

    expect(parsed).toHaveLength(1);
    expect(parsed[0]?.anchor).toEqual({ kind: 'line', filePath: 'src/safe.ts', line: 7 });
  });
});
