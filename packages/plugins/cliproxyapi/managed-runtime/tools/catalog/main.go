// Generates credential-free compatibility rows from the pinned public module's
// embedded source. The SDK exposes its static accessors only from an internal
// package; source inspection avoids importing that package or starting a service.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"os/exec"
	"path/filepath"
	"runtime"
	"sort"
	"strconv"
	"strings"
)

const sdkModule = "github.com/router-for-me/CLIProxyAPI/v8"

type model struct {
	ID                  string            `json:"id"`
	Name                string            `json:"name"`
	ContextWindowTokens int               `json:"contextWindowTokens,omitempty"`
	Capabilities        map[string]string `json:"capabilities"`
	ModelOptions        []modelOption     `json:"modelOptions,omitempty"`
	UpstreamRef         *modelUpstreamRef `json:"upstreamRef,omitempty"`
}

type modelUpstreamRef struct {
	Vendor        string `json:"vendor"`
	VendorModelID string `json:"vendorModelId"`
}

type modelOption struct {
	ID           string        `json:"id"`
	Name         string        `json:"name"`
	Type         string        `json:"type"`
	CurrentValue string        `json:"currentValue"`
	Options      []optionValue `json:"options"`
}

type optionValue struct {
	Value string `json:"value"`
	Name  string `json:"name"`
}

type sdkModel struct {
	ID             string `json:"id"`
	OwnedBy        string `json:"owned_by"`
	ContextLength  int    `json:"context_length"`
	ToolRoundTrips string `json:"-"`
	Thinking       *struct {
		Levels []string `json:"levels"`
	} `json:"thinking"`
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run() error {
	families, err := readFamilies(os.Stdin)
	if err != nil {
		return err
	}
	data, err := exec.Command("go", "list", "-m", "-json", sdkModule).Output()
	if err != nil {
		return err
	}
	var module struct {
		Dir, Version string
		Replace      *json.RawMessage
	}
	if err := json.Unmarshal(data, &module); err != nil {
		return err
	}
	if module.Replace != nil {
		return fmt.Errorf("static catalog requires the unmodified pinned public SDK")
	}
	rows, err := generateRows(module.Dir, families)
	if err != nil {
		return err
	}
	output, err := renderCatalog(module.Version, rows)
	if err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join("..", "src", "provider", "staticModels.generated.ts"), output, 0o644); err != nil {
		return err
	}
	staticModels, err := generateRuntimeModels(rows)
	if err != nil {
		return err
	}
	if err := os.WriteFile("static_models.generated.go", staticModels, 0o644); err != nil {
		return err
	}
	descriptors, err := generateFamilies(families)
	if err != nil {
		return err
	}
	if err := os.WriteFile("families.generated.go", descriptors, 0o644); err != nil {
		return err
	}
	versionSource := fmt.Sprintf("// Code generated by tools/catalog from %s@%s. DO NOT EDIT.\n\npackage managedruntime\n\nconst pinnedSDKVersion = %q\n", sdkModule, module.Version, module.Version)
	return os.WriteFile("sdk_version.generated.go", []byte(versionSource), 0o644)
}

func generate(moduleDir, version string, families []familyRow) ([]byte, error) {
	rows, err := generateRows(moduleDir, families)
	if err != nil {
		return nil, err
	}
	return renderCatalog(version, rows)
}

func generateRows(moduleDir string, families []familyRow) (map[string][]model, error) {
	registryDir := filepath.Join(moduleDir, "internal", "registry")
	modelPath, err := embeddedModelPath(registryDir)
	if err != nil {
		return nil, err
	}
	data, err := os.ReadFile(modelPath)
	if err != nil {
		return nil, err
	}
	var embedded map[string][]sdkModel
	if err := json.Unmarshal(data, &embedded); err != nil {
		return nil, err
	}
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, filepath.Join(registryDir, "model_definitions.go"), nil, 0)
	if err != nil {
		return nil, err
	}
	functions := map[string]*ast.FuncDecl{}
	constants := map[string]string{}
	for _, declaration := range file.Decls {
		switch value := declaration.(type) {
		case *ast.FuncDecl:
			functions[value.Name.Name] = value
		case *ast.GenDecl:
			if value.Tok != token.CONST {
				continue
			}
			for _, spec := range value.Specs {
				entry := spec.(*ast.ValueSpec)
				for index, expression := range entry.Values {
					if literal, ok := expression.(*ast.BasicLit); ok && literal.Kind == token.STRING {
						constants[entry.Names[index].Name], err = strconv.Unquote(literal.Value)
						if err != nil {
							return nil, err
						}
					}
				}
			}
		}
	}
	fields, err := embeddedModelFields(file)
	if err != nil {
		return nil, err
	}
	rows := map[string][]model{}
	for _, family := range families {
		provider := family.AuthEntry.Provider
		key, builtinWrapper, err := accessorCatalog(functions[family.SDK.Catalog.Getter], fields)
		if err != nil {
			return nil, fmt.Errorf("SDK accessor %s: %w", family.SDK.Catalog.Getter, err)
		}
		models := map[string]sdkModel{}
		for _, entry := range embedded[key] {
			models[entry.ID] = entry
		}
		if builtinWrapper != "" {
			expression, err := returnExpression(functions[builtinWrapper])
			if err != nil {
				return nil, err
			}
			call, ok := expression.(*ast.CallExpr)
			if !ok || len(call.Args) < 2 {
				return nil, fmt.Errorf("SDK catalog builtin insertion changed")
			}
			callee, ok := call.Fun.(*ast.Ident)
			if !ok || callee.Name != "upsertModelInfos" {
				return nil, fmt.Errorf("SDK catalog builtin insertion changed")
			}
			for _, argument := range call.Args[1:] {
				builtin, ok := argument.(*ast.CallExpr)
				if !ok {
					return nil, fmt.Errorf("SDK catalog builtin constructor changed")
				}
				name, ok := builtin.Fun.(*ast.Ident)
				if !ok || len(builtin.Args) != 0 {
					return nil, fmt.Errorf("SDK catalog builtin constructor changed")
				}
				id, err := builtinID(functions[name.Name], constants)
				if err != nil {
					return nil, err
				}
				// WithCodexBuiltins replaces an embedded row with this ID. These
				// pinned image constructors carry no Thinking facts.
				entry := sdkModel{ID: id}
				// v8.0.61 has no modality field: these exact upstream image
				// constructors (absent from models.json) are image-only. Do not
				// classify arbitrary catalog IDs by their spelling.
				switch name.Name {
				case "codexBuiltinImage15ModelInfo", "codexBuiltinImageModelInfo",
					"codexBuiltinImage25FlareModelInfo", "codexBuiltinImage25SunburstModelInfo", "codexBuiltinImage25ModelInfo",
					"codexBuiltinImage26FlareModelInfo", "codexBuiltinImage26SunburstModelInfo", "codexBuiltinImage26ModelInfo":
					entry.ToolRoundTrips = "unsupported"
				}
				models[id] = entry
			}
		}
		for id, entry := range models {
			if id == "" {
				return nil, fmt.Errorf("SDK %s catalog has an empty model id", provider)
			}
			// The existing OpenAI probe consumes id/name only. The SDK emits
			// display_name, not name, so the existing catalog falls back to id.
			row := model{ID: id, Name: id, ContextWindowTokens: entry.ContextLength, Capabilities: map[string]string{
				"toolRoundTrips": "unknown", "reasoningControls": "unknown",
			}}
			// Antigravity is itself a router. Its registry labels identify
			// Antigravity routes and carry no underlying vendor identity.
			// Muse supplies the Meta facts in the projection below.
			if entry.OwnedBy != "" && provider != "antigravity" && provider != "meta" {
				row.UpstreamRef = &modelUpstreamRef{Vendor: entry.OwnedBy, VendorModelID: id}
			}
			if entry.ToolRoundTrips != "" {
				row.Capabilities["toolRoundTrips"] = entry.ToolRoundTrips
			}
			if entry.Thinking != nil && len(entry.Thinking.Levels) > 0 {
				// Exact SDK effort choices are positive reasoning-control facts.
				// Consumers require this capability before admitting the choices.
				row.Capabilities["reasoningControls"] = "supported"
				choices := make([]optionValue, 0, len(entry.Thinking.Levels))
				for _, level := range entry.Thinking.Levels {
					if level == "" {
						return nil, fmt.Errorf("SDK %s model %s has an empty thinking level", provider, id)
					}
					name := strings.ToUpper(level[:1]) + level[1:]
					if level == "xhigh" {
						name = "XHigh"
					}
					choices = append(choices, optionValue{Value: level, Name: name})
				}
				// The SDK declares allowed levels, not an upstream default. Like
				// native Codex model options without a declared default, use the
				// first source choice as the initial presentation value.
				row.ModelOptions = []modelOption{{ID: "reasoning_effort", Name: "Thinking", Type: "select", CurrentValue: choices[0].Value, Options: choices}}
			}
			rows[provider] = append(rows[provider], row)
		}
		if len(rows[provider]) == 0 {
			return nil, fmt.Errorf("SDK %s catalog is empty", provider)
		}
		sort.Slice(rows[provider], func(i, j int) bool { return rows[provider][i].ID < rows[provider][j].ID })
	}
	// Build-time projection keeps Meta identity and capabilities owned by Muse. The public
	// SDK registry still supplies membership, limits and offered options.
	_, sourceFile, _, _ := runtime.Caller(0)
	projector := filepath.Join(filepath.Dir(sourceFile), "../../../tools/catalog/generate.mjs")
	input, err := json.Marshal(rows)
	if err != nil {
		return nil, err
	}
	command := exec.Command("node", "--experimental-strip-types", projector, "--project-model-facts")
	command.Stdin = bytes.NewReader(input)
	output, err := command.Output()
	if err != nil {
		return nil, fmt.Errorf("Muse model fact projection: %w", err)
	}
	if err := json.Unmarshal(output, &rows); err != nil {
		return nil, err
	}
	return rows, nil
}

func renderCatalog(version string, rows map[string][]model) ([]byte, error) {
	encoded, err := json.MarshalIndent(rows, "", "  ")
	if err != nil {
		return nil, err
	}
	return []byte(fmt.Sprintf("// Generated by managed-runtime/tools/catalog from %s@%s. Do not edit.\n// SDK compatibility membership; Meta identity and capability evidence derives from the Muse model-facts owner.\nimport type { ProviderCatalogDeclarationV1 } from '@happier-dev/plugin-sdk/providers';\n\nexport const CLIPROXYAPI_STATIC_MODEL_SDK_VERSION = %q;\nexport const CLIPROXYAPI_STATIC_MODELS = %s satisfies Record<string, Extract<ProviderCatalogDeclarationV1, { source: 'static' }>['staticModels']>;\n", sdkModule, version, version, encoded)), nil
}

func returnExpression(function *ast.FuncDecl) (ast.Expr, error) {
	if function == nil || function.Body == nil || len(function.Body.List) != 1 {
		return nil, fmt.Errorf("SDK static accessor shape changed")
	}
	statement, ok := function.Body.List[0].(*ast.ReturnStmt)
	if !ok || len(statement.Results) != 1 {
		return nil, fmt.Errorf("SDK static return shape changed")
	}
	return statement.Results[0], nil
}

func builtinID(function *ast.FuncDecl, constants map[string]string) (string, error) {
	expression, err := returnExpression(function)
	if err != nil {
		return "", err
	}
	pointer, ok := expression.(*ast.UnaryExpr)
	if !ok || pointer.Op != token.AND {
		return "", fmt.Errorf("SDK builtin literal shape changed")
	}
	literal, ok := pointer.X.(*ast.CompositeLit)
	if !ok {
		return "", fmt.Errorf("SDK builtin literal shape changed")
	}
	for _, element := range literal.Elts {
		field, ok := element.(*ast.KeyValueExpr)
		if !ok {
			continue
		}
		key, ok := field.Key.(*ast.Ident)
		if !ok || key.Name != "ID" {
			continue
		}
		switch value := field.Value.(type) {
		case *ast.Ident:
			if id, ok := constants[value.Name]; ok {
				return id, nil
			}
		case *ast.BasicLit:
			if value.Kind == token.STRING {
				return strconv.Unquote(value.Value)
			}
		}
	}
	return "", fmt.Errorf("SDK builtin ID source changed")
}

// Both runtime fallback and published compatibility catalogs consume these rows.
func generateRuntimeModels(rows map[string][]model) ([]byte, error) {
	var output strings.Builder
	output.WriteString("// Code generated by tools/catalog/generate.mjs from the pinned SDK. DO NOT EDIT.\n\npackage managedruntime\n\nvar managedStaticModels = map[Provider][]sourceModel{\n")
	providers := make([]string, 0, len(rows))
	for provider := range rows {
		providers = append(providers, provider)
	}
	sort.Strings(providers)
	for _, provider := range providers {
		fmt.Fprintf(&output, "%q: {\n", provider)
		for _, row := range rows[provider] {
			fmt.Fprintf(&output, "{ID:%q, Name:%q},\n", row.ID, row.Name)
		}
		output.WriteString("},\n")
	}
	output.WriteString("}\n")
	return format.Source([]byte(output.String()))
}
