type familyRow struct {
	Origins     []string                      `json:"origins"`
	Purpose     string                        `json:"purpose"`
	AuthEntry   struct{ ID, Provider string } `json:"authEntry"`
	RequestAuth struct {
		Materialization struct {
			HeaderNames []string `json:"headerNames"`
		} `json:"materialization"`
	} `json:"requestAuth"`
	SDK struct {
		StripHeaderNames []string `json:"stripHeaderNames"`
		Catalog          struct {
			Getter string `json:"getter"`
		} `json:"catalog"`
		Seed struct {
			Attributes map[string]string `json:"attributes"`
			Metadata   map[string]any    `json:"metadata"`
		} `json:"seed"`
		Adapter string `json:"adapter"`
	} `json:"sdk"`
}

func readFamilies(reader io.Reader) ([]familyRow, error) {
	var families []familyRow
	if err := json.NewDecoder(reader).Decode(&families); err != nil {
		return nil, fmt.Errorf("read managedContract.ts rows: %w", err)
	}
	seen := map[string]bool{}
	for _, family := range families {
		if family.AuthEntry.ID == "" || family.AuthEntry.Provider == "" || seen[family.AuthEntry.Provider] || family.SDK.Catalog.Getter == "" {
			return nil, fmt.Errorf("invalid or duplicate managed family %q", family.AuthEntry.Provider)
		}
		seen[family.AuthEntry.Provider] = true
		if family.SDK.Adapter != "late-headers" && family.SDK.Adapter != "request-local-auth" {
			return nil, fmt.Errorf("unsupported managed adapter %q", family.SDK.Adapter)
		}
	}
	if len(families) == 0 {
		return nil, fmt.Errorf("managed family rows are empty")
	}
	return families, nil
}

func generateFamilies(families []familyRow) ([]byte, error) {
	var output bytes.Buffer
	fmt.Fprintln(&output, "// Code generated by tools/catalog/generate.mjs from managedContract.ts. DO NOT EDIT.\n\npackage managedruntime")
	fmt.Fprintln(&output, `
type managedFamilyDescriptor struct {
 ID string
 Provider Provider
 Origins []string
 HeaderNames []string
 StripHeaderNames []string
 Adapter string
 SeedAttributes map[string]string
 SeedMetadata map[string]any
}
func managedFamilyForProvider(provider Provider) (managedFamilyDescriptor, bool) {
 family, ok := managedFamilies[provider]
 return family, ok
}`)
	fmt.Fprintln(&output, "const (")
	for _, family := range families {
		name := strings.ToUpper(family.AuthEntry.Provider[:1]) + family.AuthEntry.Provider[1:]
		fmt.Fprintf(&output, "Provider%s Provider = %q\n", name, family.AuthEntry.Provider)
	}
	fmt.Fprintln(&output, ")\nvar managedFamilies = map[Provider]managedFamilyDescriptor{")
	for _, family := range families {
		fmt.Fprintf(&output, "%q: {ID:%q, Provider:%q, Origins:%#v, HeaderNames:%#v, StripHeaderNames:%#v, Adapter:%q, SeedAttributes:%#v, SeedMetadata:%#v},\n", family.AuthEntry.Provider, family.AuthEntry.ID, family.AuthEntry.Provider, family.Origins, family.RequestAuth.Materialization.HeaderNames, family.SDK.StripHeaderNames, family.SDK.Adapter, family.SDK.Seed.Attributes, family.SDK.Seed.Metadata)
	}
	fmt.Fprintln(&output, "}")
	return format.Source(output.Bytes())
}

// These codecs intentionally accept only the pinned registry's source shapes.
// Getter names and JSON field names come from their actual SDK declarations.
func embeddedModelFields(file *ast.File) (map[string]string, error) {
	for _, declaration := range file.Decls {
		group, ok := declaration.(*ast.GenDecl)
		if !ok {
			continue
		}
		for _, spec := range group.Specs {
			typeSpec, ok := spec.(*ast.TypeSpec)
			if !ok || typeSpec.Name.Name != "staticModelsJSON" {
				continue
			}
			structure, ok := typeSpec.Type.(*ast.StructType)
			if !ok {
				break
			}
			fields := map[string]string{}
			for _, field := range structure.Fields.List {
				if field.Tag == nil || len(field.Names) != 1 {
					return nil, fmt.Errorf("SDK staticModelsJSON field changed")
				}
				tag, err := strconv.Unquote(field.Tag.Value)
				if err != nil {
					return nil, err
				}
				fields[field.Names[0].Name] = reflect.StructTag(tag).Get("json")
			}
			return fields, nil
		}
	}
	return nil, fmt.Errorf("SDK staticModelsJSON declaration missing")
}

func accessorCatalog(function *ast.FuncDecl, fields map[string]string) (string, string, error) {
	expression, err := returnExpression(function)
	if err != nil {
		return "", "", err
	}
	call, ok := expression.(*ast.CallExpr)
	if !ok || len(call.Args) != 1 {
		return "", "", fmt.Errorf("unsupported getter expression")
	}
	name, ok := call.Fun.(*ast.Ident)
	if !ok {
		return "", "", fmt.Errorf("unsupported getter callee")
	}
	wrapper := ""
	if name.Name != "cloneModelInfos" {
		wrapper = name.Name
		call, ok = call.Args[0].(*ast.CallExpr)
		if !ok || len(call.Args) != 1 {
			return "", "", fmt.Errorf("unsupported wrapped getter")
		}
		name, ok = call.Fun.(*ast.Ident)
		if !ok || name.Name != "cloneModelInfos" {
			return "", "", fmt.Errorf("unsupported clone expression")
		}
	}
	field, ok := call.Args[0].(*ast.SelectorExpr)
	if !ok {
		return "", "", fmt.Errorf("unsupported catalog field")
	}
	getModels, ok := field.X.(*ast.CallExpr)
	if !ok || len(getModels.Args) != 0 {
		return "", "", fmt.Errorf("unsupported catalog source")
	}
	callee, ok := getModels.Fun.(*ast.Ident)
	if !ok || callee.Name != "getModels" || fields[field.Sel.Name] == "" {
		return "", "", fmt.Errorf("unsupported embedded catalog source")
	}
	return fields[field.Sel.Name], wrapper, nil
}

func embeddedModelPath(registryDir string) (string, error) {
	// The source directive is authoritative; a changed declaration fails closed
	// at generation instead of silently selecting an unrelated models file.
	file, err := parser.ParseFile(token.NewFileSet(), filepath.Join(registryDir, "model_updater.go"), nil, parser.ParseComments)
	if err != nil {
		return "", err
	}
	for _, comment := range file.Comments {
		for _, line := range comment.List {
			if strings.HasPrefix(line.Text, "//go:embed ") {
				return filepath.Join(registryDir, strings.TrimSpace(strings.TrimPrefix(line.Text, "//go:embed "))), nil
			}
		}
	}
	return "", fmt.Errorf("SDK model_updater.go: embedded models directive missing")
}
