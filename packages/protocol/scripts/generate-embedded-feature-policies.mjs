#!/usr/bin/env node

import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

function parseArgs(argv) {
  const kv = new Map();
  const flags = new Set();
  for (let i = 0; i < argv.length; i += 1) {
    const raw = argv[i];
    if (!raw.startsWith('--')) continue;
    if (raw.includes('=')) {
      const [k, v] = raw.split('=');
      kv.set(k, v ?? '');
      continue;
    }
    const next = argv[i + 1];
    if (next && !next.startsWith('--')) {
      kv.set(raw, next);
      i += 1;
      continue;
    }
    flags.add(raw);
  }
  return { kv, flags };
}

function normalizePolicyEnv(raw) {
  const normalized = String(raw ?? '').trim().toLowerCase();
  if (normalized === 'production' || normalized === 'prod' || normalized === 'stable') return 'production';
  if (normalized === 'preview') return 'preview';
  return null;
}

function normalizeCsv(list) {
  if (!Array.isArray(list)) return '';
  const out = [];
  const seen = new Set();
  for (const value of list) {
    if (typeof value !== 'string') continue;
    const trimmed = value.trim();
    if (!trimmed) continue;
    if (seen.has(trimmed)) continue;
    seen.add(trimmed);
    out.push(trimmed);
  }
  return out.join(',');
}

function parseJson(raw, label) {
  try {
    return JSON.parse(raw);
  } catch (error) {
    throw new Error(`[protocol] invalid JSON for ${label}: ${error instanceof Error ? error.message : String(error)}`);
  }
}

async function loadPolicy(path, label) {
  const doc = parseJson(await readFile(path, 'utf8'), label);
  const buildPolicy = doc?.buildPolicy ?? null;
  return {
    allowRaw: normalizeCsv(buildPolicy?.allow),
    denyRaw: normalizeCsv(buildPolicy?.deny),
  };
}

function renderModuleSource(params) {
  const preview = params.preview;
  const production = params.production;
  const defaultEnv = params.defaultEnv;

  return `// This file is generated by packages/protocol/scripts/generate-embedded-feature-policies.mjs
// Do not edit by hand.

export const DEFAULT_EMBEDDED_FEATURE_POLICY_ENV = ${JSON.stringify(defaultEnv)} as const;

const EMBEDDED_FEATURE_BUILD_POLICY_RAW_INNER = {
  preview: {
    allowRaw: ${JSON.stringify(preview.allowRaw)},
    denyRaw: ${JSON.stringify(preview.denyRaw)},
  },
  production: {
    allowRaw: ${JSON.stringify(production.allowRaw)},
    denyRaw: ${JSON.stringify(production.denyRaw)},
  },
} as const;

export const EMBEDDED_FEATURE_BUILD_POLICY_RAW = Object.freeze({
  preview: Object.freeze({ ...EMBEDDED_FEATURE_BUILD_POLICY_RAW_INNER.preview }),
  production: Object.freeze({ ...EMBEDDED_FEATURE_BUILD_POLICY_RAW_INNER.production }),
}) as typeof EMBEDDED_FEATURE_BUILD_POLICY_RAW_INNER;
`;
}

/** The generated module's path inside a repository. */
export const EMBEDDED_FEATURE_POLICIES_OUTPUT = 'packages/protocol/src/features/embeddedFeaturePolicies.generated.ts';

/**
 * Render the module from `policyDir` and write it when it differs. Build
 * captures call this against their own repository root, so the module always
 * follows the policy files of the bytes being built.
 * @returns {Promise<{ outPath: string, changed: boolean }>}
 */
export async function writeEmbeddedFeaturePolicies({ repoRoot, policyDir = join(repoRoot, '.github', 'feature-policy'),
  outPath = join(repoRoot, EMBEDDED_FEATURE_POLICIES_OUTPUT), env = process.env, check = false }) {
  const requirePolicies = String(env.HAPPIER_REQUIRE_FEATURE_POLICY ?? '').trim() === '1';
  const defaultEnv = normalizePolicyEnv(env.HAPPIER_EMBEDDED_POLICY_ENV) ?? 'preview';

  let preview;
  let production;
  try {
    preview = await loadPolicy(join(policyDir, 'preview.json'), 'preview');
    production = await loadPolicy(join(policyDir, 'production.json'), 'production');
  } catch (error) {
    if (requirePolicies) throw error;
    preview = { allowRaw: '', denyRaw: '' };
    production = { allowRaw: '', denyRaw: '' };
  }

  const source = renderModuleSource({ preview, production, defaultEnv });
  const previous = await readFile(outPath, 'utf8').catch(() => null);
  if (previous === source) return { outPath, changed: false };

  if (check) {
    throw new Error(
      '[protocol] embedded feature-policy compiler input is stale. Run node packages/protocol/scripts/generate-embedded-feature-policies.mjs to refresh it.',
    );
  }

  await mkdir(dirname(outPath), { recursive: true });
  await writeFile(outPath, source, 'utf8');
  return { outPath, changed: true };
}

async function main() {
  const here = dirname(fileURLToPath(import.meta.url));
  const repoRoot = resolve(here, '..', '..', '..');
  const { flags, kv } = parseArgs(process.argv.slice(2));
  await writeEmbeddedFeaturePolicies({ repoRoot,
    policyDir: String(kv.get('--policy-dir') ?? '').trim() || undefined,
    outPath: String(kv.get('--out') ?? '').trim() || undefined,
    check: flags.has('--check') });
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) main().catch((error) => {
  console.error(error instanceof Error ? error.message : String(error));
  process.exit(1);
});
