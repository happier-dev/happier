export function resolveMachineRpcGovernance(method: string): MachineRpcGovernanceMetadataV1 {
  const actionSpecId = ACTION_SPEC_RPC_METHOD_IDS[method as keyof typeof ACTION_SPEC_RPC_METHOD_IDS];
  if (actionSpecId) {
    return { rpcClassification: 'action_spec_bound', actionSpecId };
  }
  if (Object.hasOwn(READ_ONLY_RPC_GOVERNANCE, method)) {
    return {
      rpcClassification: READ_ONLY_RPC_GOVERNANCE[method as keyof typeof READ_ONLY_RPC_GOVERNANCE],
      readOnly: true,
    };
  }
  if (
    method === RPC_METHODS.STOP_DAEMON
    // The query kind selects its public code.* Action. Sync/watch are the
    // internal editor transport, so no single Action can own these envelopes.
    || method === RPC_METHODS.DAEMON_LSP_SYNC
    || method === RPC_METHODS.DAEMON_LSP_QUERY
    || method === RPC_METHODS.DAEMON_LSP_WATCH
    || SESSION_SPAWN_PRIVATE_INTERNAL_METHODS.has(method)
    || PMS5_DIRECT_INTERNAL_METHODS.has(method)
    || A16X_PLUGIN_UI_INTERNAL_METHODS.has(method)
    || TEAM_CREDENTIAL_BROKER_INTERNAL_METHODS.has(method)
    || SIMULATOR_RELAY_INTERNAL_METHODS.has(method)
    || PROMPT_TRANSFER_INTERNAL_METHODS.has(method)
    || A12_VOICE_CLEANUP_INTERNAL_METHODS.has(method)
    || VOICE_FOUNDATION_INTERNAL_METHODS.has(method)
  ) {
    return { rpcClassification: 'internal_only' };
  }
  return { rpcClassification: 'advisory_unclassified' };
}
