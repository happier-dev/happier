import { build } from 'esbuild';
import { readFile, rename, rm, writeFile } from 'node:fs/promises';
import { randomUUID } from 'node:crypto';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export async function buildHostedHtmlGuestBootstrap({
    packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..'),
    outputFile,
    check = false,
} = {}) {
    const repoRoot = resolve(packageRoot, '../..');
    const target = resolve(outputFile);
    // One derived browser client for Metro/Expo and native document transports.
    // No runtime compiler, asset URL, network permission or second bridge protocol.
    const result = await build({
        absWorkingDir: repoRoot,
        entryPoints: [resolve(packageRoot, 'src/ui/hostedHtmlGuestEntry.ts')],
        bundle: true, write: false, minify: true, platform: 'browser', format: 'iife', target: ['es2022'],
        conditions: ['happier-source'],
        define: { 'process.env.NODE_ENV': '"production"' },
        legalComments: 'none',
        plugins: [{ name: 'workspace-protocol-source', setup(builder) {
            builder.onResolve({ filter: /^@happier-dev\/protocol(?:\/|$)/ }, args => {
                if (args.pluginData?.workspaceProtocol) return;
                return builder.resolve(args.path, { kind: args.kind, resolveDir: repoRoot, pluginData: { workspaceProtocol: true } })
                    .then(result => ({ ...result, pluginData: undefined }));
            });
        } }],
    });
    const source = '// Generated by scripts/buildHostedHtmlGuestBootstrap.mjs; do not edit.\n'
        + '/** @moduleRealm any */\n'
        + `export const HOSTED_HTML_GUEST_BOOTSTRAP_SCRIPT: string = ${JSON.stringify(result.outputFiles[0].text)};\n`;
    const current = await readFile(target, 'utf8').catch(error => {
        if (error.code === 'ENOENT') return null;
        throw error;
    });
    if (check && current !== source) throw new Error('Hosted HTML guest bootstrap is stale; run generate:hosted-html-guest');
    if (!check && current !== source) {
        // Readers need one complete source file, not custody of CLI dist. Each
        // producer stages privately and publishes its derived bytes atomically.
        const staged = `${target}.${randomUUID()}.tmp`;
        try {
            await writeFile(staged, source);
            await rename(staged, target);
        } finally {
            await rm(staged, { force: true });
        }
    }
}
