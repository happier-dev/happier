import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { resolve } from 'node:path';
import { runInThisContext } from 'node:vm';
import { build } from 'esbuild';

const GENERATED_HEADER = '// Generated by packages/plugin-sdk/scripts/generateActionTypeMap.mjs. Do not edit by hand.\n';

/** Project normalized catalog facts once for consumers that do not need schemas. */
export async function projectCatalogMetadata({ repoRoot, inputSnapshot, recordDigest = () => {} }) {
  const actionSpecs = resolve(repoRoot, 'packages/protocol/src/actions/actionSpecs.ts');
  const bundled = await build({
    stdin: { contents: `import { ACTION_SPECS } from ${JSON.stringify(actionSpecs)};
      export const ids = ACTION_SPECS.filter(spec => spec.executionPlacement === 'client'
        || spec.executionPlacements?.includes('client')).map(spec => spec.id);
      // Meta tools enter the Action policy owner before applying an effect.
      const names = new Set(['action_execute', 'action_spec_search', 'action_spec_get', 'action_options_resolve']);
      for (const spec of ACTION_SPECS) {
        if (spec.safety === 'safe' && spec.bindings?.mcpToolName) names.add(spec.bindings.mcpToolName);
      }
      // The existing native title bridge follows session.title.set safety.
      if (names.has('session_title_set')) names.add('change_title');
      export const autoApprovedNames = [...names].sort();`, resolveDir: repoRoot },
    bundle: true, write: false, platform: 'node', format: 'cjs', conditions: ['happier-source'],
    tsconfigRaw: {}, logLevel: 'silent',
    plugins: [{ name: 'captured-action-catalog', setup(builder) {
      builder.onLoad({ filter: /\.(?:[cm]?js|tsx?|json)$/ }, ({ path }) => {
        const contents = inputSnapshot?.get(resolve(path)) ?? readFileSync(path, 'utf8');
        recordDigest(path, createHash('sha256').update(contents).digest('hex'));
        return { contents, loader: path.endsWith('.json') ? 'json' : /\.tsx?$/u.test(path) ? 'ts' : 'js' };
      });
    } }],
  });
  const runtime = { exports: {} };
  runInThisContext(`(function(module, exports, require) { ${bundled.outputFiles[0].text}\n})`,
    { filename: actionSpecs })(runtime, runtime.exports, createRequire(actionSpecs));
  const ids = [...new Set(runtime.exports.ids)].sort();
  const clientPlacement = {
    path: resolve(repoRoot, 'packages/protocol/src/actions/clientRoutedActionIds.generated.ts'),
    output: GENERATED_HEADER + `export type ClientRoutedActionId = ${ids.map(id => JSON.stringify(id)).join(' | ') || 'never'};\n`,
  };
  const autoApproval = {
    path: resolve(repoRoot, 'packages/protocol/src/tools/autoApprovedNames.generated.ts'),
    output: GENERATED_HEADER + 'export const autoApprovedNames: readonly string[] = Object.freeze('
      + JSON.stringify(runtime.exports.autoApprovedNames, null, 2) + ');\n',
  };
  return { clientPlacement, outputs: new Map([clientPlacement, autoApproval].map(({ path, output }) => [path, output])) };
}
