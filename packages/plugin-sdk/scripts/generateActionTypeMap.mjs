/** Project the generated neutral declaration closure without a compiler program. */
export function projectNeutralActionDtoDeclarations({ repoRoot = REPO_ROOT, recordInput = () => {}, declarations = new Map(),
  readSource = path => readFileSync(path, 'utf8') } = {}) {
  const protocolRoot = resolve(repoRoot, 'packages/protocol/src');
  const virtual = declarations.size > 0;
  const declarationRoot = virtual ? protocolRoot : resolve(repoRoot, 'packages/plugin-sdk/src/actions');
  const indexPath = resolve(declarationRoot, virtual ? 'actions/pluginActionDtos.ts' : 'actionTypeMap.generated.ts');
  // Reuse the SDK-owned public declarations instead of publishing support copies.
  const canonicalSdkTypes = new Map(['JsonValue', 'PluginJsonValueV2'].map((name) => [name, {
    path: resolve(repoRoot, 'packages/plugin-sdk/src/identity.ts'), name,
  }]));
  canonicalSdkTypes.set('MachinePresetItemV1', {
    path: resolve(repoRoot, 'packages/plugin-sdk/src/machineSetup.ts'), name: 'MachinePresetItemV1',
  });
  canonicalSdkTypes.set('ScmComparisonSource', {
    path: resolve(repoRoot, 'packages/plugin-sdk/src/scm/comparisonSource.ts'), name: 'ScmComparisonSource',
  });
  canonicalSdkTypes.set('ActionFailureCauseV1', {
    path: resolve(repoRoot, 'packages/plugin-sdk/src/errors/index.ts'), name: 'ActionFailureCauseV1',
  });
  const sources = new Map();
  const sourceTexts = new Map();
  const selected = new Map();
  const outputNames = new Map();
  const source = (path) => {
    if (!sources.has(path)) {
      const text = declarations.get(path) ?? readSource(path);
      sourceTexts.set(path, text);
      if (!declarations.has(path)) recordInput(path, text);
      // Published declarations carry our header; preserve authored documentation
      // without treating that publication marker as declaration-owned trivia.
      const declarationText = !virtual && text.startsWith(GENERATED_HEADER) ? text.slice(GENERATED_HEADER.length) : text;
      sources.set(path, ts.createSourceFile(path, declarationText, ts.ScriptTarget.ES2022, true, ts.ScriptKind.TS));
    }
    return sources.get(path);
  };
  const resolveImport = (path, specifier) => {
    if (!specifier.startsWith('.')) throw new Error(`Private DTO dependency: ${specifier}`);
    const target = resolve(dirname(path), specifier.replace(/\.js$/u, '.ts'));
    const fromRoot = relative(declarationRoot, target);
    if (isAbsolute(fromRoot) || fromRoot === '..' || fromRoot.startsWith('../') || fromRoot.startsWith('..\\')
      || resolve(declarationRoot, fromRoot) !== target) throw new Error(`DTO dependency outside declaration closure: ${target}`);
    return target;
  };
  const declaration = (path, name) => {
    if (canonicalSdkTypes.has(name)) return canonicalSdkTypes.get(name);
    const file = source(path);
    for (const node of file.statements) {
      if ((ts.isTypeAliasDeclaration(node) || ts.isInterfaceDeclaration(node)) && node.name.text === name) return { path, node };
      if (ts.isImportDeclaration(node) && node.importClause?.namedBindings
        && ts.isNamedImports(node.importClause.namedBindings)) {
        const binding = node.importClause.namedBindings.elements.find((item) => item.name.text === name);
        if (binding) return declaration(resolveImport(path, node.moduleSpecifier.text), (binding.propertyName ?? binding.name).text);
      }
      if (ts.isExportDeclaration(node) && node.exportClause && ts.isNamedExports(node.exportClause) && node.moduleSpecifier) {
        const binding = node.exportClause.elements.find((item) => item.name.text === name);
        if (binding) return declaration(resolveImport(path, node.moduleSpecifier.text), (binding.propertyName ?? binding.name).text);
      }
    }
    throw new Error(`Unresolved DTO declaration ${name} in ${relative(repoRoot, path)}`);
  };
  const references = (node) => {
    const names = new Set();
    const parameters = new Set(node.typeParameters?.map((item) => item.name.text));
    const visit = (child, bound = parameters) => {
      if (ts.isImportTypeNode(child) || ts.isTypeQueryNode(child)) {
        throw new Error('DTO declarations must not depend on values or private import types.');
      }
      if (ts.isMappedTypeNode(child)) {
        // The constraint can reference an outer declaration with the same name;
        // only the mapped value and key remapping bind the local key parameter.
        if (child.typeParameter.constraint) visit(child.typeParameter.constraint, bound);
        const mappedBound = new Set([...bound, child.typeParameter.name.text]);
        if (child.nameType) visit(child.nameType, mappedBound);
        if (child.type) visit(child.type, mappedBound);
        return;
      }
      if (ts.isTypeReferenceNode(child) || ts.isExpressionWithTypeArguments(child)) {
        const name = child.typeName ?? child.expression;
        if (!ts.isIdentifier(name)) throw new Error('DTO declarations must not contain qualified validator types.');
        if (!bound.has(name.text) && !ACTION_DTO_BUILTINS.has(name.text)) names.add(name.text);
      }
      ts.forEachChild(child, nested => visit(nested, bound));
    };
    visit(node);
    return names;
  };
  const select = (path, name) => {
    const found = declaration(path, name);
    if (!found.node) return found;
    if (!selected.has(found.path)) selected.set(found.path, new Map());
    const declarations = selected.get(found.path);
    if (declarations.has(found.node.name.text)) return found;
    declarations.set(found.node.name.text, found.node);
    for (const reference of references(found.node)) select(found.path, reference);
    return found;
  };
  const index = source(indexPath);
  const rootNames = index.statements.flatMap(node => {
    if (ts.isTypeAliasDeclaration(node) && node.modifiers?.some(modifier => modifier.kind === ts.SyntaxKind.ExportKeyword)) return [node.name.text];
    if (ts.isExportDeclaration(node) && node.isTypeOnly && node.moduleSpecifier
      && node.exportClause && ts.isNamedExports(node.exportClause)) return node.exportClause.elements.map(element => element.name.text);
    return [];
  });
  for (const name of rootNames) select(indexPath, name);
  const uiPath = resolve(declarationRoot, virtual ? 'plugins/contributions/ui/actionDeclarativeNodeDto.ts' : 'dtos/actionDeclarativeNodeDto.generated.ts');
  if (declarations.has(uiPath) || ts.sys.fileExists(uiPath)) {
    for (const node of source(uiPath).statements) {
      if (ts.isTypeAliasDeclaration(node) && node.modifiers?.some(modifier => modifier.kind === ts.SyntaxKind.ExportKeyword)) select(uiPath, node.name.text);
    }
  }
  const mapKeysFrom = (path, name) => {
    const { path: owner, node } = declaration(path, name);
    if (ts.isTypeLiteralNode(node.type)) return node.type.members.map((member) => member.name.text);
    if (ts.isIntersectionTypeNode(node.type)) return node.type.types.flatMap((member) => {
      if (!ts.isTypeReferenceNode(member) || !ts.isIdentifier(member.typeName)) throw new Error('DTO map index must name family maps.');
      return mapKeysFrom(owner, member.typeName.text);
    });
    if (ts.isTypeReferenceNode(node.type) && ts.isIdentifier(node.type.typeName)) return mapKeysFrom(owner, node.type.typeName.text);
    throw new Error(`DTO map must retain literal keys: ${name}`);
  };
  const { families, excluded } = readActionCatalog(repoRoot, recordInput, readSource);
  const canonicalKeys = Object.values(families).flat().filter((id) => !Object.hasOwn(excluded, id)).sort();
  const inputKeys = mapKeysFrom(indexPath, 'PluginActionInputById').sort();
  const resultKeys = mapKeysFrom(indexPath, 'PluginActionResultById').sort();
  assertSameKeys(canonicalKeys, inputKeys, 'Canonical/DTO Action input maps');
  assertSameKeys(canonicalKeys, resultKeys, 'Canonical/DTO Action result maps');
  for (const path of selected.keys()) {
    const name = path === indexPath ? 'actionTypeMap.generated.ts' : `dtos/${basename(path, '.ts')}${virtual ? '.generated' : ''}.ts`;
    if ([...outputNames.values()].includes(name)) throw new Error(`Duplicate DTO module name: ${name}`);
    outputNames.set(path, name);
  }
  const outputs = new Map();
  for (const [path, declarations] of selected) {
    const imports = new Map();
    for (const node of declarations.values()) {
      for (const name of references(node)) {
        const target = declaration(path, name);
        if (target.path === path) continue;
        const targetOutput = target.node ? outputNames.get(target.path) : relative(resolve(repoRoot, 'packages/plugin-sdk/src/actions'), target.path);
        const modulePath = relative(dirname(outputNames.get(path)), targetOutput).replaceAll('\\', '/').replace(/\.ts$/u, '.js');
        const specifier = modulePath.startsWith('.') ? modulePath : `./${modulePath}`;
        if (!imports.has(specifier)) imports.set(specifier, new Map());
        imports.get(specifier).set(name, target.node?.name.text ?? target.name);
      }
    }
    const orderedDeclarations = [...declarations.values()].sort((left, right) => left.pos - right.pos);
    const output = [GENERATED_HEADER, '',
      ...[...imports].sort(([a], [b]) => a.localeCompare(b)).map(([specifier, names]) =>
        `import type { ${[...names].sort(([a], [b]) => a.localeCompare(b)).map(([local, exported]) => local === exported ? local : `${exported} as ${local}`).join(', ')} } from '${specifier}';`), '',
      ...(basename(path).startsWith('pluginActionDtoSupport.') && imports.get('../../errors/index.js')?.has('ActionFailureCauseV1')
        ? ["export type { ActionFailureCauseV1 } from '../../errors/index.js';", ''] : []),
      ...orderedDeclarations.map((node) => printer.printNode(ts.EmitHint.Unspecified, node, source(path))), ''].join('\n');
    validateGeneratedModuleSyntax(output);
    outputs.set(`packages/plugin-sdk/src/actions/${outputNames.get(path)}`, output);
  }
  // Public family names follow the same selected declarations as the aggregate
  // maps. The authored /actions spec consumes this list without repeating it.
  const familyExports = [...selected]
    .filter(([path]) => path !== indexPath)
    .flatMap(([path, declarations]) => {
      const names = [...declarations.keys()].filter(name => /Action(?:Input|Result)ById$/u.test(name)).sort();
      return names.length === 0 ? [] : [{ module: basename(outputNames.get(path), '.ts'), names }];
    })
    .sort((left, right) => left.module.localeCompare(right.module));
  const familyExportSource = [
    GENERATED_HEADER,
    '',
    ...familyExports.map(({ module, names }) => `export type { ${names.join(', ')} } from './${module}.js';`),
    ...(familyExports.length === 0 ? ['export {};'] : []),
    '',
  ].join('\n');
  validateGeneratedModuleSyntax(familyExportSource);
  outputs.set('packages/plugin-sdk/src/actions/dtos/familyExports.generated.ts', familyExportSource);
  return { inputKeys, resultKeys, outputs, inputPaths: [...sources.keys()],
    inputDigests: [...sourceTexts].map(([path, text]) => [path, digest(text)]) };
}


/** Project the standalone SDK type closure, sharing only equivalent structures. */
export function projectActionDtoDeclarations(options = {}) {
  const { repoRoot = REPO_ROOT, readSource = path => readFileSync(path, 'utf8') } = options;
  const base = projectNeutralActionDtoDeclarations(options);
  const declarationRoot = resolve(repoRoot, 'packages/plugin-sdk/src/actions');
  const sharedRelativePath = 'packages/plugin-sdk/src/actions/dtos/pluginActionDtoShapes.generated.ts';
  if (base.outputs.has(sharedRelativePath)) return base;

  const original = new Map([...base.outputs].map(([path, text]) => [resolve(repoRoot, path), text]));
  const compacted = shareActionDtoStructures(original, {
    sharedPath: resolve(repoRoot, sharedRelativePath), declarationRoot, builtins: ACTION_DTO_BUILTINS,
  });
  if (compacted === original) return base;

  // Resolve the resulting imports through the same closure owner used by
  // author publications. This also drops replaced declarations and imports.
  const projected = projectNeutralActionDtoDeclarations({
    repoRoot, readSource: path => compacted.get(path) ?? readSource(path),
  });
  return { ...base, outputs: projected.outputs };
}

function digest(value) {
  return createHash('sha256').update(value).digest('hex');
}

function fingerprintInputPaths(paths) {
  const hash = createHash('sha256').update(`action-map-v1\0${ts.version}\0`);
  for (const path of [...new Set(paths)].sort()) {
    hash.update(path).update('\0').update(readFileSync(path)).update('\0');
  }
  return hash.digest('hex');
}

async function inspectActionTypeMapCache({ cachePath, outputPath }) {
  let record;
  try {
    record = JSON.parse(await readFile(cachePath, 'utf8'));
  } catch {
    record = null;
  }
  // The canonical output identifies the generating root; matching bytes alone
  // can otherwise admit a scratch root's unchanged inputs and family shards.
  if (record?.version === 1 && record.outputPath === resolve(outputPath) && Array.isArray(record.inputPaths)) {
    let currentFingerprint = null;
    try {
      currentFingerprint = fingerprintInputPaths(record.inputPaths);
    } catch {
      // Deleted inputs invalidate the cache and enter real derivation.
    }
    try {
      if (
        currentFingerprint !== null && currentFingerprint === record.fingerprint
        && digest(await readFile(outputPath)) === record.outputDigest
      ) {
        for (const [path, expected] of record.outputDigests ?? []) {
          if (digest(await readFile(path)) !== expected) return { hit: false };
        }
        return { hit: true };
      }
    } catch {
      // A deleted output invalidates the cache and enters real derivation.
    }
  }
  return { hit: false };
}

/** One input-currentness rule for every preparation path. */
function preparedInputsUnchanged(prepared) {
  for (const [path, expectedDigest] of prepared.inputDigests ?? []) {
    const current = ts.sys.readFile(path);
    if (current === undefined || digest(current) !== expectedDigest) return false;
  }
  return true;
}

export async function runCachedActionTypeMap({ cachePath, outputPath, derive, publish = async ({ output }) => {
  await writeFileIfChanged(outputPath, output);
}, withDerivationLock = async (operation) => await operation(), mode = '--write' }) {
  if ((await inspectActionTypeMapCache({ cachePath, outputPath })).hit) return false;
  return await withDerivationLock(async (lockContext) => {
    // Waiters consume the preceding owner's result before constructing another program.
    const { hit } = await inspectActionTypeMapCache({ cachePath, outputPath });
    if (hit) return false;

    const prepared = await derive();
    // Writers complete one coherent snapshot before checking live currentness.
    // Checks and cache admission still reject stale results.
    const inputsUnchanged = () => preparedInputsUnchanged(prepared);
    const inputPaths = [...new Set(prepared.inputPaths)].sort();
    const initiallyCurrent = prepared.stale !== true && inputsUnchanged();
    if (mode === '--check' && !initiallyCurrent) {
      throw new Error('Action type map inputs changed during derivation. Run preparation again.');
    }
    const fingerprint = initiallyCurrent ? fingerprintInputPaths(inputPaths) : null;
    const outputDigests = [...(prepared.outputs ?? new Map([[outputPath, prepared.output]]))]
      .map(([path, output]) => [path, digest(output)]);
    const assertInputsCurrent = () => {
      if (prepared.stale === true || !inputsUnchanged() || fingerprint === null || fingerprintInputPaths(inputPaths) !== fingerprint) {
        throw new Error('Action type map inputs changed; generation is stale relative to current source. Run generation again.');
      }
    };
    await publish(prepared, { ...lockContext, assertInputsCurrent });
    for (const [path, expected] of outputDigests) {
      if (digest(await readFile(path)) !== expected) {
        throw new Error(`Action type map publication did not leave the derived output current: ${path}`);
      }
    }
    if (mode === '--check') assertInputsCurrent();
    await mkdir(dirname(cachePath), { recursive: true });
    await writeFile(cachePath, JSON.stringify({
      version: 1,
      outputPath: resolve(outputPath),
      inputPaths,
      fingerprint,
      outputDigest: digest(prepared.output),
      outputDigests,
    }) + '\n');
    return true;
  });
}

export function createActionTypeMapTimingReporter({
  now = () => performance.now(),
  write = (line) => process.stderr.write(line),
} = {}) {
  const startedAt = now();
  let previousAt = startedAt;
  return (phase) => {
    const currentAt = now();
    write(
      `action-type-map: phase=${phase} deltaMs=${Math.round(currentAt - previousAt)} totalMs=${Math.round(currentAt - startedAt)}\n`,
    );
    previousAt = currentAt;
  };
}

const PRIVATE_OR_ABSOLUTE_IMPORT = /(?:@happier-dev\/|\bimport\s*\(|\bfrom\s*['"](?:\/|[A-Za-z]:[\\/]))/u;

function requireArgument() {
  const argument = process.argv.slice(2);
  if (argument.length === 0) {
    return resolveAutomaticActionTypeMapMode(process.env);
  }
  if (argument.length !== 1 || (argument[0] !== '--check' && argument[0] !== '--write')) {
    throw new Error('Usage: node scripts/generateActionTypeMap.mjs [--check|--write]');
  }
  return argument[0];
}

// The source checkout owns generated DTOs. A producer invocation without an
// explicit mode writes there via the retained input cache. A remote dev target, which
// must never write its synced copy, checks. CI verifies committed bytes explicitly with
// `check:action-type-map`. Preparation and internal builds do not invoke this producer.
export function resolveAutomaticActionTypeMapMode(env) {
  return String(env.HAPPIER_DEV_TARGET_EXECUTION ?? '').trim() === '1' ? '--check' : '--write';
}

export async function writeFileIfChanged(path, content) {
  try {
    if (await readFile(path, 'utf8') === content) return false;
  } catch (error) {
    if (error?.code !== 'ENOENT') throw error;
  }
  await writeFile(path, content, 'utf8');
  return true;
}

function describeFirstDifference(current, expected) {
  let offset = 0;
  const sharedLength = Math.min(current.length, expected.length);
  while (offset < sharedLength && current[offset] === expected[offset]) offset += 1;
  const line = current.slice(0, offset).split('\n').length;
  const currentLine = current.split('\n')[line - 1] ?? '<end of file>';
  const expectedLine = expected.split('\n')[line - 1] ?? '<end of file>';
  return `first difference at line ${line}: current=${JSON.stringify(currentLine)} expected=${JSON.stringify(expectedLine)}`;
}

function assertSameKeys(left, right, description) {
  if (left.length !== right.length || left.some((key, index) => key !== right[index])) {
    throw new Error(`${description} key mismatch: ${JSON.stringify({ left, right })}`);
  }
}

export function validateGeneratedModuleSyntax(output) {
  if (PRIVATE_OR_ABSOLUTE_IMPORT.test(output)) {
    throw new Error('Generated Action type map contains a private or absolute import.');
  }
  const sourceFile = ts.createSourceFile(
    OUTPUT_PATH,
    output,
    ts.ScriptTarget.ES2022,
    false,
    ts.ScriptKind.TS,
  );
  const diagnostics = sourceFile.parseDiagnostics;
  if (diagnostics.length > 0) {
    throw new Error(
      `Generated Action type map is not valid TypeScript: ${ts.flattenDiagnosticMessageText(diagnostics[0].messageText, '\n')}`,
    );
  }
  // Diagnostic string literals may name Zod errors without exposing its types.
  const referencesValidator = (node) => {
    if (ts.isIdentifier(node) && FORBIDDEN_PUBLIC_VALIDATOR_IDENTIFIER.test(node.text)) return true;
    const namespace = ts.isQualifiedName(node) ? node.left
      : ts.isPropertyAccessExpression(node) ? node.expression : undefined;
    if (namespace && ts.isIdentifier(namespace) && namespace.text === 'z') return true;
    const module = ts.isImportDeclaration(node) || ts.isExportDeclaration(node) ? node.moduleSpecifier
      : ts.isImportTypeNode(node) && ts.isLiteralTypeNode(node.argument) ? node.argument.literal
      : ts.isImportEqualsDeclaration(node) && ts.isExternalModuleReference(node.moduleReference) ? node.moduleReference.expression
      : undefined;
    if (module && ts.isStringLiteral(module) && /^zod(?:\/|$)/u.test(module.text)) return true;
    return ts.forEachChild(node, referencesValidator);
  };
  if (referencesValidator(sourceFile)) {
    throw new Error('Generated Action type map contains a validator-library implementation reference.');
  }
}

export async function prepareActionTypeMap() {
  const timing = createActionTypeMapTimingReporter();
  const inputDigests = new Map();
  for (const path of [SCRIPT_PATH, fileURLToPath(new URL('./deriveActionDtos.mjs', import.meta.url)),
    fileURLToPath(new URL('./readActionCatalog.mjs', import.meta.url)),
    fileURLToPath(new URL('./shareWorkflowDtoStructures.mjs', import.meta.url)),
    fileURLToPath(new URL('./shareActionDtoStructures.mjs', import.meta.url)),
    fileURLToPath(new URL('./projectCatalogMetadata.mjs', import.meta.url)), COMPILER_PATH]) {
    const source = ts.sys.readFile(path);
    if (source === undefined) throw new Error(`Action type map input is unavailable: ${path}`);
    inputDigests.set(path, digest(source));
  }
  const inputSnapshot = captureActionSchemaInputs(REPO_ROOT);
  timing('input-snapshot');
  const recordDigest = (path, current) => {
    if (inputDigests.has(path) && inputDigests.get(path) !== current) throw new Error(`Action schema inputs changed between families: ${path}`);
    inputDigests.set(path, current);
  };
  const recordInput = (path, text) => recordDigest(path, digest(text));
  const schemaProjection = await deriveActionDtoSchemas({ repoRoot: REPO_ROOT, recordInput, recordDigest, inputSnapshot });
  timing('schema-derivation');
  const projection = projectActionDtoDeclarations({
    recordInput, declarations: schemaProjection.outputs, readSource: path => inputSnapshot.get(resolve(path)),
  });
  const { inputKeys, resultKeys } = projection;
  const outputs = new Map([...schemaProjection.catalogOutputs,
    ...[...projection.outputs].map(([path, text]) => [resolve(REPO_ROOT, path), text])]);
  const output = outputs.get(OUTPUT_PATH);
  if (output === undefined) throw new Error('Action DTO projection is missing its public index.');
  timing('dto-declaration-projection');
  return Object.freeze({
    inputKeys,
    inputPaths: [...inputDigests.keys()],
    inputDigests: [...inputDigests],
    output,
    outputs,
    obsoleteOutputs: ['strictJsonValue.generated.ts', 'jsonSchema.generated.ts', 'sessionDiscussionActionDtos.generated.ts',
      'sessionTargetInspectionActionDtos.generated.ts'].map((name) =>
      resolve(PACKAGE_ROOT, 'src/actions/dtos', name)),
    resultKeys,
    stale: false,
    timing,
    familyMetrics: schemaProjection.metrics,
  });
}

export async function publishPreparedActionTypeMap(mode, prepared, { assertOwned, assertInputsCurrent }) {
  const { output, timing } = prepared;
  const outputs = prepared.outputs ?? new Map([[OUTPUT_PATH, output]]);
  for (const [path, text] of outputs) {
    if (mode === '--write') {
      await mkdir(dirname(path), { recursive: true });
      // The publication lease covers every module. Input currentness is checked
      // after the complete snapshot is written, never between family outputs.
      assertOwned();
      await writeFileIfChanged(path, text);
    } else {
      assertInputsCurrent();
      const current = await readFile(path, 'utf8');
      if (current !== text) {
        throw new Error(
          `Generated Action type map is stale: ${path} (${describeFirstDifference(current, text)}). Run pnpm --dir packages/plugin-sdk run generate:action-type-map from the repository root.`,
        );
      }
    }
  }
  for (const path of prepared.obsoleteOutputs ?? []) {
    if (mode === '--check') assertInputsCurrent();
    if (!ts.sys.fileExists(path)) continue;
    if (mode === '--check') throw new Error(`Generated Action type map has obsolete output: ${path}`);
    assertOwned();
    await unlink(path);
  }
  timing(mode === '--write' ? 'publication-write' : 'publication-check');
}

export async function runActionTypeMapWithWorkspaceLock({
  mode,
  run,
  prepare = prepareActionTypeMap,
  publish = publishPreparedActionTypeMap,
  lockPath = ACTION_MAP_LOCK_PATH,
  derivationLockPath = lockPath,
  env = process.env,
  lockOptions = {},
} = {}) {
  if (mode !== '--check' && mode !== '--write') {
    throw new Error('Action type map mode must be --check or --write');
  }
  const heldLockValue = lockOptions.heldLockValue ?? env.HAPPIER_WORKSPACE_DIST_BUILD_LOCK_HELD;
  const withDerivationLock = async (operation) => await withWorkspaceBundleLock(operation, {
    ...lockOptions,
    lockPath: derivationLockPath,
    env,
    heldLockValue,
    errorLabel: lockOptions.errorLabel
      ?? '@happier-dev/plugin-sdk generated Action map lock',
  });
  // Source DTO modules and their cache share this one lease from derivation
  // through publication. CLI dist and bundled dependency publication write
  // different paths; their inherited leases never substitute for DTO custody.
  if (run) return await withDerivationLock((context) => run(mode, context));
  const publishUnderActionMapLock = (prepared, derivationContext) => {
    derivationContext.assertOwned();
    if (mode === '--check') derivationContext.assertInputsCurrent?.();
    return publish(mode, prepared, derivationContext);
  };
  if (prepare !== prepareActionTypeMap || publish !== publishPreparedActionTypeMap) {
    return await withDerivationLock(async (lockContext) => {
      const prepared = await prepare(mode);
      const assertInputsCurrent = () => {
        if (prepared.stale === true || !preparedInputsUnchanged(prepared)) {
          throw new Error('Action type map inputs changed; generation is stale relative to current source. Run generation again.');
        }
      };
      return await publishUnderActionMapLock(prepared, { ...lockContext, assertInputsCurrent });
    });
  }
  return await runCachedActionTypeMap({
    mode,
    cachePath: CACHE_PATH,
    outputPath: OUTPUT_PATH,
    derive: () => prepare(mode),
    publish: publishUnderActionMapLock,
    withDerivationLock,
  });
}

if (process.argv[1] && resolve(process.argv[1]) === SCRIPT_PATH) {
  await runActionTypeMapWithWorkspaceLock({ mode: requireArgument() });
}
