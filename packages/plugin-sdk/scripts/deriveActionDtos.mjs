function selectSchemaRows(protocol, keys, readSource) {
  const files = new Map();
  const source = path => {
    if (!files.has(path)) files.set(path, ts.createSourceFile(path, readSource(path), ts.ScriptTarget.ES2022, true));
    return files.get(path);
  };
  const unwrapped = node => {
    while (node && (ts.isAsExpression(node) || ts.isSatisfiesExpression(node) || ts.isParenthesizedExpression(node))) node = node.expression;
    return node;
  };
  const variable = (path, name) => {
    for (const node of source(path).statements) {
      if (ts.isVariableStatement(node)) {
        const found = node.declarationList.declarations.find(n => n.name.text === name);
        if (found) return { path, node: found.initializer };
      }
      if (ts.isImportDeclaration(node) && node.importClause?.namedBindings && ts.isNamedImports(node.importClause.namedBindings)) {
        const found = node.importClause.namedBindings.elements.find(n => n.name.text === name);
        if (found && node.moduleSpecifier.text.startsWith('.')) return variable(resolve(dirname(path), node.moduleSpecifier.text.replace(/\.js$/u, '.ts')), (found.propertyName ?? found.name).text);
      }
      if (ts.isExportDeclaration(node) && node.moduleSpecifier?.text.startsWith('.') && node.exportClause && ts.isNamedExports(node.exportClause)) {
        const found = node.exportClause.elements.find(n => n.name.text === name);
        if (found) return variable(resolve(dirname(path), node.moduleSpecifier.text.replace(/\.js$/u, '.ts')), (found.propertyName ?? found.name).text);
      }
    }
    return null;
  };
  const property = (path, expression, key) => {
    let node = unwrapped(expression);
    if (ts.isIdentifier(node)) {
      const found = variable(path, node.text);
      return found ? property(found.path, found.node, key) : null;
    }
    if (ts.isCallExpression(node) && node.expression.getText(source(path)) === 'Object.freeze') return property(path, node.arguments[0], key);
    if (ts.isCallExpression(node) && ts.isIdentifier(node.expression) && node.expression.text === 'lazyDefinition') {
      const create = node.arguments[0];
      if (create && ts.isArrowFunction(create) && !ts.isBlock(create.body)) return property(path, create.body, key);
    }
    if (!ts.isObjectLiteralExpression(node)) return null;
    // Object spreads use ordinary last-write semantics.
    for (const member of [...node.properties].reverse()) {
      if (ts.isSpreadAssignment(member)) {
        const found = property(path, member.expression, key);
        if (found) return found;
      } else if (ts.isPropertyAssignment(member) && member.name.text === key) return { path, node: member.initializer };
    }
    return null;
  };
  const fromType = (path, node, key) => {
    if (ts.isIndexedAccessTypeNode(node) && ts.isParenthesizedTypeNode(node.objectType)) node = node.objectType.type;
    if (!ts.isTypeQueryNode(node) || !ts.isIdentifier(node.exprName)) return null;
    const found = variable(path, node.exprName.text);
    if (!found) return null;
    return property(found.path, found.node, key);
  };
  const query = (path, node, key) => {
    if (ts.isIndexedAccessTypeNode(node)) return fromType(path, node, key);
    if (ts.isTypeQueryNode(node) && ts.isIdentifier(node.exprName)) {
      const found = variable(path, node.exprName.text);
      return found ? { path: found.path, node: found.node.parent.name } : null;
    }
    return null;
  };
  const actionPath = resolve(protocol, 'actions/actionSpecs.ts');
  const selected = new Map();
  let requiredSurface = false;
  const definition = source(actionPath).statements.find(node => ts.isTypeAliasDeclaration(node) && node.name.text === 'CanonicalActionSchemaDefinition');
  if (definition) {
    const visit = node => {
      if (ts.isPropertySignature(node) && node.name.text === 'surfaceBindings') requiredSurface = !node.questionToken;
      ts.forEachChild(node, visit);
    };
    visit(definition);
  }
  const visitType = node => {
    if (ts.isTypeReferenceNode(node) && node.typeName.getText(source(actionPath)) === 'CanonicalActionSchemaDefinition' && node.typeArguments?.length >= 3) {
      const [id, input, output, surface] = node.typeArguments;
      for (const key of keys) {
        if (ts.isLiteralTypeNode(id) && id.literal.text !== key) continue;
        let inputRow = query(actionPath, input, key);
        const outputRow = query(actionPath, output, key);
        if (!inputRow || !outputRow) continue;
        // The canonical Plugin maps select only required surfaceBindings.
        // Optional bindings in CanonicalActionSchemaDefinition cannot satisfy
        // that conditional; their public type uses the base schema instead.
        if (surface && requiredSurface) {
          const findOverride = n => {
            if (ts.isPropertySignature(n) && n.name.text === 'inputSchema') inputRow = query(actionPath, n.type, key) ?? inputRow;
            ts.forEachChild(n, findOverride);
          };
          findOverride(surface);
        }
        if (!selected.has(key)) selected.set(key, [inputRow, outputRow]);
      }
    }
    ts.forEachChild(node, visitType);
  };
  visitType(source(actionPath));
  // Literal Action rows supply the remaining canonical definitions. Follow
  // only the registry's imported spec-array owners, not arbitrary files.
  const specPaths = new Set([actionPath]);
  for (const node of source(actionPath).statements) {
    if (ts.isImportDeclaration(node) && node.moduleSpecifier.text.startsWith('.') && node.importClause?.namedBindings
      && ts.isNamedImports(node.importClause.namedBindings) && node.importClause.namedBindings.elements.some(n => /ACTION_SPECS(?:_V\d+)?$/u.test((n.propertyName ?? n.name).text))) {
      specPaths.add(resolve(dirname(actionPath), node.moduleSpecifier.text.replace(/\.js$/u, '.ts')));
    }
  }
  const stringArray = (path, expression) => {
    const node = unwrapped(expression);
    if (ts.isIdentifier(node)) {
      const found = variable(path, node.text);
      return found ? stringArray(found.path, found.node) : [];
    }
    if (!ts.isArrayLiteralExpression(node)) return [];
    return node.elements.flatMap(n => ts.isStringLiteral(n) ? [n.text]
      : ts.isSpreadElement(n) ? stringArray(path, n.expression) : []);
  };
  for (const path of specPaths) {
    const visit = node => {
      // Scope adapters may construct rows by passing a literal Action id to
      // a helper. Resolve only its keyed schema maps, without evaluating the
      // helper's runtime metadata or duplicating the family's schema owner.
      if (ts.isCallExpression(node) && ts.isIdentifier(node.expression)
        && node.arguments.length === 1 && ts.isStringLiteral(node.arguments[0])) {
        const key = node.arguments[0].text;
        const helper = source(path).statements.find(statement => ts.isFunctionDeclaration(statement)
          && statement.name?.text === node.expression.text && statement.body);
        const parameter = helper?.parameters.length === 1 && ts.isIdentifier(helper.parameters[0].name)
          ? helper.parameters[0].name.text : null;
        if (parameter && keys.includes(key) && !selected.has(key)) {
          for (const statement of helper.body?.statements ?? []) {
            if (!ts.isReturnStatement(statement) || !statement.expression) continue;
            const row = unwrapped(statement.expression);
            if (!ts.isObjectLiteralExpression(row)) continue;
            const id = row.properties.find(member => member.name?.text === 'id');
            const idExpression = id && (ts.isShorthandPropertyAssignment(id) ? id.name
              : ts.isPropertyAssignment(id) ? id.initializer : undefined);
            if (!idExpression || !ts.isIdentifier(idExpression) || idExpression.text !== parameter) continue;
            const keyed = name => {
              const field = property(path, row, name);
              if (!field || !ts.isElementAccessExpression(field.node)
                || !ts.isIdentifier(field.node.argumentExpression)
                || field.node.argumentExpression.text !== parameter) return null;
              return property(field.path, field.node.expression, key);
            };
            const input = keyed('inputSchema'), output = keyed('outputSchema');
            if (input && output) selected.set(key, [input, output]);
          }
        }
      }
      // Some canonical spec owners map declared Action ids through schema maps.
      // Resolve those maps by the actual id, never by evaluating runtime specs.
      if (ts.isCallExpression(node) && ts.isPropertyAccessExpression(node.expression) && node.expression.name.text === 'map') {
        const callback = node.arguments[0];
        if (callback && ts.isArrowFunction(callback) && callback.parameters.length === 1 && ts.isIdentifier(callback.parameters[0].name)) {
          const parameter = callback.parameters[0].name.text;
          const rows = ts.isBlock(callback.body) ? callback.body.statements.filter(ts.isReturnStatement).map(n => n.expression) : [callback.body];
          for (const expression of rows) {
            const row = expression && unwrapped(expression);
            if (!row || !ts.isObjectLiteralExpression(row)) continue;
            const id = row.properties.find(n => n.name?.text === 'id');
            const idExpression = id && (ts.isShorthandPropertyAssignment(id) ? id.name : ts.isPropertyAssignment(id) ? id.initializer : undefined);
            if (!idExpression || !ts.isIdentifier(idExpression) || idExpression.text !== parameter) continue;
            for (const key of stringArray(path, node.expression.expression)) {
              if (!keys.includes(key) || selected.has(key)) continue;
              const keyed = name => {
                const field = property(path, row, name);
                if (!field || !ts.isElementAccessExpression(field.node) || !ts.isIdentifier(field.node.argumentExpression)
                  || field.node.argumentExpression.text !== parameter) return null;
                return property(field.path, field.node.expression, key);
              };
              const input = keyed('inputSchema'), output = keyed('outputSchema');
              if (input && output) selected.set(key, [input, output]);
            }
          }
        }
      }
      if (ts.isObjectLiteralExpression(node)) {
        const id = node.properties.find(n => ts.isPropertyAssignment(n) && n.name.text === 'id');
        if (id && ts.isStringLiteral(id.initializer) && keys.includes(id.initializer.text) && !selected.has(id.initializer.text)) {
          const input = property(path, node, 'inputSchema');
          const output = property(path, node, 'outputSchema');
          const surface = property(path, node, 'surfaceBindings');
          const plugin = surface && property(surface.path, surface.node, 'plugin');
          const pluginInput = plugin && property(plugin.path, plugin.node, 'inputSchema');
          const pluginOutput = plugin && property(plugin.path, plugin.node, 'outputSchema');
          if (input && output) selected.set(id.initializer.text, [pluginInput ?? input, pluginOutput ?? output]);
        }
      }
      ts.forEachChild(node, visit);
    };
    visit(source(path));
  }
  for (const key of keys) if (!selected.has(key)) throw Error(`No canonical schema expression for Action ${key}`);
  for (const [key, rows] of selected) selected.set(key, rows.map(row => {
    if (!ts.isIdentifier(row.node)) return row;
    const found = variable(row.path, row.node.text);
    return found ? { path: found.path, node: found.node.parent.name } : row;
  }));
  return { rows: selected, sources: files };
}
