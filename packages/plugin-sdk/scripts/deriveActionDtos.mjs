function selectSchemaRows(protocol, keys, readSource) {
  const files = new Map();
  const source = path => {
    if (!files.has(path)) files.set(path, ts.createSourceFile(path, readSource(path), ts.ScriptTarget.ES2022, true));
    return files.get(path);
  };
  const catalogReader = createActionCatalogReader(path => source(path).text);
  const unwrapped = node => {
    while (node && (ts.isAsExpression(node) || ts.isSatisfiesExpression(node) || ts.isParenthesizedExpression(node))) node = node.expression;
    return node;
  };
  const variable = (path, name) => {
    for (const node of source(path).statements) {
      if (ts.isVariableStatement(node)) {
        const found = node.declarationList.declarations.find(n => n.name.text === name);
        if (found) return { path, node: found.initializer };
      }
      if (ts.isImportDeclaration(node) && node.importClause?.namedBindings && ts.isNamedImports(node.importClause.namedBindings)) {
        const found = node.importClause.namedBindings.elements.find(n => n.name.text === name);
        if (found && node.moduleSpecifier.text.startsWith('.')) return variable(resolve(dirname(path), node.moduleSpecifier.text.replace(/\.js$/u, '.ts')), (found.propertyName ?? found.name).text);
      }
      if (ts.isExportDeclaration(node) && node.moduleSpecifier?.text.startsWith('.') && node.exportClause && ts.isNamedExports(node.exportClause)) {
        const found = node.exportClause.elements.find(n => n.name.text === name);
        if (found) return variable(resolve(dirname(path), node.moduleSpecifier.text.replace(/\.js$/u, '.ts')), (found.propertyName ?? found.name).text);
      }
    }
    return null;
  };
  const helperBindings = (path, helper, bindings = new Map()) => {
    const locals = new Map(bindings);
    for (const statement of helper.body.statements) {
      if (!ts.isVariableStatement(statement)) continue;
      for (const declaration of statement.declarationList.declarations) {
        if (!ts.isIdentifier(declaration.name)) continue;
        // Mutable locals still shadow the caller, even though their value is not statically readable.
        locals.set(declaration.name.text, null);
        if ((statement.declarationList.flags & ts.NodeFlags.Const) && declaration.initializer) {
          locals.set(declaration.name.text, { path, node: declaration.initializer });
        }
      }
    }
    return locals;
  };
  const property = (path, expression, key, bindings = new Map()) => {
    let node = unwrapped(expression);
    if (ts.isIdentifier(node)) {
      const local = bindings.get(node.text);
      if (local) return property(local.path, local.node, key, local.bindings ?? bindings);
      if (bindings.has(node.text)) return null;
      const found = variable(path, node.text);
      return found ? property(found.path, found.node, key) : null;
    }
    if (ts.isCallExpression(node) && node.expression.getText(source(path)) === 'Object.freeze') return property(path, node.arguments[0], key, bindings);
    if (ts.isCallExpression(node) && ts.isIdentifier(node.expression) && node.expression.text === 'lazyDefinition') {
      const create = node.arguments[0];
      if (create && ts.isArrowFunction(create) && !ts.isBlock(create.body)) return property(path, create.body, key, bindings);
    }
    // A metadata-only helper may supply the id while its enclosing row owns schemas.
    if (key === 'id' && ts.isCallExpression(node) && ts.isIdentifier(node.expression)) {
      const helper = source(path).statements.find(statement => ts.isFunctionDeclaration(statement)
        && statement.name?.text === node.expression.text && statement.body);
      const returns = helper?.body.statements.filter(statement => ts.isReturnStatement(statement) && statement.expression);
      if (returns?.length === 1) {
        const argumentsByName = helperBindings(path, helper, bindings);
        helper.parameters.forEach((parameter, index) => {
          if (ts.isIdentifier(parameter.name) && node.arguments[index]) {
            argumentsByName.set(parameter.name.text, { path, node: unwrapped(node.arguments[index]), bindings });
          }
        });
        // Inspect the declared return object only; runtime metadata never executes.
        return property(path, returns[0].expression, key, argumentsByName);
      }
    }
    if (!ts.isObjectLiteralExpression(node)) return null;
    // Object spreads use ordinary last-write semantics.
    for (const member of [...node.properties].reverse()) {
      if (ts.isSpreadAssignment(member)) {
        const found = property(path, member.expression, key, bindings);
        if (found) return found;
      } else if (ts.isPropertyAssignment(member) || ts.isShorthandPropertyAssignment(member)) {
        let memberKey = member.name.text;
        if (ts.isComputedPropertyName(member.name)) {
          try { memberKey = catalogReader.evaluate(path, member.name.expression); } catch { continue; }
        }
        if (memberKey !== key) continue;
        const value = ts.isShorthandPropertyAssignment(member) ? member.name : member.initializer;
        return ts.isIdentifier(value) && bindings.has(value.text) ? bindings.get(value.text) : { path, node: value };
      }
    }
    return null;
  };
  const fromType = (path, node, key) => {
    if (ts.isIndexedAccessTypeNode(node) && ts.isParenthesizedTypeNode(node.objectType)) node = node.objectType.type;
    if (!ts.isTypeQueryNode(node) || !ts.isIdentifier(node.exprName)) return null;
    const found = variable(path, node.exprName.text);
    if (!found) return null;
    // A schema family can derive its maps through a typed shared definition.
    // Let the same checker infer the keyed schema rather than requiring literal rows.
    return property(found.path, found.node, key)
      ?? { path: found.path, node: found.node.parent.name, key };
  };
  const query = (path, node, key) => {
    if (ts.isIndexedAccessTypeNode(node)) return fromType(path, node, key);
    if (ts.isTypeQueryNode(node) && ts.isIdentifier(node.exprName)) {
      const found = variable(path, node.exprName.text);
      return found ? { path: found.path, node: found.node.parent.name } : null;
    }
    return null;
  };
  const actionPath = resolve(protocol, 'actions/actionSpecs.ts');
  const selected = new Map();
  const inferred = new Map();
  let requiredSurface = false;
  const definition = source(actionPath).statements.find(node => ts.isTypeAliasDeclaration(node) && node.name.text === 'CanonicalActionSchemaDefinition');
  if (definition) {
    const visit = node => {
      if (ts.isPropertySignature(node) && node.name.text === 'surfaceBindings') requiredSurface = !node.questionToken;
      ts.forEachChild(node, visit);
    };
    visit(definition);
  }
  const requiredPropertyType = (node, name) => {
    if (!node) return null;
    if (ts.isParenthesizedTypeNode(node)) return requiredPropertyType(node.type, name);
    if (ts.isTypeReferenceNode(node) && node.typeName.getText(source(actionPath)) === 'Readonly') {
      return requiredPropertyType(node.typeArguments?.[0], name);
    }
    if (!ts.isTypeLiteralNode(node)) return null;
    return node.members.find(member => ts.isPropertySignature(member) && !member.questionToken
      && member.name.getText(source(actionPath)) === name)?.type ?? null;
  };
  const visitType = node => {
    if (ts.isTypeReferenceNode(node) && node.typeName.getText(source(actionPath)) === 'CanonicalActionSchemaDefinition' && node.typeArguments?.length >= 3) {
      const [id, input, output, surface] = node.typeArguments;
      for (const key of keys) {
        if (ts.isLiteralTypeNode(id) && id.literal.text !== key) continue;
        let inputRow = query(actionPath, input, key);
        const outputRow = query(actionPath, output, key);
        if (!inputRow || !outputRow) continue;
        // The canonical Plugin maps select only required surfaceBindings.
        // Optional bindings in CanonicalActionSchemaDefinition cannot satisfy
        // that conditional; their public type uses the base schema instead.
        if (surface && requiredSurface) {
          const findOverride = n => {
            if (ts.isPropertySignature(n) && n.name.text === 'inputSchema') inputRow = query(actionPath, n.type, key) ?? inputRow;
            ts.forEachChild(n, findOverride);
          };
          findOverride(surface);
        }
        // A concrete family row can require its binding without widening all
        // optional family bindings. Match the same required-property contract
        // as PluginActionDomainInputSchemaById at that intersection only.
        if (ts.isIntersectionTypeNode(node.parent)) {
          for (const part of node.parent.types) {
            const bindings = requiredPropertyType(part, 'surfaceBindings');
            const plugin = requiredPropertyType(bindings, 'plugin');
            const schema = requiredPropertyType(plugin, 'inputSchema');
            if (schema) inputRow = query(actionPath, schema, key) ?? inputRow;
          }
        }
        // A mapped type's parameter can range over only part of the catalog.
        // Prefer a concrete authored row before asking the checker to infer a map key.
        const destination = inputRow.key === undefined && outputRow.key === undefined ? selected : inferred;
        if (!destination.has(key)) destination.set(key, [inputRow, outputRow]);
      }
    }
    ts.forEachChild(node, visitType);
  };
  visitType(source(actionPath));
  // Literal Action rows supply the remaining canonical definitions. Follow
  // the registry's named spec-array imports and re-exports to their owners.
  const specPaths = new Set();
  const addImportedSpecOwners = path => {
    if (specPaths.has(path)) return;
    specPaths.add(path);
    for (const node of source(path).statements) {
      const bindings = ts.isImportDeclaration(node) ? node.importClause?.namedBindings
        : ts.isExportDeclaration(node) ? node.exportClause : undefined;
      if (bindings && (ts.isNamedImports(bindings) || ts.isNamedExports(bindings))
        && node.moduleSpecifier && ts.isStringLiteral(node.moduleSpecifier) && node.moduleSpecifier.text.startsWith('.')
        && bindings.elements.some(n => /ACTION_SPECS(?:_V\d+)?$/u.test((n.propertyName ?? n.name).text))) {
        addImportedSpecOwners(resolve(dirname(path), node.moduleSpecifier.text.replace(/\.js$/u, '.ts')));
      }
    }
  };
  addImportedSpecOwners(actionPath);
  const stringArray = (path, expression) => {
    const node = unwrapped(expression);
    if (ts.isIdentifier(node)) {
      const found = variable(path, node.text);
      return found ? stringArray(found.path, found.node) : [];
    }
    if (!ts.isArrayLiteralExpression(node)) return [];
    return node.elements.flatMap(n => ts.isStringLiteral(n) ? [n.text]
      : ts.isSpreadElement(n) ? stringArray(path, n.expression) : []);
  };
  const tupleStringArray = (path, expression, index) => {
    const node = unwrapped(expression);
    if (ts.isIdentifier(node)) {
      const found = variable(path, node.text);
      return found ? tupleStringArray(found.path, found.node, index) : [];
    }
    if (!ts.isArrayLiteralExpression(node)) return [];
    return node.elements.flatMap(element => {
      if (ts.isSpreadElement(element)) return tupleStringArray(path, element.expression, index);
      const tuple = unwrapped(element);
      const value = ts.isArrayLiteralExpression(tuple) ? tuple.elements[index] : undefined;
      return value && ts.isStringLiteral(value) ? [value.text] : [];
    });
  };
  for (const path of specPaths) {
    const wrappedOutputs = new Map();
    const visit = node => {
      // Scope adapters may construct rows by passing a literal Action id or tuple to
      // a helper. Resolve only its keyed schema maps, without evaluating the
      // helper's runtime metadata or duplicating the family's schema owner.
      if (ts.isCallExpression(node) && ts.isIdentifier(node.expression)
        && node.arguments.length >= 1) {
        const argument = unwrapped(node.arguments[0]);
        const helper = source(path).statements.find(statement => ts.isFunctionDeclaration(statement)
          && statement.name?.text === node.expression.text && statement.body);
        const binding = helper?.parameters.length >= 1 ? helper.parameters[0].name : null;
        if (binding) {
          const locals = helperBindings(path, helper);
          for (const statement of helper.body?.statements ?? []) {
            if (!ts.isReturnStatement(statement) || !statement.expression) continue;
            const row = unwrapped(statement.expression);
            // A spec constructor can replace the literal row's output schema.
            // Let the checker read that constructor's returned schema.
            if (ts.isObjectLiteralExpression(argument) && ts.isObjectLiteralExpression(row)
              && row.properties.some(member => member.name?.text === 'outputSchema')) {
              wrappedOutputs.set(argument, { path, node, key: 'outputSchema' });
            }
            const idExpression = property(path, row, 'id', locals)?.node;
            if (!idExpression || !ts.isIdentifier(idExpression)) continue;
            const idIndex = ts.isArrayBindingPattern(binding) ? binding.elements.findIndex(element =>
              ts.isBindingElement(element) && ts.isIdentifier(element.name) && element.name.text === idExpression.text) : -1;
            const idArgument = ts.isIdentifier(binding) && binding.text === idExpression.text ? argument
              : idIndex >= 0 && ts.isArrayLiteralExpression(argument) ? argument.elements[idIndex] : undefined;
            if (!idArgument) continue;
            let key;
            try { key = catalogReader.evaluate(path, idArgument); } catch { continue; }
            if (typeof key !== 'string') continue;
            if (!keys.includes(key) || selected.has(key)) continue;
            const keyed = name => {
              const field = property(path, row, name, locals);
              if (!field || !ts.isElementAccessExpression(field.node)
                || !ts.isIdentifier(field.node.argumentExpression)
                || field.node.argumentExpression.text !== idExpression.text) return null;
              return property(field.path, field.node.expression, key);
            };
            const input = keyed('inputSchema'), output = keyed('outputSchema');
            if (input && output) selected.set(key, [input, output]);
          }
        }
      }
      // Some canonical spec owners map declared Action ids through schema maps.
      // Resolve those maps by the actual id, never by evaluating runtime specs.
      if (ts.isCallExpression(node) && ts.isPropertyAccessExpression(node.expression) && node.expression.name.text === 'map') {
        const callback = node.arguments[0];
        if (callback && ts.isArrowFunction(callback) && callback.parameters.length === 1) {
          const binding = callback.parameters[0].name;
          const rows = ts.isBlock(callback.body) ? callback.body.statements.filter(ts.isReturnStatement).map(n => n.expression) : [callback.body];
          for (const expression of rows) {
            const row = expression && unwrapped(expression);
            if (!row || !ts.isObjectLiteralExpression(row)) continue;
            const id = row.properties.find(n => n.name?.text === 'id');
            const idExpression = id && (ts.isShorthandPropertyAssignment(id) ? id.name : ts.isPropertyAssignment(id) ? id.initializer : undefined);
            if (!idExpression || !ts.isIdentifier(idExpression)) continue;
            const mappedKeys = ts.isIdentifier(binding) && binding.text === idExpression.text
              ? stringArray(path, node.expression.expression)
              : ts.isArrayBindingPattern(binding)
                ? (() => {
                    const index = binding.elements.findIndex(element => ts.isBindingElement(element)
                      && ts.isIdentifier(element.name) && element.name.text === idExpression.text);
                    return index < 0 ? [] : tupleStringArray(path, node.expression.expression, index);
                  })()
                : [];
            for (const key of mappedKeys) {
              if (!keys.includes(key) || selected.has(key)) continue;
              const keyed = name => {
                const field = property(path, row, name);
                if (!field || !ts.isElementAccessExpression(field.node) || !ts.isIdentifier(field.node.argumentExpression)
                  || field.node.argumentExpression.text !== idExpression.text) return null;
                return property(field.path, field.node.expression, key);
              };
              const input = keyed('inputSchema'), output = keyed('outputSchema');
              if (input && output) selected.set(key, [input, output]);
            }
          }
        }
      }
      if (ts.isObjectLiteralExpression(node)) {
        const id = property(path, node, 'id');
        let key;
        if (id) {
          try { key = catalogReader.evaluate(id.path, id.node); } catch {
            // Dynamic callback ids are handled by the keyed-map paths above.
          }
        }
        if (typeof key === 'string' && keys.includes(key) && !selected.has(key)) {
          const input = property(path, node, 'inputSchema');
          const output = wrappedOutputs.get(node) ?? property(path, node, 'outputSchema');
          const surface = property(path, node, 'surfaceBindings');
          const plugin = surface && property(surface.path, surface.node, 'plugin');
          const pluginInput = plugin && property(plugin.path, plugin.node, 'inputSchema');
          const pluginOutput = plugin && property(plugin.path, plugin.node, 'outputSchema');
          if (input) selected.set(key, [pluginInput ?? input, pluginOutput ?? output]);
        }
      }
      ts.forEachChild(node, visit);
    };
    visit(source(path));
  }
  for (const key of keys) {
    if (!selected.has(key) && inferred.has(key)) selected.set(key, inferred.get(key));
    if (!selected.has(key)) throw Error(`No canonical schema expression for Action ${key}`);
  }
  for (const [key, rows] of selected) selected.set(key, rows.map(row => {
    if (!row) return row;
    if (ts.isElementAccessExpression(row.node) && ts.isStringLiteral(row.node.argumentExpression)) {
      row = property(row.path, row.node.expression, row.node.argumentExpression.text) ?? row;
    }
    if (!ts.isIdentifier(row.node)) return row;
    const found = variable(row.path, row.node.text);
    return found ? { ...row, path: found.path, node: found.node.parent.name } : row;
  }));
  return { rows: selected, sources: files, inputProjection: source(actionPath).statements.some(statement =>
    ts.isTypeAliasDeclaration(statement) && statement.name.text === 'WithClientRoutingInput') };
}
