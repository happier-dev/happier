export function readActionCatalog(repoRoot, recordInput = () => {}, readSource = path => readFileSync(path, 'utf8')) {
  const sources = new Map();
  const source = path => {
    if (!sources.has(path)) {
      const text = readSource(path);
      recordInput(path, text);
      sources.set(path, ts.createSourceFile(path, text, ts.ScriptTarget.ES2022, true));
    }
    return sources.get(path);
  };
  const definition = (path, name) => {
    for (const node of source(path).statements) {
      if (ts.isVariableStatement(node)) {
        const declaration = node.declarationList.declarations.find(n => ts.isIdentifier(n.name) && n.name.text === name);
        if (declaration) return { path, node: declaration.initializer };
      }
      if (ts.isImportDeclaration(node) && node.importClause?.namedBindings && ts.isNamedImports(node.importClause.namedBindings)) {
        const binding = node.importClause.namedBindings.elements.find(n => n.name.text === name);
        if (binding) return definition(resolve(dirname(path), node.moduleSpecifier.text.replace(/\.js$/u, '.ts')), (binding.propertyName ?? binding.name).text);
      }
    }
    throw Error(`Unresolved Action catalog declaration: ${name}`);
  };
  const value = (path, name) => {
    const found = definition(path, name);
    return evaluate(found.path, found.node);
  };
  const unwrap = node => {
    while (ts.isAsExpression(node) || ts.isSatisfiesExpression(node) || ts.isParenthesizedExpression(node)) node = node.expression;
    return node;
  };
  const owner = (path, node) => {
    node = unwrap(node);
    if (!ts.isIdentifier(node)) return path;
    const found = definition(path, node.text);
    return owner(found.path, found.node);
  };
  const evaluate = (path, node) => {
    if (ts.isAsExpression(node) || ts.isSatisfiesExpression(node) || ts.isParenthesizedExpression(node)) return evaluate(path, node.expression);
    if (ts.isIdentifier(node)) return value(path, node.text);
    if (ts.isStringLiteral(node)) return node.text;
    if (ts.isArrayLiteralExpression(node)) return node.elements.flatMap(n => ts.isSpreadElement(n) ? evaluate(path, n.expression) : [evaluate(path, n)]);
    if (ts.isObjectLiteralExpression(node)) return Object.assign({}, ...node.properties.map(n => ts.isSpreadAssignment(n) ? evaluate(path, n.expression) : { [n.name.text]: evaluate(path, n.initializer) }));
    if (ts.isCallExpression(node) && node.expression.getText(source(path)) === 'Object.freeze') return evaluate(path, node.arguments[0]);
    if (ts.isCallExpression(node) && node.expression.getText(source(path)) === 'Object.values') return Object.values(evaluate(path, node.arguments[0]));
    throw Error(`Unsupported Action catalog expression: ${node.getText(source(path))}`);
  };
  const protocol = resolve(repoRoot, 'packages/protocol/src');
  const catalog = definition(resolve(protocol, 'actions/actionIds.ts'), 'ACTION_ID_FAMILIES_V1');
  let catalogNode = unwrap(catalog.node);
  if (ts.isCallExpression(catalogNode) && catalogNode.expression.getText(source(catalog.path)) === 'Object.freeze') catalogNode = unwrap(catalogNode.arguments[0]);
  if (!ts.isObjectLiteralExpression(catalogNode)) throw Error('Action family catalog must declare its family exports');
  const familyOwners = Object.fromEntries(catalogNode.properties.map(member => {
    if (!ts.isPropertyAssignment(member)) throw Error('Action family catalog must name each family export');
    return [member.name.text, owner(catalog.path, member.initializer)];
  }));
  return { families: value(resolve(protocol, 'actions/actionIds.ts'), 'ACTION_ID_FAMILIES_V1'),
    familyOwners, excluded: value(resolve(protocol, 'actions/pluginActionSurface.ts'), 'PLUGIN_SURFACE_EXCLUSION_REASONS') };
}

function createDerivationHost(inputSnapshot) {
  const options = { strict: true, skipLibCheck: true, target: ts.ScriptTarget.ES2022,
    module: ts.ModuleKind.ESNext, moduleResolution: ts.ModuleResolutionKind.Bundler,
    // Match Protocol's ambient contract. Imported declarations still resolve;
    // unrelated application @types must not inflate every family or its input identity.
    types: ['node'] };
  const host = ts.createCompilerHost(options);
  const read = inputSnapshot ? path => inputSnapshot.get(resolve(path)) : host.readFile.bind(host);
  const parse = host.getSourceFile.bind(host);
  const sources = new Map();
  const session = { options, host, read, inputs: new Map(), overlays: new Map(), metrics: null };
  if (inputSnapshot) {
    const directories = new Set();
    for (const path of inputSnapshot.keys()) {
      for (let directory = dirname(path); !directories.has(directory); directory = dirname(directory)) {
        directories.add(directory);
        if (dirname(directory) === directory) break;
      }
    }
    host.fileExists = path => session.overlays.has(path) || inputSnapshot.has(resolve(path));
    host.directoryExists = path => directories.has(resolve(path));
  }
  host.readFile = path => {
    if (session.overlays.has(path)) return session.overlays.get(path);
    const text = session.inputs.get(path) ?? read(path);
    if (text !== undefined) session.inputs.set(path, text);
    return text;
  };
  host.getSourceFile = (path, languageVersion, onError, shouldCreateNewSourceFile) => {
    const text = host.readFile(path);
    const previous = sources.get(path);
    const target = typeof languageVersion === 'object' ? languageVersion.languageVersion : languageVersion;
    const format = typeof languageVersion === 'object' ? languageVersion.impliedNodeFormat : undefined;
    if (!shouldCreateNewSourceFile && previous && previous.source.text === text && previous.target === target && previous.format === format) {
      session.metrics.sourceFilesReused += 1;
      return previous.source;
    }
    const start = performance.now();
    const source = parse(path, languageVersion, onError, shouldCreateNewSourceFile);
    session.metrics.parseMs += performance.now() - start;
    if (source) {
      session.metrics.sourceFilesParsed += 1;
      sources.set(path, { source, target, format });
    } else sources.delete(path);
    return source;
  };
  return session;
}

// Resolve the complete canonical compiler closure once, without constructing a
// checker. Families may replace schema overlays, but never reread live inputs.
// Include resolution metadata and imported declarations as well as Protocol text.
export function captureActionSchemaInputs(repoRoot) {
  const { options } = createDerivationHost();
  const host = ts.createCompilerHost(options);
  const inputs = new Map();
  const read = host.readFile.bind(host);
  host.readFile = path => {
    const key = resolve(path);
    if (!inputs.has(key)) inputs.set(key, read(path));
    return inputs.get(key);
  };
  readActionCatalog(repoRoot, () => {}, host.readFile);
  const protocol = resolve(repoRoot, 'packages/protocol/src');
  const roots = ['actions/actionSpecs.ts', ...supportBindings.map(([path]) => path),
    ...uiBindings.map(([path]) => path), ...Object.values(neutralImports)]
    .map(path => resolve(protocol, path)).filter(host.fileExists);
  ts.createProgram([...new Set(roots)], options, host);
  for (const path of ['identity.ts', 'scm/projections.ts']) {
    host.readFile(resolve(repoRoot, 'packages/plugin-sdk/src', path));
  }
  return new Map([...inputs].filter(([, text]) => text !== undefined));
}

function deriveProgram({ repoRoot, keys, bindings, extraNames = [], extraInputNames = [] }, session = createDerivationHost()) {
  const protocol = resolve(repoRoot, 'packages/protocol/src');
  const actionSpecs = resolve(protocol, 'actions/actionSpecs.ts');
  const inputs = new Map();
  const overlays = new Map();
  const { options, host, read } = session;
  session.inputs = inputs;
  session.overlays = overlays;
  session.metrics = { sourceFilesParsed: 0, sourceFilesReused: 0, parseMs: 0 };
  if (keys) {
    const { rows, sources } = selectSchemaRows(protocol, keys, path => {
      const text = inputs.get(path) ?? read(path);
      if (text === undefined) throw Error(`Missing canonical schema source ${path}`);
      inputs.set(path, text);
      return text;
    });
    const required = new Map();
    const rootImports = [];
    const members = [[], []];
    let counter = 0;
    for (const [key, expressions] of rows) expressions.forEach(({ path, node }, i) => {
      const name = `ActionSchema${counter++}`;
      if (!required.has(path)) required.set(path, []);
      required.get(path).push(`const ${name} = ${node.getText(sources.get(path))};\nexport type ${name}Value = z.${i ? 'output' : 'input'}<typeof ${name}>;`);
      rootImports.push(`import type { ${name}Value } from ${JSON.stringify('./' + relative(resolve(protocol, 'actions'), path).replaceAll('\\', '/').replace(/\.ts$/u, '.js'))};`);
      members[i].push(`readonly ${JSON.stringify(key)}: ${name}Value;`);
    });
    for (const [path, added] of required) {
      const original = sources.get(path);
      // Spec modules carry unrelated registry imports. Domain schemas retain
      // complete exports because another selected schema may import them.
      if (path !== actionSpecs && relative(resolve(protocol, 'actions/specs'), path).startsWith('..')) {
        overlays.set(path, original.text + '\n' + added.join('\n') + '\n');
        continue;
      }
      const full = ts.createSourceFile(path, original.text + '\n' + added.join('\n'), ts.ScriptTarget.ES2022, true);
      const selected = new Set();
      const needed = new Set(added.flatMap(text => {
        const file = ts.createSourceFile('added.ts', text, ts.ScriptTarget.ES2022, true);
        return collectIdentifiers(file);
      }));
      for (const name of needed) {
        for (const statement of full.statements) {
          const names = ts.isVariableStatement(statement) ? statement.declarationList.declarations.map(n => n.name.text)
            : statement.name && ts.isIdentifier(statement.name) ? [statement.name.text] : [];
          if (names.includes(name) && !selected.has(statement)) {
            selected.add(statement);
            collectIdentifiers(statement).forEach(n => needed.add(n));
          }
        }
      }
      const statements = full.statements.flatMap(statement => {
        if (ts.isImportDeclaration(statement) && statement.importClause?.namedBindings
          && ts.isNamespaceImport(statement.importClause.namedBindings)) {
          return needed.has(statement.importClause.namedBindings.name.text) ? [statement.getText(full)] : [];
        }
        if (ts.isImportDeclaration(statement) && statement.importClause?.namedBindings && ts.isNamedImports(statement.importClause.namedBindings)) {
          const elements = statement.importClause.namedBindings.elements.filter(n => needed.has(n.name.text));
          if (!elements.length) return [];
          return [printer.printNode(ts.EmitHint.Unspecified, ts.factory.updateImportDeclaration(statement, statement.modifiers,
            ts.factory.updateImportClause(statement.importClause, statement.importClause.isTypeOnly, statement.importClause.name,
              ts.factory.updateNamedImports(statement.importClause.namedBindings, elements)), statement.moduleSpecifier, statement.attributes), full)];
        }
        return selected.has(statement) ? [statement.getText(full)] : [];
      });
      if (!statements.some(text => /import \{ z \} from ['"]zod['"]/u.test(text))) statements.unshift("import { z } from 'zod';");
      overlays.set(path, statements.join('\n') + '\n');
    }
    const rootPath = resolve(protocol, 'actions/actionDtoDerivation.ts');
    overlays.set(rootPath, rootImports.join('\n') + '\n' + members.map((rows, i) => `export type PluginAction${i ? 'Result' : 'Input'}ById = { ${rows.join('\n')} };`).join('\n'));
    bindings = bindings.map(([, name, out, input]) => ['actions/actionDtoDerivation.ts', name, out, input]);
  }
  // Reuse only unchanged ASTs through the shared compiler host. Each
  // family still gets its own checker and virtual schemas. Immutable input
  // bytes stay shared; a changed virtual overlay is parsed afresh.
  const programStart = performance.now();
  const program = ts.createProgram([...new Set(bindings.map(([path]) => resolve(protocol, path)))], options, host);
  const checker = program.getTypeChecker();
  const programMs = performance.now() - programStart;
  const projectionStart = performance.now();
  const renames = new Map([...supportBindings, ...uiBindings].filter(([, , out]) => out).map(([, name, out]) => [name, out]));
  const declarations = new Map();
  const references = new Set();
  const inputReferences = new Set();
  const symbolIn = (path, name) => {
    const file = program.getSourceFile(resolve(protocol, path));
    if (!file) throw Error(`Missing schema source: ${path}`);
    const module = checker.getSymbolAtLocation(file);
    let symbol = module && checker.getExportsOfModule(module).find(n => n.name === name);
    symbol ??= file.locals?.get(name);
    if (!symbol) throw Error(`Missing canonical type ${name} in ${path}`);
    return symbol.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(symbol) : symbol;
  };
  const findSymbol = name => {
    const binding = [...supportBindings, ...uiBindings].find(([, canonical]) => canonical === name);
    if (binding) return symbolIn(binding[0], name);
    for (const file of program.getSourceFiles()) {
      const node = file.statements.find(n => (ts.isTypeAliasDeclaration(n) || ts.isInterfaceDeclaration(n)) && n.name.text === name);
      if (node) return checker.getSymbolAtLocation(node.name);
    }
    throw Error(`Unresolved schema type reference: ${name}`);
  };
  const normalize = (text, input = false, parameters = new Set()) => {
    const file = ts.createSourceFile('dto.ts', `type Dto = ${text};`, ts.ScriptTarget.ES2022, true);
    if (file.parseDiagnostics.length) throw Error('Schema projection did not parse');
    const transformed = ts.transform(file.statements[0].type, [context => {
      const visit = node => {
        if (ts.isMappedTypeNode(node)) {
          const name = node.typeParameter.name.text;
          const alreadyScoped = parameters.has(name);
          parameters.add(name);
          try { return ts.visitEachChild(node, visit, context); }
          finally { if (!alreadyScoped) parameters.delete(name); }
        }
        if (ts.isIntersectionTypeNode(node)) {
          const retained = node.types.filter(n => !/^(?:z\.core\.)?\$brand</u.test(n.getText(file)));
          if (retained.length !== node.types.length) return ts.visitNode(retained.length === 1 ? retained[0] : ts.factory.createIntersectionTypeNode(retained), visit);
        }
        if (ts.isTypeReferenceNode(node)) {
          const name = node.typeName.getText(file);
          if (/^(?:z\.)?Zod|^z\.core\.\$Zod/u.test(name)) return ts.factory.createKeywordTypeNode(ts.SyntaxKind.UnknownKeyword);
          if (input && name === 'PluginJsonValueV2' && ts.isUnionTypeNode(node.parent)) {
            // An optional JSON union is projected member by member: its outer
            // containers retain mutability while nested values use JsonValue.
            // Expand the canonical union rather than inventing another JSON type.
            const canonical = checker.getDeclaredTypeOfSymbol(findSymbol(name));
            const projected = normalize(checker.typeToString(canonical, undefined, flags), true, parameters);
            const expanded = ts.createSourceFile('json-input.ts', `type JsonInput = ${projected};`, ts.ScriptTarget.ES2022, true).statements[0].type;
            // These nodes belong to a different source; detach their positions
            // before the enclosing declaration is printed against its source.
            const synthesize = child => ts.setTextRange(ts.visitEachChild(child, synthesize, context), { pos: -1, end: -1 });
            return synthesize(expanded);
          }
          if (name === 'ProtocolObjectProjection') {
            const [shape, projection] = node.typeArguments ?? [];
            if (!shape || !ts.isTypeLiteralNode(shape) || !projection || !ts.isLiteralTypeNode(projection)) throw Error('Unexpanded composable schema');
            const index = projection.literal.text === 'input' ? 0 : 1;
            return ts.factory.createTypeLiteralNode(shape.members.map(member => {
              const selected = member.type?.typeArguments?.[index];
              if (!selected) throw Error('Unexpanded composable property');
              const types = ts.isUnionTypeNode(selected) ? selected.types : [selected];
              const defined = types.filter(n => n.kind !== ts.SyntaxKind.UndefinedKeyword);
              // ProtocolObjectProjection removes shape readonly; other authored
              // readonly members outside this projection retain their modifiers.
              return ts.factory.createPropertySignature(
                member.modifiers?.filter(modifier => modifier.kind !== ts.SyntaxKind.ReadonlyKeyword), member.name,
                defined.length !== types.length ? ts.factory.createToken(ts.SyntaxKind.QuestionToken) : member.questionToken,
                ts.visitNode(defined.length === 1 ? defined[0] : ts.factory.createUnionTypeNode(defined), visit));
            }));
          }
          if (!ts.isIdentifier(node.typeName)) throw Error(`Private schema reference: ${name}`);
          const base = input && name === 'PluginJsonValueV2' ? 'JsonValue' : renames.get(name) ?? name;
          const isReference = !builtins.has(base) && !parameters.has(base);
          // Recursive support aliases must retain the caller's projection.
          // Output aliases can contain mutable JSON while author inputs use
          // JsonValue; sharing that alias silently loses nested input typing.
          const inputProjection = input && isReference && !Object.hasOwn(neutralImports, base)
            && name !== 'PluginInvocableActionId';
          const out = base;
          if (isReference) (inputProjection ? inputReferences : references).add(name === 'PluginJsonValueV2' && input ? 'JsonValue' : name);
          const arguments_ = node.typeArguments?.map(n => ts.visitNode(n, visit)) ?? [];
          if (inputProjection) arguments_.push(ts.factory.createLiteralTypeNode(ts.factory.createTrue()));
          return ts.factory.updateTypeReferenceNode(node, ts.factory.createIdentifier(out), arguments_.length ? arguments_ : undefined);
        }
        if (ts.isImportTypeNode(node) || ts.isTypeQueryNode(node)) throw Error(`Private schema projection: ${node.getText(file)}`);
        return ts.visitEachChild(node, visit, context);
      };
      return root => ts.visitNode(root, visit);
    }]);
    try { return printer.printNode(ts.EmitHint.Unspecified, transformed.transformed[0], file); }
    finally { transformed.dispose(); }
  };
  const render = (symbol, outputName = renames.get(symbol.name) ?? symbol.name, input = false, projectedType) => {
    if (declarations.has(outputName)) return;
    declarations.set(outputName, '');
    const type = projectedType ?? checker.getDeclaredTypeOfSymbol(symbol);
    const declaration = symbol.declarations?.find(n => ts.isTypeAliasDeclaration(n) || ts.isInterfaceDeclaration(n));
    const parameters = new Set(declaration?.typeParameters?.map(n => n.name.text));
    const parameterText = declaration?.typeParameters?.length ? `<${declaration.typeParameters.map(n => n.getText()).join(', ')}>` : '';
    // The checker prints a named interface as its own name. Preserve its
    // canonical heritage and members instead of emitting a circular alias.
    if (declaration && ts.isInterfaceDeclaration(declaration)) {
      const heritage = declaration.heritageClauses?.flatMap(clause => clause.types.map(node => normalize(node.getText(), input, parameters))) ?? [];
      const body = normalize(`{ ${declaration.members.map(node => node.getText()).join('\n')} }`, input, parameters);
      declarations.set(outputName, `export interface ${outputName}${parameterText}${heritage.length ? ' extends ' + heritage.join(', ') : ''} ${body}\n`);
      return;
    }
    const text = normalize(checker.typeToString(type, undefined, flags), input, parameters);
    declarations.set(outputName, `export type ${outputName}${parameterText} = ${text};\n`);
  };
  for (const [path, name, outputName, input] of bindings) {
    const symbol = symbolIn(path, name);
    if (keys && /PluginAction(Input|Result)ById/u.test(name)) {
      const type = checker.getDeclaredTypeOfSymbol(symbol);
      const properties = checker.getPropertiesOfType(type);
      if (JSON.stringify(properties.map(n => n.name).sort()) !== JSON.stringify([...keys].sort())) throw Error('Canonical family key mismatch');
      for (const property of properties) {
        const value = checker.getTypeOfSymbolAtLocation(property, property.valueDeclaration ?? property.declarations?.[0] ?? program.getSourceFile(actionSpecs));
        if (value.flags & (ts.TypeFlags.Any | ts.TypeFlags.Unknown | ts.TypeFlags.Never)) {
          const diagnostics = program.getSemanticDiagnostics();
          throw Error(`Nonconcrete Action ${property.name}: ${checker.typeToString(value)}\n`
            + ts.formatDiagnosticsWithColorAndContext(diagnostics, { getCurrentDirectory: () => repoRoot, getCanonicalFileName: path => path, getNewLine: () => '\n' }));
        }
      }
    }
    let projectedType;
    if (name === 'PluginDeclarativeComposerApplyEffectV1') {
      const schema = symbolIn(path, name + 'Schema');
      const location = schema.valueDeclaration ?? schema.declarations[0];
      const output = checker.getPropertyOfType(checker.getTypeOfSymbolAtLocation(schema, location), '_output');
      if (!output) throw Error('Missing canonical declarative effect schema output');
      projectedType = checker.getTypeOfSymbolAtLocation(output, location);
    }
    render(symbol, outputName ?? renames.get(name) ?? name, input, projectedType);
  }
  if (!keys) for (const name of extraNames) references.add(name);
  if (!keys) for (const name of extraInputNames) inputReferences.add(name);
  for (const name of references) {
    if (Object.hasOwn(neutralImports, name) || name === 'PluginInvocableActionId') continue;
    // Family dependencies live in the one generated support module; its own
    // derivation closes these canonical aliases rather than copying old DTOs.
    if (keys) continue;
    render(findSymbol(name), renames.get(name) ?? name);
  }
  for (const name of inputReferences) {
    if (keys) continue;
    render(findSymbol(name), renames.get(name) ?? name);
    render(findSymbol(name), `${renames.get(name) ?? name}Input`, true);
  }
  if (!keys) for (const name of inputReferences) {
    const base = renames.get(name) ?? name;
    const output = ts.createSourceFile('output.ts', declarations.get(base), ts.ScriptTarget.ES2022, true).statements[0];
    const inputName = `${base}Input`;
    const projected = ts.createSourceFile('input.ts', declarations.get(inputName), ts.ScriptTarget.ES2022, true).statements[0];
    if (!ts.isTypeAliasDeclaration(output) || !ts.isTypeAliasDeclaration(projected)) throw Error(`Input support projection needs a type alias: ${name}`);
    const combined = ts.factory.updateTypeAliasDeclaration(output, output.modifiers, output.name,
      [...(output.typeParameters ?? []), ts.factory.createTypeParameterDeclaration(undefined, 'Input',
        ts.factory.createKeywordTypeNode(ts.SyntaxKind.BooleanKeyword), ts.factory.createLiteralTypeNode(ts.factory.createFalse()))],
      ts.factory.createConditionalTypeNode(ts.factory.createTypeReferenceNode('Input'),
        ts.factory.createLiteralTypeNode(ts.factory.createTrue()), projected.type, output.type));
    declarations.set(base, printer.printNode(ts.EmitHint.Unspecified, combined, undefined) + '\n');
    declarations.delete(inputName);
  }
  return { declarations: [...declarations], references: [...references], inputReferences: [...inputReferences],
    inputDigests: [...inputs].map(([path, text]) => [path, createHash('sha256').update(text).digest('hex')]),
    ...session.metrics, programMs, projectionMs: performance.now() - projectionStart,
    maxRssKiB: process.resourceUsage().maxRSS };
}

function collectIdentifiers(node) {
  const names = new Set();
  const visit = child => {
    if (ts.isIdentifier(child)) {
      const parent = child.parent;
      if (!(parent && ((ts.isPropertyAccessExpression(parent) && parent.name === child)
        || ((ts.isPropertyAssignment(parent) || ts.isPropertySignature(parent) || ts.isMethodDeclaration(parent)) && parent.name === child)))) names.add(child.text);
    }
    ts.forEachChild(child, visit);
  };
  visit(node);
  return [...names];
}

async function worker(request) {
  const directory = mkdtempSync(resolve(tmpdir(), 'happier-action-schema-'));
  try {
    const input = resolve(directory, 'request.json');
    const output = resolve(directory, 'result.json');
    writeFileSync(input, JSON.stringify(request));
    const run = await runCommand(process.execPath, [SCRIPT, input, output], {
      stdio: ['ignore', 'inherit', 'inherit'], ownedProcessGroup: true,
    });
    if (run.error) throw run.error;
    if (run.status !== 0) throw Error(`Action schema family failed (${run.status ?? run.signal})`);
    return JSON.parse(readFileSync(output, 'utf8'));
  } finally { rmSync(directory, { recursive: true, force: true }); }
}

export async function deriveActionDtoSchemas({ repoRoot, recordInput = () => {}, recordDigest = () => {}, onlyFamilies,
  inputSnapshot = captureActionSchemaInputs(repoRoot) } = {}) {
  const directory = mkdtempSync(resolve(tmpdir(), 'happier-action-inputs-'));
  try {
    const inputSnapshotPath = resolve(directory, 'inputs.json');
    writeFileSync(inputSnapshotPath, JSON.stringify([...inputSnapshot]));
    return await deriveSnapshot({ repoRoot, recordInput, recordDigest, onlyFamilies, inputSnapshot, inputSnapshotPath });
  } finally { rmSync(directory, { recursive: true, force: true }); }
}

async function deriveSnapshot({ repoRoot, recordInput, recordDigest, onlyFamilies, inputSnapshot, inputSnapshotPath }) {
  const protocol = resolve(repoRoot, 'packages/protocol/src');
  const { families, familyOwners, excluded } = readActionCatalog(repoRoot, recordInput, path => inputSnapshot.get(path));
  const selectedFamilies = Object.entries(families).flatMap(([family, ids]) => {
    if (onlyFamilies && !onlyFamilies.includes(family)) return [];
    const keys = ids.filter(id => !Object.hasOwn(excluded, id));
    if (!keys.length) return [];
    const stem = family === 'computer' ? 'computerControl' : family.replace(/_([a-z])/gu, (_, letter) => letter.toUpperCase());
    const familyNames = ['Input', 'Result'].map(kind => stem[0].toUpperCase() + stem.slice(1) + `Action${kind}ById`);
    return [{ family, keys, familyNames, path: resolve(dirname(familyOwners[family]), `${stem}ActionDtos.ts`) }];
  });
  const requests = selectedFamilies.map(({ keys, familyNames }) => ({
    keys, bindings: familyNames.map((name, i) => ['actions/actionSpecs.ts', `PluginAction${i ? 'Result' : 'Input'}ById`, name, i === 0]),
  }));
  const results = [];
  if (requests.length) {
    // Amortize each host over a core-sized batch, with at most one host per
    // available core. Sequential custody preserves the existing memory topology;
    // exiting a batch releases its checkers instead of retaining all families.
    const cores = availableParallelism();
    const hosts = Math.min(cores, Math.ceil(requests.length / cores));
    const perHost = Math.ceil(requests.length / hosts);
    for (let index = 0; index < requests.length; index += perHost) {
      const batch = await worker({ repoRoot, inputSnapshotPath, requests: requests.slice(index, index + perHost) });
      for (const [path, digest] of batch.inputDigests) recordDigest(path, digest);
      results.push(...batch.results);
    }
  }
  const outputs = new Map();
  const names = [[], []];
  const imports = [];
  const dependencies = new Set();
  const inputDependencies = new Set();
  const metrics = [];
  const consume = (label, result, elapsedMs) => {
    for (const [path, digest] of result.inputDigests) recordDigest(path, digest);
    metrics.push({ family: label, elapsedMs: Math.round(elapsedMs), maxRssKiB: result.maxRssKiB,
      sourceFilesParsed: result.sourceFilesParsed, sourceFilesReused: result.sourceFilesReused,
      parseMs: Math.round(result.parseMs), programMs: Math.round(result.programMs), projectionMs: Math.round(result.projectionMs) });
    process.stderr.write(`action-type-map: family=${label} elapsedMs=${metrics.at(-1).elapsedMs} maxRssKiB=${result.maxRssKiB}\n`);
    return result;
  };
  const supportPath = resolve(protocol, 'actions/pluginActionDtoSupport.ts');
  const relativeImport = (from, to) => {
    const path = relative(dirname(from), to).replaceAll('\\', '/').replace(/\.ts$/u, '.js');
    return path.startsWith('.') ? path : './' + path;
  };
  for (const [index, { family, familyNames, path }] of selectedFamilies.entries()) {
    // Virtual declarations follow the defining family export; only their SDK
    // projection is published. A newly declared family needs no placement list.
    const derived = results[index];
    const result = consume(family, derived, derived.elapsedMs);
    const local = new Set(result.declarations.map(([name]) => name));
    const refs = result.references.filter(name => !local.has(name));
    const inputRefs = result.inputReferences;
    refs.forEach(name => dependencies.add(name));
    inputRefs.forEach(name => inputDependencies.add(name));
    const refNames = refs.map(name => [...supportBindings, ...uiBindings].find(([, canonical]) => canonical === name)?.[2] ?? name);
    refNames.push(...inputRefs.map(name => [...supportBindings, ...uiBindings].find(([, canonical]) => canonical === name)?.[2] ?? name));
    outputs.set(path, GENERATED_HEADER
      + (refNames.length ? `import type { ${[...new Set(refNames)].sort().join(', ')} } from '${relativeImport(path, supportPath)}';\n` : '')
      + result.declarations.map(([, text]) => text).join('\n'));
    imports.push(`import type { ${familyNames.join(', ')} } from '${relativeImport(resolve(protocol, 'actions/pluginActionDtos.ts'), path)}';`);
    familyNames.forEach((name, i) => names[i].push(name));
  }
  if (!onlyFamilies) {
    const start = performance.now();
    const support = consume('support', await worker({ repoRoot, inputSnapshotPath, bindings: [...supportBindings, ...uiBindings], extraNames: [...dependencies], extraInputNames: [...inputDependencies] }),
      performance.now() - start);
    for (const name of dependencies) {
      const renamed = [...supportBindings, ...uiBindings].find(([, canonical]) => canonical === name)?.[2] ?? name;
      if (!support.declarations.some(([candidate]) => candidate === renamed) && !Object.hasOwn(neutralImports, name) && name !== 'PluginInvocableActionId') {
        throw Error(`Missing generated support dependency: ${name}`);
      }
    }
    for (const name of inputDependencies) {
      const renamed = [...supportBindings, ...uiBindings].find(([, canonical]) => canonical === name)?.[2] ?? name;
      if (!support.declarations.some(([candidate]) => candidate === renamed)) throw Error(`Missing generated input support dependency: ${name}`);
    }
    const neutralImportStatements = Object.entries(neutralImports).map(([name, path]) =>
      `import type { ${name === 'PluginJsonSchema' ? 'PluginJsonSchemaV2 as PluginJsonSchema' : name} } from '${relativeImport(supportPath, resolve(protocol, path))}';`);
    outputs.set(supportPath, GENERATED_HEADER + neutralImportStatements.join('\n') + "\nimport type { PluginInvocableActionId } from './pluginActionDtos.js';\n"
      + support.declarations.filter(([name]) => !Object.hasOwn(neutralImports, name)).map(([, text]) => text).join('\n')
      + `\nexport type { ${Object.keys(neutralImports).join(', ')}, PluginInvocableActionId };\n`);
    const indexPath = resolve(protocol, 'actions/pluginActionDtos.ts');
    const exportNames = [...supportBindings.map(([, name, out]) => out ?? name),
      ...['JSONType'].filter(name => support.declarations.some(([candidate]) => candidate === name))];
    outputs.set(indexPath, GENERATED_HEADER + imports.join('\n') + '\n'
      + `import type { ${exportNames.map(name => `${name} as Dto${name}`).join(', ')} } from './pluginActionDtoSupport.js';\n`
      + exportNames.map(name => `export type ${name} = Dto${name};`).join('\n') + '\n'
      + names.map((families, i) => `export type PluginAction${i ? 'Result' : 'Input'}ById = ${families.join(' & ')};`).join('\n')
      + '\nexport type PluginInvocableActionId = keyof PluginActionInputById;\n');
    // The former hand-authored UI grammar becomes a type-only re-export of
    // this producer's canonical schema closure, preserving existing imports.
    const uiNames = uiBindings.map(([, name, out]) => out ?? name);
    outputs.set(resolve(protocol, 'plugins/contributions/ui/actionDeclarativeNodeDto.ts'), GENERATED_HEADER
      + `import type { ${uiNames.map(name => `${name} as Dto${name}`).join(', ')} } from '../../../actions/pluginActionDtoSupport.js';\n`
      + uiNames.map(name => `export type ${name} = Dto${name};`).join('\n')
      + "\nexport type PluginUiAttachmentToneV1 = NonNullable<DtoComposerAttachmentAuthorPresentationV1['tone']>;\n");
  }
  return { outputs, metrics };
}

function deriveFamilyBatch({ repoRoot, requests }, session) {
  const inputDigests = new Map();
  const results = requests.map(request => {
    const start = performance.now();
    const { inputDigests: observed, ...result } = deriveProgram({ repoRoot, ...request }, session);
    for (const [path, digest] of observed) {
      if (inputDigests.has(path) && inputDigests.get(path) !== digest) throw Error(`Action schema inputs changed between families: ${path}`);
      inputDigests.set(path, digest);
    }
    return { ...result, inputDigests: [], elapsedMs: performance.now() - start };
  });
  return { results, inputDigests: [...inputDigests] };
}

